import { libraryBooks } from "@/lib/parent-queries";
import { LibraryView } from "./LibraryView";

/**
 * «Библиотека» — веб-порт apps/mobile-parent/src/screens/study/LibraryScreen.tsx.
 *
 * Данные НАСТОЯЩИЕ: таблица `books` (в демо-школе 11 книг) плюс отметки
 * `book_favorites` выбранного ребёнка — те же, что видит сам ученик.
 *
 * ФАЙЛ ОТКРЫВАЕТСЯ (12.08.2026). Раньше кнопки не было: я решил, что после
 * миграций 188/189 старые пути без префикса школы стали невидимы. Это
 * оказалось не так — миграция 188 отдельным условием оставляет такие пути
 * видимыми членам ДЕМО-школы, а все 11 книг как раз демо-школьные и лежат на
 * старых путях. Проверено действием под правами самого родителя: все 11
 * подписались и отдали байты. Поэтому ничего никуда не переносится, а кнопка
 * зовёт то же серверное действие `getBookFileUrl`, которым открывают книгу
 * ученик и учитель — второй копии подписывания не заводится.
 *
 * Пометка «файла нет» по-прежнему приходит из данных: у книги может не быть
 * ни файла, ни внешней ссылки.
 */
export default async function ParentLibraryPage() {
  const books = await libraryBooks();
  return <LibraryView books={books} />;
}
