import { listPublicSchools } from "@/lib/public-schools";
import { LoginScreen } from "./LoginScreen";

/**
 * Экран входа. СЕРВЕРНЫЙ компонент — стал им 19.08.2026, и вот зачем.
 *
 * ЧТО ЧИНИМ. На первом кадре стоял заголовок «Вход в кабинет», а через секунду
 * с лишним он подменялся логотипом школы и её названием. Школа запомнена в
 * памяти браузера, а память читается только после того, как выполнится весь
 * фронтовый код, — до этого страница про школу не знала ничего и показывала
 * общий заголовок. Смена смысла на глазах у человека: сперва «просто вход»,
 * потом «вход в такую-то школу».
 *
 * ЧТО СДЕЛАНО. Список школ теперь приезжает в готовом HTML — страница берёт
 * его при сборке, до всякого браузера. Дальше два случая, и оба без мелькания:
 *
 *   ШКОЛА В УСТАНОВКЕ ОДНА (нынешний рабочий путь). Выбирать не из чего, и
 *   сервер подставляет её сам. Логотип, название и «Сменить школу» стоят в
 *   HTML с первого кадра — подменять потом нечего, состояние ровно одно.
 *
 *   ШКОЛ НЕСКОЛЬКО. Какую помнит ЭТОТ браузер, сервер знать не может: HTML
 *   один на всех, он лежит в кэше края. Поэтому сервер не угадывает и не
 *   подставляет чужой заголовок, а рисует место под школу — рамку логотипа и
 *   полосу под название (см. LoginForm). Когда браузер прочтёт память, место
 *   заполнится. Смысл кадра не меняется: «здесь будет школа» становится
 *   школой.
 *
 * ПОЧЕМУ НЕ ЧЕРЕЗ COOKIE. Cookie сервер прочитал бы и подставил школу сразу
 * даже при двадцати школах — но страница с cookie перестаёт быть кэшируемой
 * на краю: на каждый заход поднималась бы функция в Гонконге. Скорость
 * карточки только что починена (18.08.2026, коммит 4ee4136), и разменивать её
 * на исчезновение полусекундной заглушки нельзя.
 *
 * ПОЧЕМУ СТРАНИЦА ОСТАЛАСЬ КЭШИРУЕМОЙ. revalidate ниже, никаких cookies() и
 * headers(): страница по-прежнему собирается заранее и отдаётся из кэша края
 * целиком. Обращения к базе на заходе человека нет — оно происходит раз в пять
 * минут при обновлении страницы, а не при каждом открытии.
 */

// Пять минут — те же, что у /api/public/schools, и намеренно те же: два места
// отдают один список, и рассинхронизация выглядела бы как «в окне школа есть, а
// в шапке нет». Ссылка на логотип подписана на час, поэтому за пять минут
// протухнуть не успевает; на случай, когда страница всё же залежалась в кэше
// дольше часа (ночь без заходов), в SchoolMark стоит откат на буквы названия.
export const revalidate = 300;

export default async function LoginPage() {
  // null означает «не удалось спросить» и обрабатывается не как пустой список:
  // разбор в lib/public-schools.ts. Здесь просто передаётся дальше.
  const initialSchools = await listPublicSchools();

  return <LoginScreen initialSchools={initialSchools} />;
}
