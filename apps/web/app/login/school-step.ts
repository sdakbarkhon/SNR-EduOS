/**
 * Шаг «какая школа» — ОДНО правило на сервер и на браузер.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Решение «спросить школу, подставить её молча или
 * пропустить шаг» принимается теперь в двух местах: на сервере при сборке
 * страницы (там ещё неизвестно, что запомнил браузер) и в браузере после
 * загрузки (там известно). Если бы правило было списано в оба места, они
 * разошлись бы на первой же правке — и человек увидел бы, как страница
 * передумывает. Поэтому правило одно, а мест вызова два.
 *
 * ФАЙЛ НАМЕРЕННО ЧИСТЫЙ: ни "use client", ни "server-only", ни обращений к
 * localStorage и к базе. Он получает список и запомненный выбор аргументами —
 * только так его может позвать и сервер, и браузер.
 */

export type PublicSchool = { id: string; name: string; logoUrl: string | null };

export type SchoolStep =
  /** Школ нет ни одной — шага не существует, сразу форма. */
  | { kind: "skip" }
  /** Выбор сделан за человека: единственная школа либо запомненная. */
  | { kind: "pick"; school: PublicSchool }
  /** Надо спросить: школ несколько, и какая нужна — неизвестно. */
  | { kind: "ask" };

/**
 * `rememberedId` — то, что лежит в памяти браузера. На сервере его знать
 * НЕОТКУДА, поэтому оттуда приходит null, и сервер честно отвечает «ask» там,
 * где браузер ответит «pick». Это не расхождение: сервер не угадывает, а
 * признаётся, что не знает, — и экран рисует место под школу, а не чужой
 * заголовок (см. LoginForm).
 *
 * Порядок проверок важен. Запомненный выбор идёт ПЕРЕД правилом единственной
 * школы: если школ стало две, а человек уже выбирал, его выбор сильнее.
 */
export function resolveSchoolStep(
  list: PublicSchool[],
  rememberedId: string | null,
): SchoolStep {
  if (list.length === 0) return { kind: "skip" };

  if (rememberedId) {
    const found = list.find((s) => s.id === rememberedId);
    // Запомненной школы может уже не быть в списке — её закрыли или убрали в
    // архив. Тогда память молча игнорируется и человека спрашивают заново.
    if (found) return { kind: "pick", school: found };
  }

  if (list.length === 1) return { kind: "pick", school: list[0]! };

  return { kind: "ask" };
}
