import { NextResponse } from "next/server";
import { listPublicSchools } from "@/lib/public-schools";
import type { PublicSchool } from "@/app/login/school-step";

// Список школ ДО входа — для экрана входа.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ПУТЬ. До входа сессии нет, а правила доступа на schools
// отдают вошедшему ровно одну строку — его собственную школу
// («authenticated reads own school»). Анонимному посетителю они не отдают
// ничего, и это правильно: список школ — не то, что должно быть открыто
// «просто так». Поэтому здесь один узкий маршрут.
//
// Что именно уходит наружу и почему — записано ОДИН раз, в
// lib/public-schools.ts. Здесь только обёртка в ответ.
//
// 19.08.2026 — САМА СТРАНИЦА ВХОДА ЭТОТ МАРШРУТ БОЛЬШЕ НЕ ЖДЁТ: список
// приезжает в готовом HTML (app/login/page.tsx). Маршрут остался нужен для
// двух случаев: человек открыл окно по «Сменить школу» уже после загрузки, и
// сборка страницы прошла без списка (сети не было) — тогда браузер
// переспрашивает. Удалять его нельзя.
//
// 18.08.2026 — было force-dynamic, и каждый заход стоил полного круга: запрос
// к базе плюс подпись ссылок на логотипы. Замер в браузере — 3510 мс на
// холодном первом запросе. Список школ меняется раз в месяц, а ссылка на
// логотип подписана на час, поэтому пять минут кэша безопасны: подпись не
// успеет протухнуть, а новая школа появится через пять минут после создания.
export const revalidate = 300;

export async function GET() {
  const list = await listPublicSchools();

  // Не удалось — пустой список, а не 500: экран входа обязан открыться в любом
  // случае. Как он поступает с пустым списком — см. school-step.ts.
  const schools: PublicSchool[] = list ?? [];

  // Пять минут кэша. Ссылка на логотип подписана на час, так что за время
  // жизни кэша протухнуть не успеет.
  return NextResponse.json({ schools }, {
    headers: { "Cache-Control": "public, s-maxage=300, stale-while-revalidate=600" },
  });
}
