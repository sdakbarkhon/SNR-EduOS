/** Сколько живёт сообщение по умолчанию. */
const СРОК_ПО_УМОЛЧАНИЮ = 5000;

export function useFlash(мс: number = СРОК_ПО_УМОЛЧАНИЮ) {
  const [flashMsg, setFlashMsg] = useState<string | null>(null);
  const таймер = useRef<ReturnType<typeof setTimeout> | null>(null);

  const flash = useCallback((msg: string) => {
    if (таймер.current) clearTimeout(таймер.current);
    setFlashMsg(msg);
    таймер.current = setTimeout(() => setFlashMsg(null), мс);
  }, [мс]);

  useEffect(() => () => { if (таймер.current) clearTimeout(таймер.current); }, []);

  return { flash, flashMsg };
}

export function FlashBanner({ msg }: { msg: string | null }) {
  if (!msg) return null;
  return (
    <div className="rounded-xl bg-emerald-50 px-4 py-3 text-sm font-medium text-emerald-700 ring-1 ring-emerald-200">
      {msg}
    </div>
  );
}
