"use client";

import { useEffect, useState, type ReactNode } from "react";
import { createPortal } from "react-dom";

/**
 * ОКНО РИСУЕТСЯ В <body>, А НЕ ВНУТРИ СОДЕРЖИМОГО СТРАНИЦЫ. 03.09.2026.
 *
 * ═══ ЧТО ЧИНИМ ════════════════════════════════════════════════════════════
 *
 * Заказчик увидел светлую полосу над затемнением: окно начиналось не от края
 * экрана. Причина в том, что `position: fixed` считается от окна браузера
 * ТОЛЬКО пока ни у одного предка нет `transform`, `filter`, `backdrop-filter`,
 * `perspective`, `contain` или `will-change` — любое из них по спеке CSS
 * делает предка «содержащим блоком», и затемнение начинает мерить свои
 * `inset-0` от него, а не от окна.
 *
 * Каркасы у нас как раз стеклянные: размытые подложки, ScaleWrapper с
 * `transform: scale()` на широких мониторах, липкая шапка с `backdrop-blur`.
 * Искать, кто именно из них виноват на конкретном экране, — работа, которую
 * пришлось бы повторять после каждой правки вёрстки.
 *
 * ПОЭТОМУ ЛЕЧИМ НЕ ПРИЧИНУ, А ЗАВИСИМОСТЬ. Окно, вынесенное порталом прямо в
 * `document.body`, не имеет над собой ни одного предка из вёрстки страницы —
 * и накрывает окно браузера целиком независимо от того, что появится в
 * каркасе завтра.
 *
 * ═══ ПОЧЕМУ ОТДЕЛЬНЫЙ КОМПОНЕНТ ═══════════════════════════════════════════
 *
 * Приём в проекте уже был: пятьдесят окон звали `createPortal` сами, каждое со
 * своей строчкой защиты от сервера. Ещё семнадцать рисовали затемнение прямо в
 * содержимом — их и переводим. Писать `createPortal` в каждом из них значило бы
 * завести семнадцатую копию одной и той же обвязки; здесь она одна.
 *
 * ═══ ПОЧЕМУ ЖДЁМ МОНТАЖА ══════════════════════════════════════════════════
 *
 * На сервере `document` не существует, а разметка страницы рисуется там.
 * Поэтому до монтажа возвращаем `null` — то же самое делают уже работающие
 * окна строкой `if (typeof document === "undefined") return null`. Разница
 * лишь в том, что здесь это написано один раз.
 *
 * ═══ ЧЕГО ЭТОТ КОМПОНЕНТ НЕ ДЕЛАЕТ ════════════════════════════════════════
 *
 * Ничего, кроме переноса. Ни z-index, ни закрытие по щелчку мимо, ни клавиша
 * выхода, ни разметка окна сюда не переезжают: у окон это устроено по-разному,
 * и свести их к одному — отдельная работа, которой никто не заказывал. Здесь
 * меняется ТОЛЬКО место отрисовки.
 *
 * ВЛОЖЕННЫЕ ОКНА. Порядок между окнами после переноса решает z-index, а не
 * вложенность в разметке. Проверено: все вложенные пары в проекте разведены
 * числами — 60 над 50 у замены плана, 10010 над 10000 у выбора файла, 50 над
 * 40 у окна успеха над загрузкой. Равных пар нет ни одной.
 */
export function ModalPortal({ children }: { children: ReactNode }) {
  const [смонтировано, setСмонтировано] = useState(false);
  useEffect(() => setСмонтировано(true), []);
  if (!смонтировано || typeof document === "undefined") return null;
  return createPortal(children, document.body);
}
