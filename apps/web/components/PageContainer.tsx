import type { ReactNode } from "react";
import { cn } from "@/lib/cn";

/**
 * Общий контейнер контента страницы — max-w-[1920px] (та же финальная
 * целевая ширина, что даёт сам каркас TeacherShell/AppShell) + центрирование
 * + горизонтальный паддинг. На 1920 и уже — контент как раньше, шире —
 * центрируется без растяжения (было 1600, изменено по решению пользователя).
 * Раньше почти каждый экран заново изобретал свой max-w (3xl/5xl/6xl/7xl) —
 * контент не дотягивал до ширины, которую уже разрешает каркас, оставляя
 * пустые поля на 2560+/3440+ (Адаптив, заход 2). Не для ВСЕХ экранов — там,
 * где узкая читаемая колонка нужна специально (например текстовые описания),
 * max-w подбирается локально, без этого компонента.
 */
export function PageContainer({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cn("mx-auto w-full max-w-[1920px] px-4 sm:px-6 lg:px-8", className)}>{children}</div>;
}
