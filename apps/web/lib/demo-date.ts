// дата исправлена 06.08.2026 (см. ниже).
//
// Раньше — переключаемая демо-заморозка через NEXT_PUBLIC_DEMO_FROZEN_DATE
// (полдень Ташкента, нейтральная точка суток). По решению заказчика
// заморозка теперь навсегда, тумблер больше не нужен — хардкод-константа
// вместо env var. Якорь — 10:50 Ташкент, а не полдень: это стык 2-го и 3-го
// урока (правило "1-completed / 2-in_progress / 3+ ручной старт" встаёт
// естественно — 1-й урок уже завершён, 2-й уже идёт, 3-й ещё не активирован).
//
// 06.08.2026 — якорь переставлен с 29.07 на 01.08 (время 10:50 сохранено).
// Причина: на 29.07 живая БД держит ВСЕ 18 уроков в статусе completed —
// демо открывалось на дне без единого живого урока, ровно против цели
// заморозки. Правило реально выполняется только на 01.08: у каждой из 3
// групп 09:00 completed, 09:55 in_progress, 10:50+ scheduled (3/3/12 по
// школе). Статусы уроков — данные, не вычисляются от времени, поэтому
// подвинут был якорь, а не данные (см. resheniya_2.md 06.08).
//
// getDemoNow()/getDemoNowMs() безопасны и в клиентских, и в серверных
// компонентах (чистая константа, без window/document) — используются
// только в UI-слое (компоненты фронтенда) и SSR/server actions/API routes,
// куда их явно прокинули (см. resheniya_2.md) — НЕ в БД (updated_at/
// created_at пишутся реальным Postgres now()).

const FROZEN_AT_ISO = "2026-08-01T10:50:00+05:00"; // = 2026-08-01T05:50:00.000Z

export function getDemoNow(): Date {
  return new Date(FROZEN_AT_ISO);
}

export function getDemoNowMs(): number {
  return getDemoNow().getTime();
}

export function isDemoMode(): boolean {
  return true;
}
