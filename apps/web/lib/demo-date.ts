//   * 06.08 позже — вернули на 29.07 и вместо этого пересчитали САМИ
//     СТАТУСЫ (apps/web/scripts/fix-lesson-statuses-frozen-week.mjs).
//     Причины отката: заказчику нужна среда, суббота как демо-день выглядит
//     странно; и 01.08 всё равно дрейфовал — живой демо-пользователь за
//     полдня сдвинул его с 3/3/12 на 4/2/12, то есть «найти удачный день»
//     не является устойчивым решением само по себе.
//   * 07.08 — сдвинули 10:50 → 10:15 (см. абзац «почему середина» выше).
