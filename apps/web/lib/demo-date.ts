// то нет, а подсветка в расписании уезжала на два урока вперёд. В 10:15 ни
// один урок не начинается и не заканчивается, поэтому знак сравнения
// перестаёт что-либо решать. Не возвращать якорь на границу слота.
//
// История даты (важно, чтобы не сделать четвёртый круг):
//   * 05.08 — поставили 29.07 10:50.
//   * 06.08 утром — временно перевели на 01.08, потому что в БД на 29.07 все
//     18 уроков лежали completed (демо-день без единого живого урока), а
//     форма 1/2/3+ фактически существовала только на 01.08. Правили якорь,
