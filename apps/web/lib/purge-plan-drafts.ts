/**
 * УБОРКА И СТОРОЖ ЗАКАЗОВ НА РАЗБОР УЧЕБНИКА. 06.09.2026.
 *
 * ═══ ЗАЧЕМ ═════════════════════════════════════════════════════════════════
 *
 * Заказ живёт тридцать дней (решение заказчика) и уносит с собой свой файл.
 * Без этого бакет `curriculum-plans` копил бы файлы вечно — он и так уже
 * болен: пять файлов, четыре из них не привязаны ни к чему. Заводить второй
 * источник сирот нельзя.
 *
 * ═══ ПОЧЕМУ В ДВА ХОДА ════════════════════════════════════════════════════
 *
 * SQL до хранилища не дотягивается. Поэтому функция базы удаляет строки и
 * ВОЗВРАЩАЕТ пути их файлов, а сносит файлы уже этот код. Порядок именно
 * такой: сначала строки, потом файлы. Обратный порядок при обрыве оставил бы
 * строку с путём в никуда — а это ложь на экране: «файл готов», а его нет.
 *
 * Наш порядок при обрыве оставляет файл без строки. Он никому не виден, но и
 * сам уже не уйдёт: строки, по которой его нашли бы, больше нет. Поэтому
 * такие пути ПИШУТСЯ В ЛОГ поимённо — сирота должна быть названа вслух, а не
 * тихо осесть в бакете, как осели четыре нынешних.
 *
 * ═══ СВОЯ ОШИБКА КРОН НЕ РОНЯЕТ ═══════════════════════════════════════════
 *
 * Уборка едет прицепом к чужому крону и не имеет права его валить. Всё, что
 * может пойти не так, пишется в лог и возвращается числом.
 */

/* eslint-disable @typescript-eslint/no-explicit-any */

export type ИтогУборки = {
  /** Сколько заказов удалено. */
  заказов: number;
  /** Сколько файлов снесено из хранилища. */
  файлов: number;
  /** Пути, которые удалить не вышло: строки уже нет, файл остался. */
  осиротело: string[];
};

export async function убратьПросроченныеЗаказы(db: any): Promise<ИтогУборки> {
  const итог: ИтогУборки = { заказов: 0, файлов: 0, осиротело: [] };
  try {
    const { data, error } = await db.rpc("fn_purge_expired_plan_drafts");
    if (error) throw new Error(error.message);

    const пути = ((data ?? []) as Array<{ result_path: string | null } | string>)
      .map((r) => (typeof r === "string" ? r : r.result_path))
      .filter((p): p is string => Boolean(p));
    // Строк могло уйти больше, чем файлов: у отказавших заказов файла нет.
    итог.заказов = (data ?? []).length;

    if (пути.length > 0) {
      const { error: rmErr } = await db.storage.from("curriculum-plans").remove(пути);
      if (rmErr) {
        итог.осиротело = пути;
        console.error("[purge-plan-drafts] файлы удалить не вышло:", rmErr.message, пути.join(", "));
      } else {
        итог.файлов = пути.length;
      }
    }
    if (итог.заказов > 0) {
      console.log(`[purge-plan-drafts] убрано заказов ${итог.заказов}, файлов ${итог.файлов}`);
    }
  } catch (e) {
    console.error("[purge-plan-drafts] уборка не отработала:", (e as Error)?.message);
  }
  return итог;
}


/** Сколько заказов добито и сколько занятых ими файлов снесено. */
export type ИтогСторожа = {
  /** Сколько зависших заказов переведено в отказ. */
  заказов: number;
  /** Сколько занятых ими мест снесено из хранилища. */
  файлов: number;
};

/**
 * СТОРОЖ ЗАВИСШИХ ЗАКАЗОВ. Едет тем же прицепом, что и уборка выше.
 *
 * ═══ ЧТО ЛЕЧИТ ════════════════════════════════════════════════════════════
 *
 * Фон ставит заказу 'running' первым шагом, а 'done' либо 'failed' — последним.
 * Убьют процесс между этими точками (потолок времени, перезапуск инстанса,
 * обрыв) — и заказ остаётся 'running' навсегда: первая кнопка у учителя гаснет
 * насовсем, уникальный индекс держит четвёрку занятой, а место под файл лежит
 * в бакете сиротой. Снять это из браузера нечем — правил записи у таблицы для
 * него нет вовсе.
 *
 * ═══ ПОЧЕМУ ФАЙЛ СНОСИТСЯ ПО ВЫЧИСЛЕННОМУ ПУТИ ════════════════════════════
 *
 * `result_path` у зависшего пуст: он проставляется вместе с «готово». Но путь
 * занятого места известен заранее по соглашению — его и возвращает функция
 * базы. Файла может не быть вовсе (не дошли до брони) — хранилище на такой
 * снос не ругается, и это нормальный, а не исключительный случай.
 *
 * Как и уборка: своя беда пишется в лог и не роняет крон.
 */
export async function добитьЗависшиеЗаказы(db: any): Promise<ИтогСторожа> {
  const итог: ИтогСторожа = { заказов: 0, файлов: 0 };
  try {
    // Срок берётся умолчанием функции — десять минут. Второго числа в коде
    // не заводим: пусть срок живёт в одном месте, в самой функции.
    const { data, error } = await db.rpc("fn_fail_stuck_plan_drafts");
    if (error) throw new Error(error.message);

    const строки = (data ?? []) as Array<{ id: string; "брошенный_файл": string | null }>;
    итог.заказов = строки.length;
    if (итог.заказов === 0) return итог;

    const пути = строки.map((r) => r["брошенный_файл"]).filter((p): p is string => Boolean(p));
    if (пути.length > 0) {
      const { data: снесено, error: rmErr } = await db.storage.from("curriculum-plans").remove(пути);
      if (rmErr) {
        console.error("[stuck-plan-drafts] занятые места снести не вышло:", rmErr.message, пути.join(", "));
      } else {
        // Хранилище возвращает только те, что реально были: у заказа, не
        // дошедшего до брони, файла нет, и это не ошибка.
        итог.файлов = (снесено ?? []).length;
      }
    }
    console.warn(`[stuck-plan-drafts] добито зависших заказов ${итог.заказов}, снесено занятых мест ${итог.файлов}`);
  } catch (e) {
    console.error("[stuck-plan-drafts] сторож не отработал:", (e as Error)?.message);
  }
  return итог;
}
