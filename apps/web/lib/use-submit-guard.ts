"use client";

import { useCallback, useRef, type TransitionStartFunction } from "react";

/**
 * Z.2.9 — защита от двойной отправки формы.
 *
 * Кнопки в админке и так гаснут по `isPending` из `useTransition`, но между
 * кликом и перерисовкой есть окно: обработчик уже начал работу, а атрибут
 * `disabled` ещё не проставлен. Быстрый двойной клик (и нетерпеливый двойной
 * тап на телефоне) успевает пройти дважды — и создаются две записи.
 *
 * Блокировка живёт в ref, а не в состоянии: она встаёт в тот же тик, что и
 * первый вызов, до всякого рендера. Снимается, когда работа завершилась —
 * успехом или ошибкой, иначе форма залипла бы после первой же неудачи.
 *
 * Идемпотентные действия (редактирование, переключатели) в этом не нуждаются
 * — повтор там ничего не портит; оборачиваем только создание.
 *
 * ═══ 03.09.2026 — ОН НЕ РАБОТАЛ. ВООБЩЕ НИГДЕ ════════════════════════════
 *
 * Прежняя подпись была `(fn: () => void | Promise<void>) => void`, и все
 * четыре места звали её одинаково:
 *
 *     guard(() => startTransition(async () => { ...работа... }))
 *
 * `startTransition` возвращает `undefined`. Значит проверка «а не обещание
 * ли нам вернули» не срабатывала, и замок снимался ветвью `else` — СИНХРОННО,
 * в том же тике, не дождавшись ни единого запроса. К моменту, когда
 * обработчик клика возвращал управление, `busy` уже снова был `false`.
 *
 * То есть комментарий обещал «второй клик до перерисовки больше не создаёт
 * вторую запись», а код этого не делал ни в одном из четырёх мест: создание
 * группы, ученика, учителя и родителя.
 *
 * ═══ ПОЧЕМУ ПОДПИСЬ ПОМЕНЯЛАСЬ ═══════════════════════════════════════════
 *
 * Чинить было можно двумя способами. Первый — оставить подпись и научить
 * каждое место возвращать обещание, обернув startTransition в new Promise.
 * Это четыре одинаковых куска в четырёх файлах, то есть ровно та «копия»,
 * которая в этом проекте расходилась уже семь раз.
 *
 * Второй, выбранный: мост между `startTransition` (он ничего не возвращает)
 * и замком (ему нужно дождаться) живёт ЗДЕСЬ, в одном месте. Вызывающие
 * отдают и то и другое, а как их поженить — забота этого файла.
 *
 * Поведение `isPending` при этом не изменилось ни на йоту: в переход
 * по-прежнему уходит та же самая асинхронная функция, что и раньше.
 */
export function useSubmitGuard(): (
  start: TransitionStartFunction,
  work: () => Promise<void>,
) => void {
  const busy = useRef(false);

  return useCallback((start: TransitionStartFunction, work: () => Promise<void>) => {
    if (busy.current) return;
    busy.current = true;
    start(async () => {
      try {
        await work();
      } finally {
        // finally, а не хвост try: отказ действия обязан отпустить замок,
        // иначе после первой же ошибки форму нельзя отправить повторно.
        busy.current = false;
      }
    });
  }, []);
}
