import { createAdminClient } from "@/lib/supabase/admin";

/**
 * ШКОЛЫ, В КОТОРЫХ ЧЕЛОВЕК РАБОТАЕТ. Только для сервера. 06.09.2026.
 *
 * ═══ ЗАЧЕМ СЛУЖЕБНЫЙ КЛЮЧ ═════════════════════════════════════════════════
 *
 * Учителю видна РОВНО ОДНА строка `schools` — его собственное правило чтения
 * звучит `id = current_school_id()`. То есть названия ВТОРОЙ своей школы он не
 * видит, а переключателю без названия грош цена: список из двух одинаковых
 * пунктов «школа» выбором не назовёшь.
 *
 * Расширять правило ради подписи нельзя — правила закрыты вторым заходом, да и
 * незачем: тут не «показать чужое», тут «назвать своё». Поэтому имена берутся
 * служебным ключом, и берутся СТРОГО по привязкам самого человека: сначала его
 * строки `teacher_schools` с `is_active`, и лишь потом названия НАЙДЕННЫХ школ.
 * Ни одной школы сверх тех, где он числится, отсюда не выйдет.
 *
 * ═══ ЦЕНА НА КАЖДОМ ОТКРЫТИИ СТРАНИЦЫ ═════════════════════════════════════
 *
 * Шапка рисуется на каждой странице учителя, а школ у всех двенадцати сегодня
 * по одной. Поэтому первым делом считаются ПРИВЯЗКИ — один запрос, — и если
 * их меньше двух, дальше не идём вовсе: ни названий, ни выбранной школы
 * спрашивать незачем, переключателя всё равно не будет. Обычный учитель платит
 * за него один запрос, а не четыре.
 *
 * ═══ ЧТО ЗДЕСЬ НЕ РЕШАЕТСЯ ════════════════════════════════════════════════
 *
 * Какая школа выбрана СЕЙЧАС — вопрос не сюда. На него отвечает
 * `current_school_id()` под сессией человека: там и хранимый выбор, и запасной
 * ход на домашнюю школу, и проверка, что выбранная всё ещё его. Второй копии
 * этих правил в коде быть не должно, поэтому вызывающий спрашивает функцию сам
 * и передаёт ответ в переключатель.
 */

export type МояШкола = { id: string; name: string };

/**
 * Школы, между которыми человеку ЕСТЬ ЧТО переключать.
 *
 * Меньше двух привязок — пустой список: одна школа выбора не требует, и
 * называть её ради переключателя не нужно.
 */
export async function мои_школы(teacherId: string): Promise<МояШкола[]> {
  try {
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    const служебный = createAdminClient() as any;

    const { data: привязки } = await служебный
      .from("teacher_schools").select("school_id")
      .eq("teacher_id", teacherId).eq("is_active", true);
    const идентификаторы = ((привязки ?? []) as Array<{ school_id: string }>).map((r) => r.school_id);
    if (идентификаторы.length < 2) return [];

    const { data: школы } = await служебный
      .from("schools").select("id, name").in("id", идентификаторы);

    return ((школы ?? []) as МояШкола[])
      .map((s) => ({ id: s.id, name: s.name ?? "" }))
      .sort((a, b) => a.name.localeCompare(b.name, "ru"));
  } catch (e) {
    // Шапка не имеет права падать из-за переключателя: нет списка — нет и
    // переключателя, всё остальное работает как раньше.
    console.error("[мои_школы] не вышло:", (e as Error)?.message);
    return [];
  }
}
