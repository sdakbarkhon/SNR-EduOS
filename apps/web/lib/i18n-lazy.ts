import type { Dictionary, Locale } from "@snr/core";
import { defaultLocale } from "@core-i18n/runtime";
import { ru } from "@core-i18n/ru";

/**
 * Словари для БРАУЗЕРА: только активный язык, остальные — по требованию.
 *
 * ЭТОТ ФАЙЛ НЕ ИМПОРТИРУЕТСЯ ЯВНО НИ ОДНИМ ЭКРАНОМ. Он подставляется вместо
 * packages/core/src/i18n/index.ts на этапе сборки браузерного бандла —
 * см. next.config.mjs, NormalModuleReplacementPlugin. Поэтому все 175 файлов,
 * которые пишут `import { getDictionary } from "@snr/core"`, менять не
 * пришлось: они получают отсюда, сами того не зная.
 *
 * ЗАЧЕМ. Замер боевой сборки: чанк 28922-*.js — 599 447 байт распакованных,
 * 175 063 сжатых, 9 433 русских слова. Это словари ВСЕГО приложения на трёх
 * языках, и они приезжали на каждый экран. Человек всегда работает на одном
 * языке; два других — мёртвый вес в половину веса экрана входа.
 *
 * ПОЧЕМУ ПОДМЕНОЙ, А НЕ ПРАВКОЙ САМОГО packages/core. Тот же пакет собирает
 * мобильное приложение, и там ленивость ЛОМАЕТ: apps/mobile-parent берёт язык
 * телефона синхронно на первом же рендере (LocaleContext.tsx:
 * useState(detectDeviceLocale)) и сразу зовёт getDictionary. Родитель с
 * узбекским телефоном увидел бы русский, который потом ничем не заменится —
 * повторного рендера там не будет. А выигрывать в Metro нечего: разделения на
 * чанки у него нет, весь код и так в одном файле. Подмена делает браузерную
 * сборку ленивой, не трогая мобильную ни одним байтом.
 *
 * ПОЧЕМУ getDictionary ОСТАЛАСЬ СИНХРОННОЙ. Её зовут 175 файлов, включая
 * экраны, которые сейчас трогать нельзя. Асинхронная сигнатура означала бы
 * правку каждого из них. Вместо этого синхронность обеспечена порядком:
 * LocaleProvider НИКОГДА не переключает язык, пока словарь не в памяти
 * (components/LocaleProvider.tsx). То есть к моменту, когда любой компонент
 * спросит getDictionary("uz"), узбекский уже загружен.
 *
 * ДОБАВЛЯЕШЬ ЭКСПОРТ В packages/core/src/i18n/index.ts — добавь и сюда.
 * Иначе в браузере имени просто не станет.
 *
 * ПУТИ ЧЕРЕЗ АЛИАС @core-i18n/*, А НЕ ОТНОСИТЕЛЬНЫЕ, И ЭТО ОБЯЗАТЕЛЬНО.
 * Подменённый модуль webpack резолвит относительно ПАПКИ ТОГО ФАЙЛА, ЧТО
 * подменили, — то есть packages/core/src/i18n, а не lib. Относительные пути
 * отсюда уезжают не туда, сборка падает с «Can't resolve». Алиас объявлен в
 * tsconfig.json и от контекста не зависит.
 */

/** Загруженные словари. Русский — статически: это язык по умолчанию, с него
 *  начинается любая сессия (LocaleProvider стартует с "ru"), и он же остаётся
 *  запасным, если что-то пошло не так. */
const loaded: Partial<Record<Locale, Dictionary>> = { ru };

/**
 * Догрузить язык. Зовётся из LocaleProvider ПЕРЕД переключением.
 *
 * Ошибку не глотает и пустоту не возвращает: если чанк не скачался (сеть
 * отвалилась между заходами), исключение уходит наверх, вызывающий пишет его
 * в консоль и ОСТАВЛЯЕТ прежний язык. Человек видит, что язык не сменился, —
 * это честнее, чем экран с пустыми подписями или с голыми ключами.
 *
 * Импорты перечислены поимённо, а не собраны шаблоном `./${locale}`: шаблон
 * заставил бы webpack собрать контекст-модуль и затащить в него ВСЁ, что
 * лежит рядом, включая types.ts на 170 КБ. Два явных импорта — ровно два
 * отдельных чанка.
 */
export async function loadDictionary(locale: Locale): Promise<void> {
  if (loaded[locale]) return;

  switch (locale) {
    case "uz": {
      const m = await import("@core-i18n/uz");
      loaded.uz = m.uz;
      return;
    }
    case "en": {
      const m = await import("@core-i18n/en");
      loaded.en = m.en;
      return;
    }
    case "ru":
      return; // уже здесь, статически
    default: {
      // Язык, которого нет в списке. Молча подменять на русский нельзя —
      // это и есть тот самый тихий отказ, из-за которого потом ищут причину
      // неделю.
      throw new Error(`[i18n] неизвестный язык: ${String(locale)}`);
    }
  }
}

/** Загружен ли язык. Нужен LocaleProvider, чтобы не дёргать loadDictionary
 *  на каждом рендере. */
export function isDictionaryLoaded(locale: Locale): boolean {
  return Boolean(loaded[locale]);
}

export function getDictionary(locale: Locale): Dictionary {
  const d = loaded[locale];
  if (d) return d;

  // Сюда попасть не должно: LocaleProvider не переключает язык, пока словарь
  // не загружен. Но если попали — кричим в консоль и отдаём русский.
  // Русский, а не пустой объект: пустой объект превратил бы каждую подпись в
  // undefined, экран стал бы решетом из пустых мест, и никто бы не понял,
  // отчего. Неправильный язык виден сразу и чинится по этой же записи.
  console.error(
    `[i18n] словарь «${locale}» запрошен раньше, чем загружен — показан «${defaultLocale}». ` +
      `Значит, язык переключили мимо LocaleProvider. Ищи вызов setLocale вне него.`,
  );
  return loaded[defaultLocale]!;
}

/**
 * Форма прежнего экспорта сохранена, но за ней стоит проверка.
 *
 * В браузере полного набора словарей не существует по замыслу, поэтому отдать
 * честный Record нельзя. Прежде чем вернуть undefined (а его потом ищут
 * полдня), лучше упасть с внятным текстом. Ни один экран в apps/web этим
 * экспортом не пользуется — проверено поиском; ловушка стоит на будущее.
 */
export const dictionaries: Record<Locale, Dictionary> = new Proxy(
  {} as Record<Locale, Dictionary>,
  {
    get(_t, prop: string) {
      const d = loaded[prop as Locale];
      if (d) return d;
      throw new Error(
        `[i18n] dictionaries.${prop} в браузере недоступен: языки грузятся по одному. ` +
          `Используй getDictionary(locale) — он отдаёт активный язык.`,
      );
    },
  },
);

export * from "@core-i18n/runtime";
