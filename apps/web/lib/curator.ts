// 11.08.2026 — единственное место в коде, где решается «наблюдатель ли этот
// учитель». Само правило живёт в SQL (`is_curator_teacher`, миграция 187):
// куратор — это учитель БЕЗ предмета в карточке И ТОЛЬКО в демо-школе.
// В настоящих школах роли куратора нет (решение 6.1, записано в шапке блока
// назначений lib/admin-api.ts).
//
// ПОЧЕМУ ЧЕРЕЗ ВЫЗОВ БАЗЫ, А НЕ СВОЕЙ ФОРМУЛОЙ. До этого условие
// `!teacher.subject_slug` было переписано от руки в ПЯТИ местах: страница
// учебного плана, страница уроков, карточка урока, библиотека кафедры и
// выбор файлов из базы знаний. Ровно та же формула отдельно жила в
// SQL-политике видимости уроков. Шесть копий одного правила — и правило
// поменялось. Теперь формула одна, и разойтись интерфейсу с правилами
// видимости больше нечем: оба спрашивают одну и ту же функцию.
//
// ЧТО ДЕЛАЕМ ПРИ СБОЕ ВЫЗОВА: считаем, что НЕ наблюдатель. Ошибка в эту
// сторону покажет учителю кнопки, которые ему всё равно запретит база;
// ошибка в другую — спрячет работу у того, кто имеет на неё право, а это
// ровно тот симптом, который здесь и чинится.

/** Наблюдатель ли текущий учитель (куратор демо-школы). Работает и на
 *  сервере, и в браузере — принимает любой supabase-клиент. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
export async function isCuratorTeacher(db: any): Promise<boolean> {
  const { data, error } = await db.rpc("is_curator_teacher");
  if (error) {
    console.error("[curator] is_curator_teacher failed:", error.message);
    return false;
  }
  return data === true;
}

// ─────────────────────────────────────────────────────────────────────
// ВТОРОЕ ПРАВИЛО, КОТОРОЕ РАНЬШЕ ПУТАЛИ С ПЕРВЫМ.
//
// Из пяти переписанных от руки условий «пустой предмет» три были про
// наблюдателя (учебный план, список уроков, карточка урока), а два — про
// БИБЛИОТЕКУ КАФЕДРЫ: выбор файлов из базы знаний и вкладка библиотеки.
// Выглядели они одинаково только потому, что до миграции 187 оба правила
// совпадали по формуле.
//
// Теперь они разные, и подменять одно другим нельзя. Политика
// teacher_library_materials требует буквально:
//     subject_slug IS NOT NULL AND subject_slug = <мой слаг>
// то есть кафедра доступна тому, у кого предмет ЗАПОЛНЕН — независимо от
// школы. Если бы эти два места спросили isCuratorTeacher(), учитель
// настоящей школы с пустым предметом увидел бы кнопку загрузки, а база
// отбила бы файл: кнопка есть, работа не сохраняется.
// ─────────────────────────────────────────────────────────────────────

/** Может ли учитель работать с библиотекой своей кафедры. Зеркало правила
 *  вставки teacher_library_materials: нужен непустой предмет в карточке. */
export function canUseDepartmentLibrary(subjectSlug: string | null | undefined): boolean {
  return !!subjectSlug;
}
