/** Типы этапов-объяснений. Единственные, кому положена картинка. */
export const EXPLANATION_CONTENT_TYPES: ReadonlySet<string> = new Set(["presentation"]);

/** Показывать ли этому этапу картинку (и плашки её состояния). */
export function stageAllowsMedia(contentType: string | null | undefined): boolean {
  return EXPLANATION_CONTENT_TYPES.has(contentType ?? "");
}
