import "server-only";
import { createClient as createSbClient } from "@supabase/supabase-js";
import { signLogoUrl } from "@/lib/school-card";
import type { PublicSchool } from "@/app/login/school-step";

/**
 * Список школ для экрана входа — ОДНО место, откуда он берётся.
 *
 * ЗАЧЕМ ВЫНЕСЕНО ИЗ МАРШРУТА. Тот же список нужен теперь дважды: маршруту
 * /api/public/schools (его зовёт браузер, когда школу выбирают руками) и самой
 * странице входа при сборке (чтобы школа стояла в готовом HTML, а не
 * подставлялась потом). Выборка, отбор колонок и подпись логотипов не должны
 * жить в двух копиях: разойдись они — и наружу утечёт колонка, которую в одном
 * из мест забыли исключить.
 *
 * ЧТО УХОДИТ НАРУЖУ: id, название, ссылка на логотип. Всё.
 * Чего НЕ уходит и уйти не может — здесь это не «забыли», а перечислено
 * осознанно: код школы, реквизиты, адрес, телефон, почта, ФИО директора, сайт,
 * автостарт, ночное закрытие, замороженная дата, признак демо, признак архива,
 * дата создания, число учеников. Выборка перечисляет колонки поимённо (не
 * select("*")), а ответ собирается вручную полем к полю — чтобы новая колонка
 * в schools не начала утекать сама собой при следующей миграции.
 *
 * АРХИВНЫЕ И ДЕМО не отдаются: архивная школа входа не имеет вовсе
 * (миграция 202), а демо — витрина с собственной кнопкой на том же экране, и в
 * списке школ, куда человек «относится», ей не место.
 *
 * ПОЧЕМУ ЭТО НЕ ЗАЩИТА, А УДОБСТВО. Выбор школы на входе не разграничивает
 * доступ и не может: что человек увидит после входа, решают правила доступа по
 * ЕГО школе, а не по тому, что он выбрал на первом экране.
 */

/**
 * `null` означает «спросить не удалось» и НЕ ТО ЖЕ, что пустой массив.
 *
 * Разница принципиальна для экрана входа. Пустой массив — это факт: школ в
 * установке нет, шага выбора не существует, показываем форму. `null` — это
 * незнание: ключей не оказалось, база не ответила, сборка шла без сети. Во
 * втором случае экран обязан не решать за человека, а честно переспросить
 * список из браузера — иначе одна неудачная сборка тихо отключила бы выбор
 * школы для всех.
 */
export async function listPublicSchools(): Promise<PublicSchool[] | null> {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) {
    console.error("[public-schools] нет ключей Supabase");
    return null;
  }

  try {
    const sb = createSbClient(url, key, { auth: { persistSession: false } });

    const { data, error } = await sb
      .from("schools")
      .select("id, name, logo_path")
      .eq("is_active", true)
      .eq("is_demo", false)
      .order("name");

    if (error) {
      console.error("[public-schools] не удалось прочитать список:", error.message);
      return null;
    }

    const rows = (data ?? []) as Array<{ id: string; name: string; logo_path: string | null }>;

    // Ответ собирается вручную: сюда попадает только то, что перечислено.
    return await Promise.all(
      rows.map(async (s) => ({
        id: s.id,
        name: s.name,
        logoUrl: await signLogoUrl(s.logo_path),
      })),
    );
  } catch (e) {
    // Сборка может идти вообще без сети. Падать нельзя: экран входа обязан
    // собраться в любом случае, а список переспросит браузер.
    console.error("[public-schools] обращение не удалось:", e);
    return null;
  }
}
