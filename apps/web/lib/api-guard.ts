import "server-only";
import { NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

/**
 * Отказ в доступе на маршрутах API — ОДНА форма на все.
 *
 * ЗАЧЕМ ОДНО МЕСТО. 19.08.2026 разведка нашла семь маршрутов, которые меняли
 * данные или тратили деньги, не спрашивая, кто их зовёт. Закрывать их по
 * одному значило бы завести семь разных форм отказа — и по разнице между ними
 * снаружи читается, какая проверка сработала. Здесь форма одна: короткое
 * «forbidden» и статус, больше наружу не уходит ничего.
 *
 * ПОЧЕМУ НАРУЖУ НЕ ПИШЕМ ПРИЧИНУ. Причина отказа — это подсказка тому, кто
 * подбирает. «Сессии нет» и «сессия есть, но ты не родитель» — два разных
 * ответа, по которым перебирают учётные записи. Внутрь, в лог сервера,
 * причина пишется полностью: там она нужна нам и не видна никому чужому.
 *
 * ГДЕ ЭТОТ ФАЙЛ НЕ ПРИМЕНЯЕТСЯ. На маршрутах родителя
 * (/api/parent/request-code, /api/parent/verify-code). Мобильное приложение
 * знает ЗАКРЫТЫЙ список кодов ошибок — not_found, too_soon, wrong_code,
 * expired, too_many, no_account — и любой другой код показывает человеку как
 * «нет сети» (apps/mobile-parent/src/lib/parentPhoneLogin.ts:78). Отдать туда
 * «forbidden» значило бы сломать вход по телефону, а править приложение в
 * этом заходе нельзя. Там отказы остаются прежними по форме.
 */

/** Короткий отказ. Причина уходит в лог сервера, наружу — нет. */
export function denied(
  route: string,
  reason: string,
  status: 401 | 403 = 401,
): NextResponse {
  // console.warn, а не error: это не поломка, это работающая защита. Но и не
  // log — отказ должен быть заметен в выдаче Vercel, а не тонуть в шуме.
  console.warn(`[guard] ${route}: отказано (${status}) — ${reason}`);
  return NextResponse.json({ error: "forbidden" }, { status });
}

export type SignedIn =
  | { ok: true; userId: string }
  | { ok: false; response: NextResponse };

/**
 * Требует вошедшего. РОЛЬ НЕ ПРОВЕРЯЕТ — это осознанно.
 *
 * Маршруты, которые ею закрыты, отдают либо общее для всех число (счётчик
 * обращений к ИИ, обычная длительность задачи), либо факт дня. Разграничение
 * по ролям там не нужно и вредно: ученик обязан видеть свою квоту, учитель —
 * общий счётчик установки, и оба должны получить ответ. Закрывается ровно
 * одно: аноним с улицы, который сегодня получал то же самое, ничего о себе не
 * сообщив.
 */
export async function requireSignedIn(route: string): Promise<SignedIn> {
  const db = await createClient();
  const { data, error } = await db.auth.getUser();

  if (error || !data?.user) {
    return { ok: false, response: denied(route, "сессии нет", 401) };
  }
  return { ok: true, userId: data.user.id };
}
