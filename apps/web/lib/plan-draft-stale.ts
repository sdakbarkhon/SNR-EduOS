/** Сколько ждём, прежде чем считать заказ брошенным. */
export const СРОК_БРОШЕННОГО_МС = 10 * 60 * 1000;

/**
 * Брошен ли заказ, заведённый в это время.
 *
 * Считается ОТ ЗАВЕДЕНИЯ, а не от начала работы: отдельной отметки старта у
 * заказа нет, а фон запускается через секунды. Заодно это единственный способ
 * распознать заказ, оставшийся в `queued`, — до такого фон не дошёл вовсе.
 */
export function заказБрошен(createdAt: string, сейчас = Date.now()): boolean {
  const заведён = new Date(createdAt).getTime();
  if (!Number.isFinite(заведён)) return false;
  return сейчас - заведён > СРОК_БРОШЕННОГО_МС;
}

