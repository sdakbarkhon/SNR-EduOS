import type { ContentType } from "@snr/core";

export const HOMEWORK_AI_TYPES = [
  "file",
  "test",
  "programming",
  "bundle",
  "code_completion",
] as const satisfies readonly ContentType[];

export type HomeworkAiType = (typeof HOMEWORK_AI_TYPES)[number];

/** Настоящая проверка, а не приведение: сужает тип только когда значение и правда в списке. */
export function isHomeworkAiType(t: string | null | undefined): t is HomeworkAiType {
  return !!t && (HOMEWORK_AI_TYPES as readonly string[]).includes(t);
}
