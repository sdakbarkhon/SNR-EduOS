// Промт "Gemini migration" — модельная стратегия для всех AI-фич платформы.
// Flash по умолчанию (чат, короткие ответы) — Pro только там, где реально
// нужно качество (длинный контент, парсинг). См. resheniya_2.md для оценки
// экономии в долларах.
//
// gemini-2.5-pro отключён (ночной прогон, ЧАСТЬ 1): модель вернула 404 "no
// longer available to new users" — это не временный сбой квоты (как раньше
// ловил isZeroQuota() в gemini-client.ts), а структурная недоступность.
// resolveModel() теперь ВСЕГДА возвращает Flash независимо от tier — единая
// точка, через которую проходят все вызовы (generateText/generateJSON/chat/
// streamChat/generateContent), поэтому чинить каждый call site отдельно не
// нужно. AiModelTier/"pro" оставлены в типах, чтобы вызывающий код не
// пришлось трогать и чтобы Pro можно было безопасно вернуть один правкой
// здесь, если модель снова станет доступна.

export const GEMINI_MODEL_FLASH = "gemini-2.5-flash";
export const GEMINI_MODEL_PRO = "gemini-2.5-pro"; // недоступна — см. комментарий выше, не используется

export type AiModelTier = "flash" | "pro";

export function resolveModel(_tier?: AiModelTier): string {
  return GEMINI_MODEL_FLASH;
}

// Цены (USD за 1M токенов, публичный прайс Gemini API). Используются экраном
// расходов в суперадмине, чтобы посчитать деньги поверх записанных токенов.
//
// ВАЖНО ПРО ДАТУ. Числа для Flash были заведены на старте проекта и к августу
// 2026 устарели вчетверо: стояло 0.075/0.30, а платный прайс gemini-2.5-flash
// сейчас 0.30 за миллион входных и 2.50 за миллион выходных. Никакой ошибки
// это не вызывало ровно потому, что цены нигде не считались — теперь считаются,
// поэтому проверяйте их при каждом разговоре о расходах.
// Проверено и обновлено: 18.08.2026.
//
// Это ПЛАТНЫЙ прайс. Пока проект укладывается в бесплатный предел (около 1000
// обращений в сутки), фактический счёт равен нулю, а посчитанная сумма
// показывает, во сколько тот же объём обошёлся бы на платном тарифе. Именно
// поэтому на экране расходов рядом всегда стоит остаток бесплатного предела.
export const PRICING_USD_PER_1M = {
  [GEMINI_MODEL_FLASH]: { input: 0.3, output: 2.5 },
  [GEMINI_MODEL_PRO]: { input: 1.25, output: 5.0 },
  // Векторы: отдельная модель со своим прайсом, текстовых «выходных» токенов
  // у неё нет — считается только вход.
  "gemini-embedding-001": { input: 0.15, output: 0 },
  // Для сравнения — то, что мигрируем ОТ:
  "claude-sonnet-4-6": { input: 3.0, output: 15.0 },
} as const;

/** Бесплатный предел обращений в сутки (Gemini free tier). На него смотрит
 *  экран расходов: пока он не выбран, счёт нулевой. */
export const FREE_TIER_DAILY_REQUESTS = 1000;

/** Стоимость одного вызова в долларах по текущему прайсу. Неизвестная модель
 *  считается по прайсу Flash — она у нас единственная работающая. */
export function costUsd(model: string, inputTokens: number, outputTokens: number): number {
  const p = (PRICING_USD_PER_1M as Record<string, { input: number; output: number }>)[model]
    ?? PRICING_USD_PER_1M[GEMINI_MODEL_FLASH];
  return (inputTokens / 1_000_000) * p.input + (outputTokens / 1_000_000) * p.output;
}
