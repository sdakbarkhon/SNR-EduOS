import type { ParsedTopic } from "@/lib/curriculum-parse";

/**
 * ФОРМАТ ФАЙЛА УЧЕБНОГО ПЛАНА. 06.09.2026.
 *
 * ═══ ЗАЧЕМ ФАЙЛ ════════════════════════════════════════════════════════════
 *
 * Кнопка «Создать учебный план» отдаёт темы файлом, а не кладёт план в базу.
 * Учитель открывает файл, правит темы и приносит их второй кнопкой. Между
 * кнопками файл живёт у него на компьютере — и должен открываться чем угодно.
 *
 * ═══ ПОЧЕМУ CSV, А НЕ JSON И НЕ DOCX ═══════════════════════════════════════
 *
 * Требований три, и они тянут в разные стороны: человек должен править файл
 * руками, машина — читать его без модели, а сломать его правкой должно быть
 * трудно.
 *
 *   JSON  — машине идеален, человеку враждебен: лишняя запятая, и файл мёртв;
 *   DOCX  — человеку удобен, машине непонятен: разбирать пришлось бы моделью,
 *           то есть платить второй раз ровно за то, что уже посчитано;
 *   CSV   — открывается Excel и Google Таблицами как таблица, правится в них
 *           привычно, читается кодом построчно и переживает почти любую
 *           правку.
 *
 * ═══ МЕТКА ═════════════════════════════════════════════════════════════════
 *
 * Первая строка — признак «этот файл сделали мы». По ней загрузка понимает,
 * что темы уже готовы, и НЕ зовёт модель. Нет метки — файл считается чужим и
 * разбирается моделью, как раньше. Метка несёт версию: формат когда-нибудь
 * изменится, и старый файл должен читаться старым способом, а не молча
 * рассыпаться.
 *
 * ═══ МЕЛОЧИ, БЕЗ КОТОРЫХ EXCEL ЛОМАЕТСЯ ═══════════════════════════════════
 *
 *   • BOM в начале — иначе Excel открывает кириллицу кракозябрами;
 *   • разделитель `;` — русская локаль Excel ждёт именно его;
 *   • перенос строки CRLF — тот же довод;
 *   • поле с `;` или кавычкой берётся в кавычки, внутренняя кавычка
 *     удваивается — правило CSV, которое Excel соблюдает сам. Переноса
 *     строки внутри поля мы не пишем вовсе: он заменяется пробелом;
 *   • поле, начинающееся с `=`, `+`, `-` или `@`, получает ведущий апостроф —
 *     иначе Excel считает его формулой, показывает «#ИМЯ?» и при следующем
 *     сохранении название темы пропадает совсем. На чтении апостроф снимается.
 *
 * ═══ ЧИТАЕМ МЫ НЕ ТО, ЧТО ПИСАЛИ ══════════════════════════════════════════
 *
 * Между кнопками файл побывает в чужих руках и вернётся НЕ таким, каким ушёл.
 * Поэтому чтение устроено осторожнее записи — три места, где чужая правка
 * молча превращала темы в мусор:
 *
 *   • КОДИРОВКА. «Сохранить как → CSV (разделители — запятые)» в русском Excel
 *     пишет windows-1251 без BOM. Чтение вслепую как UTF-8 дало бы кракозябры,
 *     и они стали бы названиями тем, не вызвав ни одной ошибки. Пробуем UTF-8,
 *     видим знак замены — перечитываем как windows-1251.
 *   • РАЗДЕЛИТЕЛЬ. Google Таблицы всегда отдают запятую, Excel с нерусским
 *     региональным форматом — тоже. Разделитель не зашит: он опознаётся по
 *     строке заголовков.
 *   • ЗАПИСИ, А НЕ СТРОКИ. Alt+Enter в описании — и Excel сохранит поле с
 *     переносом ВНУТРИ кавычек. Резать текст по переносам до разбора кавычек
 *     значило бы рвать такую тему пополам.
 */

export const МЕТКА = "# SNR EduOS · учебный план · v1";
const ЗАГОЛОВОК = ["Тема", "Описание", "Уроков"] as const;
const BOM = "﻿";

/** Символы, с которых Excel считает ячейку формулой. */
const ОПАСНОЕ_НАЧАЛО = ["=", "+", "-", "@"];

function экранировать(v: string): string {
  let s = v.replace(/\r?\n/g, " ").trim();
  // Апостроф перед формульным началом. В ячейке он виден — некрасиво, зато
  // текст цел; без него Excel показывает «#ИМЯ?», а при сохранении на месте
  // темы остаётся ошибка формулы, и название потеряно навсегда.
  if (ОПАСНОЕ_НАЧАЛО.includes(s[0] ?? "")) s = `'${s}`;
  return /[;"]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** Снимает наш апостроф. Только перед формульным началом: тема, честно
 *  начинающаяся с апострофа, остаётся как есть. */
function снятьАпостроф(s: string): string {
  return s.startsWith("'") && ОПАСНОЕ_НАЧАЛО.includes(s[1] ?? "") ? s.slice(1) : s;
}

/** Темы файлом. Первая строка — метка, вторая — заголовки столбцов. */
export function темыВCsv(topics: ParsedTopic[]): string {
  const строки = [
    МЕТКА,
    ЗАГОЛОВОК.join(";"),
    ...topics.map((t) => [
      экранировать(t.title),
      экранировать(t.description ?? ""),
      String(t.estimated_lessons > 0 ? t.estimated_lessons : 1),
    ].join(";")),
  ];
  return BOM + строки.join("\r\n") + "\r\n";
}

/** Байты файла в текст. Сначала UTF-8; если в нём оказался знак замены —
 *  значит байты были не UTF-8, и это почти наверняка windows-1251 из русского
 *  Excel. Перечитываем. Молча принимать кракозябры за названия тем нельзя:
 *  ошибки не будет, а план получится из «ÐÑÐ¾Ð±Ð¸». */
export function файлВТекст(buffer: Buffer): string {
  const utf8 = buffer.toString("utf-8");
  if (!utf8.includes("\uFFFD")) return utf8;
  try {
    return new TextDecoder("windows-1251").decode(buffer);
  } catch {
    return utf8;
  }
}

/** Наш ли это файл. Смотрим только начало: метка стоит первой строкой. */
export function этоНашФайл(текст: string): boolean {
  const начало = текст.replace(/^\uFEFF/, "").trimStart().split(/\r?\n/, 1)[0] ?? "";
  return начало.trim().startsWith("# SNR EduOS");
}

/**
 * Разбор нашего файла — БЕЗ МОДЕЛИ. Это и есть весь смысл метки.
 *
 * Пустые записи пропускаются, строка заголовков — тоже. Число уроков, которое
 * учитель стёр или испортил, становится единицей: терять всю тему из-за одной
 * ячейки нельзя, а «один урок» — честное умолчание.
 */
export function csvВТемы(текст: string): ParsedTopic[] {
  const чистый = текст.replace(/^\uFEFF/, "");
  const разделитель = опознатьРазделитель(чистый);
  const темы: ParsedTopic[] = [];

  for (const ячейки of разобратьТаблицу(чистый, разделитель)) {
    // Метка — единственная строка-комментарий. Раньше отсекалась любая
    // решётка, и тема «#1. Атом и молекула» исчезала бесследно.
    if ((ячейки[0] ?? "").trimStart().startsWith("# SNR EduOS")) continue;

    const title = снятьАпостроф((ячейки[0] ?? "").trim());
    if (!title) continue;
    // Строка заголовков — единственная, где в первой ячейке стоит слово
    // «Тема». Настоящая тема с таким названием осталась бы без описания,
    // поэтому сверяем пару.
    if (title === ЗАГОЛОВОК[0] && (ячейки[1] ?? "").trim() === ЗАГОЛОВОК[1]) continue;

    const описание = снятьАпостроф((ячейки[1] ?? "").trim());
    const уроков = Number.parseInt((ячейки[2] ?? "").trim(), 10);
    темы.push({
      title,
      description: описание || null,
      estimated_lessons: Number.isFinite(уроков) && уроков > 0 ? уроков : 1,
    });
  }
  return темы;
}

/** Разделители, которые встречаются в жизни: наш, гугловский и табуляция. */
const РАЗДЕЛИТЕЛИ = [";", ",", "\t"];

/**
 * Каким знаком разделены столбцы. Спрашиваем у самого файла, а не у веры в то,
 * что он вернулся неизменным: Google Таблицы отдают запятую всегда, Excel с
 * нерусским региональным форматом — тоже.
 *
 * Признак — строка заголовков: «Тема», «Описание», «Уроков». Если её нет
 * вовсе (учитель стёр), берём тот разделитель, при котором таблица выходит
 * шире всего: три столбца лучше одного, а одна колонка на всё — это как раз
 * та беда, ради которой всё и затевалось.
 */
function опознатьРазделитель(текст: string): string {
  for (const р of РАЗДЕЛИТЕЛИ) {
    for (const ячейки of разобратьТаблицу(текст, р)) {
      if ((ячейки[0] ?? "").trim() === ЗАГОЛОВОК[0]
        && (ячейки[1] ?? "").trim() === ЗАГОЛОВОК[1]) return р;
    }
  }
  let лучший = РАЗДЕЛИТЕЛИ[0]!;
  let максимум = 0;
  for (const р of РАЗДЕЛИТЕЛИ) {
    const ширина = разобратьТаблицу(текст, р)
      .reduce((м, я) => Math.max(м, я.length), 0);
    if (ширина > максимум) { максимум = ширина; лучший = р; }
  }
  return лучший;
}

/**
 * Текст в таблицу за один проход. Конец записи ищется С УЧЁТОМ КАВЫЧЕК:
 * перенос строки внутри закавыченного поля (Alt+Enter в Excel) — часть
 * значения, а не конец темы. Разбирать построчно, а кавычки после, значило бы
 * рвать такую тему пополам и получать из неё две мусорные.
 */
function разобратьТаблицу(текст: string, разделитель: string): string[][] {
  const таблица: string[][] = [];
  let запись: string[] = [];
  let текущая = "";
  let вКавычках = false;

  const закрытьПоле = () => { запись.push(текущая); текущая = ""; };
  const закрытьЗапись = () => {
    закрытьПоле();
    if (запись.some((я) => я.trim() !== "")) таблица.push(запись);
    запись = [];
  };

  for (let i = 0; i < текст.length; i += 1) {
    const c = текст[i]!;
    if (вКавычках) {
      if (c === '"') {
        if (текст[i + 1] === '"') { текущая += '"'; i += 1; }
        else вКавычках = false;
      } else текущая += c;
      continue;
    }
    if (c === '"') { вКавычках = true; continue; }
    if (c === разделитель) { закрытьПоле(); continue; }
    if (c === "\r") { if (текст[i + 1] === "\n") i += 1; закрытьЗапись(); continue; }
    if (c === "\n") { закрытьЗапись(); continue; }
    текущая += c;
  }
  закрытьЗапись();
  return таблица;
}
