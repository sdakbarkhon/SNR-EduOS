/**
 * Цена обучения группы (`groups.course_price`) — заход 2 по платежам.
 *
 * ОДНО МЕСТО ПРАВДЫ для трёх задач: разбор того, что ввёл человек; показ
 * числа человеку; живое приведение поля во время набора. Форма и server
 * action обязаны понимать ввод ОДИНАКОВО — иначе на экране одно число, а в
 * базе другое.
 *
 * ЧТО В БАЗЕ. `integer NOT NULL DEFAULT 0`, плюс проверка
 * `groups_course_price_not_negative` (`CHECK (course_price >= 0)`) из миграции
 * 227. То есть база — последний рубеж, а не единственный: сюда отказ должен
 * доходить уже понятной фразой, а не текстом Postgres.
 *
 * НОЛЬ ЗНАЧИТ «ЦЕНА НЕ ЗАДАНА», а не «бесплатно». Сегодня ноль стоит у всех
 * семи групп, потому что колонку не правил ни один экран. Поэтому поле формы
 * открывается ПУСТЫМ при нуле, а в списке вместо «0 сум» стоит слово «не
 * задана»: админ обязан видеть разницу между «мы решили не брать денег» и
 * «мы ещё не заполнили».
 *
 * ПРОБЕЛЫ. Человек пишет «4 500 000», и это правильный способ писать деньги.
 * Разбор снимает ЛЮБЫЕ пробельные знаки, включая неразрывный U+00A0 (им же
 * группируем сами) и узкий U+202F — их вставляют Word, Excel и телефонные
 * клавиатуры. `\s` в JS покрывает весь этот набор.
 */

/** Верхняя граница `integer` в Postgres. Больше — не «дорого», а переполнение:
 *  без этой проверки база бросит английское «integer out of range». */
export const COURSE_PRICE_MAX = 2147483647;

/** Неразрывный пробел: цена не должна переноситься по разрядам. */
const NBSP = " ";

/** Группировка по три разряда. Работает со строкой, а не с числом: у длинных
 *  строк цифр Number теряет точность раньше, чем мы успеем отказать. */
function groupDigits(digits: string): string {
  return digits.replace(/\B(?=(\d{3})+(?!\d))/g, NBSP);
}

/**
 * Разбор того, что пришло из формы. Бросает машинный код — фразу подставит
 * humanizeAdminError на языке вызывающего.
 *
 * Пусто → 0 («цена не задана»). Дробь, буква, минус → BAD_PRICE.
 */
export function parseCoursePrice(raw: string): number {
  const cleaned = raw.replace(/\s/g, "");
  if (cleaned === "") return 0;
  if (!/^\d+$/.test(cleaned)) throw new Error("BAD_PRICE");
  // Сначала длина, потом Number: 20-значную строку Number округлит молча.
  if (cleaned.replace(/^0+(?=\d)/, "").length > 10) throw new Error("PRICE_TOO_BIG");
  const value = Number(cleaned);
  if (!Number.isSafeInteger(value) || value > COURSE_PRICE_MAX) throw new Error("PRICE_TOO_BIG");
  return value;
}

/** Число из базы → строка для человека: «4 500 000». Без единицы — её
 *  подставляет вызывающий из словаря, у трёх языков она разная. */
export function formatCoursePrice(value: number): string {
  return groupDigits(String(Math.trunc(Math.abs(value))));
}

/**
 * Живое приведение поля во время набора: всё, кроме цифр, просто не попадает
 * в поле — ни точка, ни запятая, ни буква, ни минус. Вставка «4 500 000»
 * из буфера при этом читается верно, потому что пробелы отбрасываются вместе
 * с остальным и разряды собираются заново.
 *
 * ПОТОЛОК ДЕРЖИТСЯ ЗДЕСЬ ЖЕ. Лишний ноль в цене — это не выдумка: 4 500 000
 * и 45 000 000 отличаются одним нажатием. Как только число перестаёт
 * помещаться в `integer`, поле просто не принимает следующую цифру. Иначе
 * отказ пришёл бы с сервера, а текст отказа в продакшен-сборке Next
 * подменяет своим (см. отчёт по заходу 2) — админ увидел бы английскую
 * заглушку вместо объяснения.
 */
export function formatCoursePriceInput(raw: string): string {
  let digits = raw.replace(/\D/g, "").replace(/^0+(?=\d)/, "");
  if (digits === "") return "";
  // Сначала по длине — 20-значную строку Number округлит молча, — потом по
  // значению: 10 цифр помещаются не все (9 999 999 999 > предела).
  if (digits.length > 10) digits = digits.slice(0, 10);
  while (digits.length > 1 && Number(digits) > COURSE_PRICE_MAX) digits = digits.slice(0, -1);
  return groupDigits(digits);
}
