/**
 * Школо-зависимое «сейчас». Z.3, заход 1, 10.08.2026.
 *
 * ЗАЧЕМ. `getDemoNow()` из `lib/demo-date.ts` отдаёт константу 29.07.2026
 * ВСЕМ подряд — она про школу не знает ничего. Пока населена одна демо-школа,
 * это незаметно; как только в SNR International School появятся ученики и
 * учителя, их расписание, посещаемость, домашние задания и оценки начнут
 * считать «сегодня» 29 июля.
 *
 * ЭТОТ МОДУЛЬ ПОКА НИКТО НЕ ЗОВЁТ. Заход 1 создаёт источник и доводит школу
 * до клиента; перевод 69 существующих вызовов — заходы 2 и 3. Поведение
 * приложения после этого захода не меняется ни на йоту.
 *
 * ПРАВИЛО ОДНО, И ИСТОЧНИК ПРАВДЫ — БАЗА:
 *   schools.frozen_date IS NULL  → настоящее время;
 *   schools.frozen_date = дата   → якорь на этой дате.
 *
 * Ни `is_demo`, ни кука демо-аренды, ни признак демо-сессии здесь не
 * участвуют — и это не придирка. У демо-школы есть НАСТОЯЩИЙ ученик
 * `sherzod_10`: он входит обычным логином и куки аренды не получает. Любая
 * реализация, опирающаяся на куку или на признак сессии, отдала бы ему
 * настоящее время и сломала бы демонстрацию ровно там, где её показывают.
 * Принадлежность к школе — единственный признак, который для него верен.
 *
 * ПОЧЕМУ ВРЕМЯ СУТОК ВСЁ-ТАКИ В КОДЕ. `schools.frozen_date` имеет тип `date`
 * — в нём есть день и нет часа. День берётся из базы (это и есть источник
 * правды, он у каждой школы свой), а время суток внутри дня — общее
 * оформительское решение, и оно живёт здесь одной константой. Значение
 * выбрано не случайно: 10:15 Ташкента — СЕРЕДИНА второго урока (09:55–10:40).
 * Момент, попадающий на границу слота, — известные грабли: в разных местах
 * сравнение написано то как `>=`, то как `>`, и ровно на стыке они дают
 * разный ответ. Подробная история трёх кругов — в шапке `lib/demo-date.ts`.
 * НЕ ставить якорь на границу слота.
 *
 * ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ. Он отвечает на вопрос «какой сейчас день и час»
 * и только на него. Для ИЗМЕРЕНИЯ ИНТЕРВАЛОВ («сколько удерживают клавишу»,
 * «сколько идёт анимация») нужны настоящие часы — `Date.now()`. Это
 * разделение в проекте уже осознано: см. комментарий в
 * `components/lesson-stages/SlideViewer.tsx`, где реальные часы взяты
 * намеренно. Не сводить одно к другому.
 *
 * Файл намеренно без зависимостей: его импортируют и сервер, и клиент, и
 * legacy-модуль `demo-date.ts`.
 */

/** Время суток якоря, Ташкент. Единственное место, где оно записано. */
export const FROZEN_TIME_OF_DAY_TASHKENT = "10:15";

/** Смещение Ташкента. Часовой пояс без перевода часов, поэтому константа. */
export const TASHKENT_UTC_OFFSET = "+05:00";

/** Заморожена ли школа. `frozen_date` как приходит из базы: «2026-07-29» или null. */
export function isSchoolFrozen(frozenDate: string | null | undefined): boolean {
  return !!frozenDate;
}

/**
 * «Сейчас» для школы.
 *
 * У незамороженной школы это настоящие часы — то есть каждый вызов даёт
 * новое значение. У замороженной — всегда один и тот же момент, сколько бы
 * раз ни позвали: на этом держится неподвижность демонстрации.
 */
export function schoolNow(frozenDate: string | null | undefined): Date {
  if (!frozenDate) return new Date();
  return new Date(`${frozenDate}T${FROZEN_TIME_OF_DAY_TASHKENT}:00${TASHKENT_UTC_OFFSET}`);
}

export function schoolNowMs(frozenDate: string | null | undefined): number {
  return schoolNow(frozenDate).getTime();
}

/** Ташкентская дата (YYYY-MM-DD) для ISO-момента. */
function tashkentDay(iso: string): string {
  return new Date(new Date(iso).getTime() + 5 * 60 * 60 * 1000).toISOString().slice(0, 10);
}

/**
 * Урок лежит в дне СТРОГО РАНЬШЕ замороженного дня школы — значит начать его
 * нельзя. Z.3, заход 3.
 *
 * ТОЧНОЕ ЗЕРКАЛО ТРИГГЕРА `trg_block_past_day_lesson_start` (миграция 173),
 * сверено по его исходнику:
 *   * `frozen_date IS NULL` → триггер делает RETURN NEW, ограничения нет
 *     вовсе. Здесь — `false`, то есть кнопка старта доступна всегда;
 *   * иначе сравнивается ДЕНЬ УРОКА ПО ТАШКЕНТУ с `frozen_date`, строго
 *     меньше — отказ. Здесь та же пара и тот же знак.
 *
 * Источник истины — база: она отдаёт P0001 «Нельзя начать урок за прошедший
 * день» независимо от того, что показал интерфейс. Эта функция нужна лишь
 * чтобы не рисовать заведомо нерабочую кнопку и не ронять человека в сырую
 * ошибку Postgres. Разъедутся — получим либо кнопку, падающую в сырую
 * ошибку, либо её отсутствие там, где старт разрешён.
 *
 * Сам замороженный день и всё, что позже, начинать МОЖНО: заказчик
 * показывает клиентам, что уроки запускаются наперёд.
 */
export function isPastDayLessonForSchool(
  startsAtIso: string,
  frozenDate: string | null | undefined,
): boolean {
  if (!frozenDate) return false;
  return tashkentDay(startsAtIso) < frozenDate;
}

/**
 * Читает `frozen_date` школы. Отдельным запросом, потому что школа у
 * вызывающего уже есть (layout'ы получают `school_id` из тех запросов, что и
 * так делают), а `schools` читается любой вошедшей ролью — политика
 * «authenticated reads schools» с USING (true), проверено 10.08.
 *
 * Возвращает null и при отсутствии школы, и при ошибке: «не знаем про
 * заморозку» безопаснее трактовать как «настоящее время», иначе сбой запроса
 * заморозил бы настоящую школу.
 */
export async function getSchoolFrozenDate(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  schoolId: string | null | undefined,
): Promise<string | null> {
  if (!schoolId) return null;
  const { data, error } = await db
    .from("schools").select("frozen_date").eq("id", schoolId).maybeSingle();
  if (error || !data) return null;
  return (data as { frozen_date: string | null }).frozen_date ?? null;
}
