/**
 * ВЫГРУЗКА ТАБЛИЦЫ В CSV, КОТОРЫЙ EXCEL ОТКРЫВАЕТ БЕЗ МАСТЕРА ИМПОРТА.
 *
 * Три решения, каждое ради того, чтобы файл открылся двойным щелчком:
 *
 *   • BOM в начале — иначе Excel на русской Windows читает файл в системной
 *     кодировке и все кириллические имена превращаются в кракозябры;
 *   • разделитель «точка с запятой», а не запятая — в русской локали Excel
 *     ждёт именно её, с запятой вся строка попадает в одну ячейку;
 *   • перевод строки CRLF — так строки не слипаются в старых версиях.
 *
 * Каждое поле берётся в кавычки, внутренние кавычки удваиваются: иначе
 * комментарий учителя с «;» или переносом строки разъехался бы по колонкам.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. На 26.08 ровно эта же процедура была написана дважды —
 * в аналитике администратора и в расходах ИИ у суперадмина. Экран оценок
 * учителя стал бы третьей копией. Те две не переписаны намеренно: экраны
 * администратора и суперадмина в этом заходе в запретной зоне, трогать их
 * было нельзя.
 */
export function downloadCsv(fileName: string, rows: ReadonlyArray<ReadonlyArray<string>>): void {
  const body = rows
    .map((row) => row.map((cell) => `"${String(cell ?? "").replace(/"/g, '""')}"`).join(";"))
    .join("\r\n");
  const url = URL.createObjectURL(new Blob(["﻿" + body], { type: "text/csv;charset=utf-8" }));
  const a = document.createElement("a");
  a.href = url;
  a.download = fileName;
  a.click();
  URL.revokeObjectURL(url);
}

/** Имя файла без пробелов и знаков, на которых спотыкаются файловые системы. */
export function csvFileNamePart(value: string): string {
  return value.trim().replace(/[\\/:*?"<>|]+/g, "").replace(/\s+/g, "-");
}
