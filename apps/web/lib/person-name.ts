/** Имя для обращения. В базе полное имя лежит одной строкой в западном порядке
 *  — «Ivan Petrov», «Karim Alisher Botirov» (проверено выборкой из admins и
 *  teachers), поэтому имя — первое слово.
 *
 *  Транслитерации здесь нет намеренно: «Ivan» останется «Ivan», а не станет
 *  «Иваном». Придумывать за человека написание его имени приложение не вправе —
 *  если админ хочет видеть кириллицу, имя правится в базе, а не угадывается.
 *
 *  Односложное имя («Администратор») возвращается как есть. Пустая строка тоже
 *  возвращается пустой — вызывающий сам решает, что показать. */
export function firstName(fullName: string | null | undefined): string {
  return (fullName ?? "").trim().split(/\s+/)[0] ?? "";
}
