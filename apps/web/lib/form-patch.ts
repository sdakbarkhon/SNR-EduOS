/**
 * Пишем в базу только то, что человек ДЕЙСТВИТЕЛЬНО менял.
 *
 * ОТКУДА ЭТО ВЗЯЛОСЬ. 19.08.2026 нашлись два экрана суперадмина, где
 * сохранение затирало заполненное пустым, и человек об этом не узнавал:
 *
 *   Администраторы — форма ждала поле googleEmail, а страница отдавала
 *   google_email. В форму всегда приезжало undefined, поле рисовалось пустым,
 *   а серверное действие писало колонку БЕЗУСЛОВНО. Каждое «Сохранить»
 *   отвязывало администратору вход через Google, ничего не спросив.
 *
 *   Карточка школы — шесть полей организации. Очистил любое, сохранил, и
 *   прежнее значение исчезло. Здесь расхождения имён не было: поле честно
 *   показывало значение, но пустая строка так же честно превращалась в NULL.
 *
 * ПОЧЕМУ ИМЕННО ТАКОЕ РЕШЕНИЕ. Форма в HTML отправляет ВСЕ свои поля, в том
 * числе пустые, — поэтому «поле пришло или нет» ничего не различает, и на
 * formData.has() построить защиту нельзя. Спрашивать подтверждение на каждое
 * опустевшее поле — второй диалог поверх формы на ровном месте, и он
 * появлялся бы там, где человек стёр значение нарочно.
 *
 * Поэтому рядом с каждым защищаемым полем едет СКРЫТОЕ поле с тем значением,
 * которое форме дали при открытии. Совпало — человек поля не трогал, колонку
 * не пишем вовсе. Не совпало — пишем, в том числе пустоту: стёр нарочно —
 * значит нарочно.
 *
 * Что это даёт разом:
 *   • сломанная подстановка больше не может затереть данные — пустое поле,
 *     приехавшее из-за ошибки, равно пустому «исходному» и просто пропускается;
 *   • намеренная очистка поля по-прежнему работает, без лишних вопросов;
 *   • ни одной новой строки на экране и ни одного нового диалога.
 *
 * ГДЕ НЕТ СКРЫТЫХ ПОЛЕЙ — форма создания. Там сравнивать не с чем, и все
 * поля считаются заполненными заново: пустое становится NULL, как и было.
 */

/**
 * КАКИЕ ПОЛЯ ЗАЩИЩЕНЫ — перечислено здесь, и это единственное место.
 *
 * Списки живут в этом модуле, а не рядом с формами, по двум причинам. Первая:
 * их читают с обеих сторон — и клиентская форма (чтобы разложить скрытые
 * поля), и серверное действие (чтобы собрать patch); модуль чистый, его можно
 * тащить куда угодно, в отличие от lib/school-card.ts, который тянет за собой
 * клиент Supabase. Вторая: добавляя седьмое поле в карточку школы, правишь
 * одну строку здесь, и защита появляется сразу на обеих сторонах.
 */
export const SCHOOL_CARD_FIELDS = [
  "address", "phone", "email", "director_name", "website", "legal_details",
] as const;

/** У администратора защищена одна колонка — та самая, что затиралась. */
export const ADMIN_GUARDED_FIELDS = ["google_email"] as const;

/** Приставка скрытого поля с исходным значением. */
export const ORIG_PREFIX = "__orig_";

/** Имя скрытого поля для колонки. */
export function origName(field: string): string {
  return ORIG_PREFIX + field;
}

/**
 * Возвращает ТОЛЬКО изменённые поля. Пустая строка становится null — так же,
 * как было раньше, но лишь для тех полей, которые человек правда правил.
 */
export function changedFields<K extends string>(
  fd: FormData,
  names: readonly K[],
): Partial<Record<K, string | null>> {
  const patch: Partial<Record<K, string | null>> = {};

  for (const name of names) {
    const now = String(fd.get(name) ?? "").trim();
    const orig = fd.get(origName(name));

    // Скрытого поля нет — это форма создания либо форма, которую ещё не
    // научили его отдавать. Ведём себя как раньше: пишем что прислали.
    if (orig === null) {
      patch[name] = now === "" ? null : now;
      continue;
    }

    // Не трогали — колонки в запросе не будет вовсе.
    if (now === String(orig).trim()) continue;

    patch[name] = now === "" ? null : now;
  }

  return patch;
}
