-- Миграция 249: имя группы уникально в пределах школы.
--
-- Пункт 227, 03.09.2026. Решение заказчика — заводить ограничение в базе.
--
-- ═══ ПОЧЕМУ ТЕПЕРЬ, ЕСЛИ СТОЛЬКО ВРЕМЕНИ ЖИЛИ БЕЗ НЕГО ════════════════════
--
-- Проверка была только в коде: assertGroupNameFree (apps/web/lib/admin-api.ts)
-- вычитывает все группы школы и сравнивает имена без регистра и краевых
-- пробелов. Комментарий рядом честно писал, что ограничения в базе нет и
-- миграцию не делали. Пока группы заводились по одной, этого хватало.
--
-- Массовое создание ломает обе опоры сразу:
--
--   1. ПРОВЕРКА НЕ ВИДИТ ПОВТОРОВ ВНУТРИ ПАЧКИ. Она читает базу, а не то,
--      что мы собираемся вставить. Двенадцать имён, среди которых два
--      одинаковых, пройдут проверку все двенадцать раз.
--
--   2. ПРЕДОХРАНИТЕЛЬ ОТ ДВОЙНОГО КЛИКА НЕ РАБОТАЕТ. Найдено 03.09.2026:
--      useSubmitGuard отпускает замок синхронно, потому что startTransition
--      возвращает undefined. То есть задвоение возможно уже сегодня, без
--      всякого массового создания. Оно чинится тем же заходом, но полагаться
--      на один только код после такой находки нельзя.
--
-- ═══ ЧТО ПРОВЕРЕНО ПЕРЕД НАПИСАНИЕМ ═══════════════════════════════════════
--
-- 03.09.2026 на живой базе:
--
--   * задвоенных имён (по ключу lower(btrim(name)) в пределах школы) — НЕТ;
--   * имён с краевыми пробелами — НЕТ;
--   * все десять групп дают десять разных ключей.
--
-- То есть индекс встанет без починки данных. Если у вас он всё-таки
-- откажет — значит группы появились после проверки; тогда покажите вывод
-- запроса из конца этого файла и не чините вслепую.
--
-- ═══ ПОЧЕМУ ФУНКЦИОНАЛЬНЫЙ ИНДЕКС, А НЕ UNIQUE(school_id, name) ═══════════
--
-- Простой UNIQUE считал бы «7-А» и «7-а » разными именами, а для человека
-- это одна и та же группа — и путаница в выпадающих списках расписания,
-- назначений и перевода ученика была бы ровно та же, ради предотвращения
-- которой проверка вообще писалась.
--
-- lower(btrim(name)) повторяет код буква в букву: name.trim().toLowerCase().
--
-- IMMUTABLE обе функции, поэтому в индексе их использовать можно.
--
-- ═══ ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ ══════════════════════════════════════════
--
-- Не трогает подписи веток чата. Классная ветка ищется по совпадению
-- chat_threads.title = groups.name, и переименование группы эту связь рвёт
-- (проверено живьём 03.09.2026: fn_class_thread_id после переименования
-- отдаёт NULL, а назначенный следом учитель не попадает в классный чат).
-- Это отдельная беда, шире этого захода, и заказчик записал её отдельным
-- пунктом. Здесь она НЕ чинится намеренно.
--
-- Не трогает и проверку в коде: она остаётся первой линией, потому что
-- умеет назвать человеку, какое именно имя занято, а индекс умеет только
-- отказать. Индекс — вторая линия, на случай гонки и пачки.

BEGIN;

SET LOCAL lock_timeout = '3s';

-- Замок берётся на groups: таблица из десяти строк, ACCESS EXCLUSIVE на
-- время построения индекса. Это доли секунды; CONCURRENTLY не нужен и в
-- транзакции невозможен.
CREATE UNIQUE INDEX IF NOT EXISTS groups_school_name_unique_idx
  ON public.groups (school_id, lower(btrim(name)));

COMMENT ON INDEX public.groups_school_name_unique_idx IS
  'Имя группы уникально внутри школы, без учёта регистра и краевых пробелов '
  '— повторяет assertGroupNameFree буква в букву. Вторая линия после '
  'проверки в коде: она называет занятое имя, индекс только отказывает. '
  'Заведён под массовое создание групп (пункт 227): проверка в коде не '
  'видит повторов внутри одной пачки. Миграция 249.';

COMMIT;

