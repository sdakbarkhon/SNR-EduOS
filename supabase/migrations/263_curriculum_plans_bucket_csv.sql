-- ============================================================================
-- Миграция 263: бакет учебных планов принимает наш CSV.
-- ============================================================================
--
-- ═══ ЗАЧЕМ ═════════════════════════════════════════════════════════════════
--
-- Кнопка «Создать учебный план» отдаёт темы файлом, а вторая кнопка принимает
-- его обратно. Файл — CSV: он открывается таблицей в Excel, правится руками и
-- читается кодом без модели. Но бакет `curriculum-plans` заведён миграцией 116
-- под два типа, pdf и docx, — и хранилище отказывает всем прочим ещё до RLS,
-- своей собственной проверкой списка. Живая проба записи 06.09.2026:
--
--     mime type text/csv is not supported
--
-- То есть без этой строки цепочка «книга → темы → файл» упирается в стену на
-- последнем шаге: разбор уже оплачен, а записать нечего.
--
-- ═══ ПОЧЕМУ ОДИН ТИП, А НЕ ГОРСТЬ ══════════════════════════════════════════
--
-- Соблазн внести заодно text/plain и application/vnd.ms-excel: Windows с
-- установленным Excel называет .csv вторым из них. Не вносим. Тип, с которым
-- файл ложится в хранилище, мы задаём САМИ — и на стороне фона (заказ пишет
-- 'text/csv; charset=utf-8'), и на стороне браузера (uploadCurriculumPlanFile
-- ставит 'text/csv' по расширению, не веря слову браузера). Список бакета —
-- это забор, а не удобство: чем он у́же, тем меньше в бакете окажется того,
-- чего мы не ждали.
--
-- ═══ ЧТО НЕ МЕНЯЕТСЯ ═══════════════════════════════════════════════════════
--
-- Ни правила доступа к бакету, ни лимит размера, ни приватность, ни один файл
-- внутри. Четыре осиротевших файла остаются как есть — они отдельным пунктом.
-- ============================================================================

UPDATE storage.buckets
   SET allowed_mime_types = allowed_mime_types || ARRAY['text/csv']
 WHERE id = 'curriculum-plans'
   AND NOT ('text/csv' = ANY (allowed_mime_types));

-- ── Заодно: подпись колонки говорила неправду ───────────────────────────────
--
-- В 262 записано «<teacher_id>/drafts/<id>.csv». Так было бы, если бы файл
-- клался мимо соглашения о путях: первый сегмент любого нового файла — школа
-- (packages/core/src/storage/path.ts), иначе он считается наследием демо-школы,
-- а правило «своей папки» отсчитывает владельца не от того сегмента. Код
-- поправлен тем же заходом, поправляем и подпись.
COMMENT ON COLUMN public.curriculum_plan_drafts.result_path IS
  'Путь готового CSV в бакете curriculum-plans (<school_id>/<teacher_id>/drafts/<id>.csv). NULL, пока заказ не выполнен или отказал.';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_types text[];
BEGIN
  SELECT allowed_mime_types INTO v_types FROM storage.buckets WHERE id = 'curriculum-plans';

  IF v_types IS NULL THEN
    RAISE EXCEPTION '263: у бакета curriculum-plans пропал список типов — так он примет что угодно';
  END IF;
  IF NOT ('text/csv' = ANY (v_types)) THEN
    RAISE EXCEPTION '263: text/csv в списке типов не появился';
  END IF;
  -- Прежние два типа обязаны остаться: ими грузят настоящие файлы планов.
  IF NOT ('application/pdf' = ANY (v_types)) THEN
    RAISE EXCEPTION '263: из списка пропал application/pdf';
  END IF;
  IF NOT ('application/vnd.openxmlformats-officedocument.wordprocessingml.document' = ANY (v_types)) THEN
    RAISE EXCEPTION '263: из списка пропал docx';
  END IF;
  IF array_length(v_types, 1) <> 3 THEN
    RAISE EXCEPTION '263: в списке % типов вместо трёх', array_length(v_types, 1);
  END IF;

  RAISE NOTICE '263: бакет учебных планов принимает pdf, docx и наш csv';
END $$;
