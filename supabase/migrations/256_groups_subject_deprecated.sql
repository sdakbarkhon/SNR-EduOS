-- ============================================================================
-- Миграция 256: groups.subject помечена устаревшей и получает умолчание.
-- ============================================================================
--
-- ═══ ЧТО ЭТО ЗА КОЛОНКА ════════════════════════════════════════════════════
--
-- След модели «группа = один курс». Настоящая связь «группа — предметы» живёт
-- в назначениях (`subjects.group_id`), и у класса их бывает пять-шесть. А в
-- колонке лежит ОДНО значение, да ещё и в двух разных видах:
--
--   'programming' × 4, 'robotics' × 2   — слаги из списка в коде
--   'Схемотехника', 'Science'           — САМИ НАЗВАНИЯ
--
-- Второй вид не ошибка ввода: форма писала `слаг ?? само название`, и предмет,
-- которого в списке кода нет, попадал туда русским словом. То есть колонка
-- хранила смесь по замыслу, а не по недосмотру.
--
-- Хуже смеси другое: у трёх демо-классов там 'programming', хотя предметов у
-- каждого пять-шесть. Экран групп показывал этот один и молчал про остальные.
--
-- ═══ ЧТО СДЕЛАНО В КОДЕ ════════════════════════════════════════════════════
--
-- Читателей у колонки не осталось:
--   • список групп показывает назначения, а не её;
--   • помощник ИИ берёт предмет урока из назначения;
--   • экраны задания и урока спрашивают справочник (`subject_id`), и строк
--     без него в базе НОЛЬ: 0 из 60 заданий, 0 из 130 уроков;
--   • мёртвые выборки колонки (объявления, карточка ученика, выбор файлов)
--     убраны.
--
-- Три формы админа — группа, массовое создание, единое окно — больше не
-- спрашивают предмет у группы и кладут в колонку пустую строку.
--
-- ═══ ЧТО ДЕЛАЕТ ЭТА МИГРАЦИЯ ═══════════════════════════════════════════════
--
-- Ровно две вещи, обе безопасные:
--   1. умолчание '' — чтобы колонку можно было не передавать при вставке
--      вовсе (сегодня она `text NOT NULL` без умолчания, и пропуск падал);
--   2. пометку в схеме, чтобы следующий человек не принял её за источник
--      правды.
--
-- ДАННЫЕ НЕ ТРОГАЕТ. Восемь существующих строк остаются как есть: их вид
-- ничего не ломает, а решение приводить их к одному виду — за заказчиком.
-- Сама колонка уходит в конце цепочки заходов, вместе с остальными слагами.
--
-- ПОРЯДОК ВЫКАТКИ НЕ ВАЖЕН. Код кладёт пустую строку явно — он работает и до
-- этой миграции, и после.
-- ============================================================================

ALTER TABLE public.groups ALTER COLUMN subject SET DEFAULT '';

COMMENT ON COLUMN public.groups.subject IS
  'УСТАРЕЛА (05.09.2026). След модели «группа = один курс». Предметы группы — в назначениях public.subjects (group_id). Ни один экран её не читает, формы кладут пустую строку. Уходит вместе с остальными слагами в конце цепочки заходов; до тех пор новые строки получают '''' по умолчанию.';
