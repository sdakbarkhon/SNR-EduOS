-- Миграция 221: в перечень действий журнала добавлен вход суперадмина в школу.
--
-- ЗАЧЕМ. Суперадмин получил возможность зайти в школу и посмотреть её экраны —
-- строго на чтение. Сам вход должен оставлять след: кто, когда и в какую школу
-- заходил. Журнал (миграция 220) для этого готов, но перечень видов действий в
-- нём закрыт проверкой, и незнакомый вид он не примет — намеренно.
--
-- ЧТО МЕНЯЕТСЯ. Ровно одно значение: 'school.visit'. Больше ничего — ни
-- колонок, ни прав, ни функций.
--
-- ПОЧЕМУ ЭТО МИГРАЦИЯ, А НЕ СТРОКА В КОДЕ. Перечень живёт проверкой прямо в
-- таблице, чтобы журнал не принимал того, о чём не договаривались. Плата за
-- такую строгость — миграция на каждый новый вид действия, и это осознанная
-- плата: лучше написать пять строк SQL, чем однажды обнаружить в журнале
-- запись, которую туда никто не собирался класть.
--
-- ДО ПРИМЕНЕНИЯ. Вход в школу работает и без этой миграции — просто без записи
-- в журнал. Проверка отобьёт запись ПОНЯТНОЙ ошибкой
-- (superadmin_journal_action_check), приложение её поймает, напишет
-- предупреждение в лог и пустит человека дальше. Экраны просмотра при этом не
-- ломаются: смотреть школу можно, следа пока не остаётся.

ALTER TABLE public.superadmin_journal
  DROP CONSTRAINT IF EXISTS superadmin_journal_action_check;

ALTER TABLE public.superadmin_journal
  ADD CONSTRAINT superadmin_journal_action_check
  CHECK (action IN (
    'school.create', 'school.update', 'school.archive', 'school.delete',
    'admin.create', 'admin.update', 'admin.delete', 'admin.reset_password',
    'self.google_email', 'self.password',
    'access.denied',
    -- 20.08.2026 — вход в школу на просмотр. Пишется ОДНОЙ строкой на вход,
    -- а не на каждый открытый экран: тринадцать строк за одну прогулку
    -- утопили бы настоящие действия в шуме, ничего не добавив к «заходил в
    -- школу N в 14:20».
    'school.visit'
  ));

NOTIFY pgrst, 'reload schema';
