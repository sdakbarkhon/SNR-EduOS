BEGIN;

-- Точное имя старой политики — из живого текста миграции 147
-- (supabase/migrations/147_teacher_library.sql:97-106), не гадание.
DROP POLICY IF EXISTS "teacher reads library materials" ON public.teacher_library_materials;

CREATE POLICY "teacher reads own subject library materials" ON public.teacher_library_materials
  FOR SELECT TO authenticated
  USING (
    (
      school_id = public.current_school_id()
      AND subject_slug = (SELECT t.subject_slug FROM public.teachers t WHERE t.id = public.current_teacher_id())
    )
    OR public.is_super_admin()
  );

COMMIT;
