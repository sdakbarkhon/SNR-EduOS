-- ПРАВКИ К ПРОМТУ (после сверки с реальной схемой):
--
--   1) Таблица называется teacher_library_materials, не
--      department_materials — такой таблицы нет нигде в схеме (см. отчёт
--      разведки предыдущего Этапа 12). Использую реальное имя.
--
--   2) У teacher_library_materials НЕТ колонки subject_id (uuid,
--      ссылка на конкретную classroom-строку subjects) — только
--      subject_slug (text: programming/robotics/math/english/russian,
--      предмет САМОГО УЧИТЕЛЯ на момент загрузки, миграция 147). У
--      subjects.id нет единственного канонического значения на предмет
--      — это каталог ПО КЛАССАМ (миграция 98), одна и та же
--      "Программирование" существует как 3 разные строки (3-А/7-А/10-А).
--      Черновик промта (`s.id = department_materials.subject_id`)
--      физически не мог бы работать даже при правильном имени таблицы —
--      сравнивать пришлось бы subject_slug, а не subject_id.
--
--   3) `s.teacher_id = auth.uid()` в черновике промта — сравнение
--      разных типов сущностей: subjects.teacher_id — это FK на
--      teachers.id, а auth.uid() — это id из auth.users. Они совпадают
--      только у СУПЕР-АДМИНСКИХ бутстрап-строк, для обычного учителя
--      teachers.id != auth.users.id (отдельная таблица со своим uuid).
--      Правильный паттерн — public.current_teacher_id() (уже
--      используется по всей кодовой базе, SECURITY DEFINER, резолвит
--      auth.uid() → teachers.id) — тот же приём, что и remaining RLS
--      этой же таблицы (миграция 147, insert-политика).
--
--   4) Промт просил заменить ЧЕТЫРЕ политики (SELECT + "аналогично для
--      INSERT/UPDATE/DELETE" единой FOR ALL). Это было бы РЕГРЕССОМ:
--      текущие INSERT/UPDATE/DELETE-политики (миграция 147) УЖЕ строже —
--      только САМ АВТОР (uploaded_by = current_teacher_id()) может
--      редактировать/удалять СВОЙ материал. Общая "FOR ALL по предмету"
--      разрешила бы ЛЮБОМУ учителю этого предмета удалить/изменить
--      материал ДРУГОГО учителя того же предмета — понижение
--      привилегий, не их выравнивание. Меняю ТОЛЬКО SELECT; INSERT/
--      UPDATE/DELETE не трогаю (они и так корректны и даже строже).
--
--   5) Куратор (teachers.subject_slug IS NULL) — новая политика ниже
--      естественным образом отдаёт ему 0 материалов (subject_slug =
--      NULL никогда не TRUE в SQL, тройная логика) — ровно то поведение,
--      о котором промт спрашивал в п. "если куратор не должен видеть —
--      проверить что RLS его не пускает". Отдельная ветка-исключение не
--      нужна.
