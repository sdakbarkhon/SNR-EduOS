-- ============================================================================
-- Миграция 257: материалы группы ссылаются на справочник предметов школы.
-- ============================================================================
--
-- ЧТО БЫЛО. `course_materials.subject` — текст с НАЗВАНИЕМ предмета
-- («Математика», «Схемотехника»), скопированным в момент загрузки. Не слаг:
-- эта колонка с самого начала хранила русское имя, поэтому её и не задело
-- лечение слагов. Но копия есть копия: школа переименует предмет в
-- справочнике — двести двадцать шесть строк останутся со старым словом, и
-- фильтр по предмету распадётся на два пункта вместо одного.
--
-- ЧТО СТАНОВИТСЯ. Рядом появляется `catalog_id` — ссылка на строку
-- справочника. Имя колонки, правило удаления и индекс те же, что у книг
-- (миграция 254) и у назначений (171): третьего способа сослаться на
-- справочник в схеме быть не должно.
--
-- ПЕРЕЕЗД БЕЗ МОСТА. У книг слаг приходилось переводить в название через
-- словарь кода. Здесь перевод не нужен: в колонке уже лежит название, и оно
-- сверяется с `school_subjects.name` напрямую, внутри своей школы. Все 226
-- строк находят пару — проверено прогоном с откатом 05.09.2026.
--
-- СТАРАЯ КОЛОНКА ОСТАЁТСЯ. Она уходит в конце цепочки заходов вместе с
-- остальными копиями предмета.
--
-- МАТЕРИАЛ БЕЗ ПАРЫ В СПРАВОЧНИКЕ. `catalog_id` остаётся пустым, материал
-- никуда не девается и показывается по своему тексту, как раньше. Сегодня
-- таких нет ни одного.
-- ============================================================================

ALTER TABLE public.course_materials
  ADD COLUMN IF NOT EXISTS catalog_id uuid NULL
  REFERENCES public.school_subjects(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_course_materials_catalog_id
  ON public.course_materials (catalog_id);

COMMENT ON COLUMN public.course_materials.catalog_id IS
  'Предмет материала строкой справочника школы (school_subjects). NULL = пары нет, показ падает на устаревшую текстовую копию course_materials.subject.';

-- Переезд. Только там, где ссылки ещё нет: повторный запуск ничего не
-- переписывает и не отменяет ручных правок.
UPDATE public.course_materials AS cm
   SET catalog_id = ss.id
  FROM public.school_subjects AS ss
 WHERE cm.catalog_id IS NULL
   AND ss.school_id = cm.school_id
   AND ss.name = cm.subject;

-- Самопроверка: без пары остаться никто не должен.
DO $$
DECLARE
  v_total integer;
  v_linked integer;
BEGIN
  SELECT count(*), count(catalog_id) INTO v_total, v_linked FROM public.course_materials;
  RAISE NOTICE '257: материалов %, со ссылкой %', v_total, v_linked;
  IF v_total <> v_linked THEN
    RAISE EXCEPTION
      '257: % материалов не нашли предмет в справочнике своей школы. Текст в course_materials.subject не совпал ни с одним названием — заведите предмет с нужным именем и повторите.',
      v_total - v_linked;
  END IF;
END $$;
