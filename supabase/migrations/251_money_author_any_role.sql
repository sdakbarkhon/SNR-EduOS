-- Миграция 251: у правки суммы счёта появляется автор любой роли.
--
-- Срез 3d по роли менеджера, 03.09.2026. Единственная миграция всего захода.
--
-- ═══ УПОР, КОТОРЫЙ ЗАКРЫВАЕТСЯ ════════════════════════════════════════════
--
--   tuition_invoices.adjusted_by → REFERENCES admins(id) ON DELETE SET NULL
--
-- Автором правки суммы могла быть ТОЛЬКО строка из `admins`. У менеджера её
-- нет и быть не может: он не привязан ни к какой школе, в этом вся роль.
--
-- Пропустить его с `adjusted_by = null` можно было одной строкой, но тогда
-- правка суммы счёта потеряла бы автора молча. Деньги — последнее место, где
-- такое допустимо.
--
-- ═══ ЧТО ПРОВЕРЕНО ПЕРЕД НАПИСАНИЕМ ═══════════════════════════════════════
--
-- 03.09.2026 на живой базе:
--
--   счетов                                32
--   из них с заполненным adjusted_by       0   ← конвертировать НЕЧЕГО
--   все 32                                 в состоянии open
--   читателей колонки в коде               НЕТ ни одного: экран показывает
--                                          «Сумма изменена школой» по
--                                          adjusted_at, а не по автору
--   пишущих                                два (admin-payments.ts)
--
-- То есть переезд ключа обходится без починки данных и без правки чтения.
--
-- ═══ ВАРИАНТЫ, И ПОЧЕМУ ВЫБРАН ЭТОТ ═══════════════════════════════════════
--
--   1. ССЫЛКА НА УЧЁТНУЮ ЗАПИСЬ вместо админа (выбран). Одна колонка, один
--      смысл, ключ цел. Любая роль — человек, а человек есть в auth.users.
--      Конвертировать нечего, читателей нет. Дешевле всех.
--
--   2. Вторая колонка под менеджера. Два поля на один факт: читать пришлось
--      бы оба, и однажды кто-то прочитал бы одно. В этом проекте копии
--      расходились семь раз.
--
--   3. Снять ключ, хранить «id из своей таблицы» плюс роль. Целостности нет:
--      удалённый менеджер оставил бы висячий идентификатор, а ON DELETE
--      SET NULL перестал бы работать.
--
--   4. Пропускать пустотой — запрещено заказчиком, и правильно.
--
-- ═══ ВТОРАЯ КОЛОНКА — ЭТО ДРУГОЙ ФАКТ, А НЕ ТОТ ЖЕ ════════════════════════
--
-- `adjusted_by` отвечает на «КТО», `adjusted_by_role` — на «В КАКОМ КАЧЕСТВЕ».
-- Это разные вопросы: один и тот же человек может быть заведён и админом
-- школы, и менеджером, а через год перестать быть тем и другим. Определять
-- роль задним числом по нынешним таблицам значит однажды показать неправду.
--
-- Ровно то же решение принято в миграции 250 для журнала суперадмина
-- (actor_role), и по той же причине.
--
-- ═══ ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ ══════════════════════════════════════════
--
-- НЕ ЗАВОДИТ АВТОРА ПОПОЛНЕНИЮ БАЛАНСА. Проверено: в `balance_entries` нет
-- ни одной колонки «кто» — ни author, ни created_by, ни admin_id. То есть
-- сегодня НИКТО не знает, кто пополнил баланс, и это не беда менеджера, а
-- давняя дыра, общая для всех ролей.
--
-- Закрыть её значило бы завести новую колонку и научить её писать — работы,
-- которую заказчик не просил. Менеджер при этом ничего не ухудшает: его
-- пополнение так же безымянно, как и админское. Дыра названа отдельно в
-- журнале решений; закрывать — по слову заказчика.
--
-- Отмены и возврата счёта это тоже касается: колонок «кто отменил» и «кто
-- вернул» не существует вовсе.

BEGIN;

SET LOCAL lock_timeout = '5s';

-- ── 1. Ключ переезжает на учётную запись ───────────────────────────────────
--
-- Порядок важен: сперва снять старый, потом поставить новый. Данных в
-- колонке нет, поэтому проверка нового ключа пройдёт мгновенно.
ALTER TABLE public.tuition_invoices
  DROP CONSTRAINT IF EXISTS tuition_invoices_adjusted_by_fkey;

ALTER TABLE public.tuition_invoices
  ADD CONSTRAINT tuition_invoices_adjusted_by_fkey
  FOREIGN KEY (adjusted_by) REFERENCES auth.users(id) ON DELETE SET NULL;

COMMENT ON COLUMN public.tuition_invoices.adjusted_by IS
  'Учётная запись того, кто правил сумму. Ссылается на auth.users, а не на '
  'admins: править может и менеджер, у которого строки в admins нет и быть '
  'не может. До миграции 251 колонка была пуста во всех 32 счетах, поэтому '
  'переезд ключа обошёлся без починки данных.';

-- ── 2. В каком качестве правил ─────────────────────────────────────────────
ALTER TABLE public.tuition_invoices
  ADD COLUMN IF NOT EXISTS adjusted_by_role text;

-- CHECK, а не перечисление: перечислений про роли в этом проекте нет ни
-- одного, и заводить первое ради двух значений незачем. NULL допускается —
-- это «правки не было», и таковы все 32 существующих счёта.
ALTER TABLE public.tuition_invoices
  DROP CONSTRAINT IF EXISTS tuition_invoices_adjusted_by_role_chk;
ALTER TABLE public.tuition_invoices
  ADD CONSTRAINT tuition_invoices_adjusted_by_role_chk
  CHECK (adjusted_by_role IS NULL OR adjusted_by_role IN ('admin', 'manager'));

COMMENT ON COLUMN public.tuition_invoices.adjusted_by_role IS
  'В каком качестве правили сумму: admin или manager. Отдельный от '
  'adjusted_by факт — один человек может быть заведён обеими ролями, и '
  'определять роль задним числом значит однажды показать неправду. Та же '
  'развилка решена так же в миграции 250 (superadmin_journal.actor_role).';

COMMIT;

