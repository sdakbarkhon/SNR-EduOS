-- Миграция 246: длительность урока задаёт школа, а не учитель у каждого урока.
--
-- ЗАЧЕМ. Длительность спрашивали в трёх местах сразу: в форме урока у учителя,
-- в окне массового создания и константой SLOT_DURATION_MIN = 45 в
-- планировщике учебного плана. Три источника одного числа — это три способа
-- разойтись. Плюс само поле у учителя бессмысленно: сетка звонков в школе
-- одна, и решает её не предметник.
--
-- РЕШЕНИЕ ЗАКАЗЧИКА (01.09.2026): одно число на школу, задаёт суперадмин в
-- карточке школы. Поле у учителя убрать совсем. Переопределений на отдельный
-- урок НЕ делать — это вернуло бы ровно то, что убираем.
--
-- ── ВОРОТА ПЕРЕД НАПИСАНИЕМ (проверено на живой базе 01.09.2026) ────────────
--
--   SNR Demo School   уроков 126   все по 45 минут   без ends_at 0   ends_at не сходится 0
--   SNR School        уроков   2   все по 45 минут   без ends_at 0   ends_at не сходится 0
--
-- Все 128 уроков по 45 минут, и у каждого ends_at ровно starts_at + 45 минут.
-- Значит, умолчание 45 не меняет ни одного существующего урока: перенос
-- ничего не ломает, потому что переносить нечего.
--
-- СУЩЕСТВУЮЩИЕ УРОКИ НЕ ТРОГАЕМ. У них своё время начала и конца, оно уже
-- записано в lessons.starts_at / lessons.ends_at и остаётся как есть. Число у
-- школы влияет ТОЛЬКО на уроки, создаваемые после её применения. Эта миграция
-- не выполняет ни одного UPDATE по lessons.
--
-- ── ГРАНИЦЫ: ОТ 15 МИНУТ ДО 3 ЧАСОВ ────────────────────────────────────────
--
-- Урок в одну минуту и урок в пять часов заводить не надо, поэтому границы
-- стоят прямо в схеме, а не только в форме.
--
--   НИЖНЯЯ, 15 минут. Самый короткий настоящий урок в школе — 30 минут
--   (младшие классы, сокращённые дни). Пятнадцать оставляют запас вниз для
--   короткого занятия в учебном центре и при этом отрезают заведомую чепуху.
--   Ниже пятнадцати «урок» перестаёт быть уроком и начинает ломать смежное:
--   окно правки отметок (public.mark_edit_window) — те же 15 минут, и урок
--   короче него означал бы, что «пока урок идёт» короче, чем обычное окно
--   исправления, то есть правило миграции 245 не даёт учителю ничего.
--
--   ВЕРХНЯЯ, 180 минут. Три часа накрывают самое длинное, что бывает:
--   сдвоенную пару с перерывом внутри или длинную мастерскую. Пять часов —
--   это уже не урок, а день, и такое число почти наверняка опечатка
--   (например, 450 вместо 45).
--
-- ВТОРОГО ДИАПАЗОНА НЕ ОСТАЁТСЯ. В коде стояла отдельная проверка «5..240
-- минут» — в createLesson, в updateLesson и в двух роутах. Она была проверкой
-- ПОЛЯ УРОКА, а поле уходит целиком, и вместе с ним уходит она. Единственный
-- диапазон теперь этот, и он один и тот же в схеме и в общем слое
-- (packages/core/src/utils/lessonDuration.ts — те же 15 и 180).
--
-- ── ПУСТОЕ ЗНАЧЕНИЕ ────────────────────────────────────────────────────────
--
-- Колонка NOT NULL DEFAULT 45, поэтому пустой она быть не может ни у одной
-- школы: ни у двух существующих (им проставится 45), ни у будущих (createSchool
-- эту колонку не передаёт вовсе, сработает умолчание). Отдельно проверено
-- прогоном: вставка школы без колонки даёт 45; попытка записать NULL явно
-- отбивается not-null; попытка записать 0, 5, 181, 300 отбивается проверкой.
--
-- Форма суперадмина пустое поле в базу не отправляет: пустая строка означает
-- «не менял», колонка в запрос не попадает и прежнее значение остаётся.
--
-- ── ЗАМКИ: ЧТО БЕРЁТСЯ И ЧТО ЗАКРЫВАТЬ ─────────────────────────────────────
--
-- Оба ALTER TABLE берут ACCESS EXCLUSIVE на public.schools. Что это значит
-- здесь:
--
--   * ADD COLUMN ... NOT NULL DEFAULT 45 таблицу НЕ ПЕРЕПИСЫВАЕТ. С
--     PostgreSQL 11 постоянное умолчание кладётся в каталог
--     (pg_attribute.attmissingval), а строки не трогаются. У нас PostgreSQL
--     17.6, таблица 64 кБ и 2 строки — работа идёт только по каталогу;
--   * ADD CONSTRAINT ... CHECK, наоборот, таблицу СКАНИРУЕТ, чтобы убедиться,
--     что существующие строки условию отвечают. Две строки — сканирование
--     мгновенное. Приём NOT VALID + VALIDATE CONSTRAINT здесь был бы лишним
--     усложнением: он нужен на миллионах строк, не на двух;
--   * на schools ссылаются 66 внешних ключей других таблиц. Их этот ALTER не
--     касается: добавление колонки не проверяет и не перестраивает ссылки, и
--     замки на ссылающиеся таблицы НЕ берутся.
--
-- ЗАКРЫВАТЬ НИЧЕГО НЕ НАДО, но есть настоящий риск, и он не в длительности
-- работы, а в ОЧЕРЕДИ. ACCESS EXCLUSIVE несовместим даже с чтением: если в
-- момент применения кто-то держит долгий запрос к schools, наш ALTER встаёт в
-- очередь, а за ним встают ВСЕ последующие читатели schools — то есть
-- практически весь сайт, потому что школу читает почти каждый экран. Поэтому
-- ниже стоит lock_timeout: не дождались за три секунды — миграция честно
-- падает и ничего не ломает, вместо того чтобы подвесить портал. Повторить
-- можно сразу же.
--
-- ── ЧТО МЕНЯЕТСЯ В КОДЕ ЭТИМ ЖЕ КОММИТОМ ───────────────────────────────────
--
--   * форма урока у учителя больше не спрашивает длительность;
--   * окно массового создания — тоже;
--   * createLesson не принимает durationMinutes вовсе и читает число у школы
--     группы: переопределить его неоткуда;
--   * updateLesson не принимает duration_minutes: существующий урок свою
--     длительность сохраняет;
--   * SLOT_DURATION_MIN из планировщика убран, длительность приходит доводом.
--
-- ШАГ МЕЖДУ УРОКАМИ (SLOT_STRIDE_MIN = 55 в планировщике) НЕ ТРОНУТ — ждёт
-- отдельного решения заказчика. Разбор последствий — в журнале решений.

BEGIN;

-- Не дождались за три секунды — падаем, а не подвешиваем портал (см. выше).
SET LOCAL lock_timeout = '3s';

ALTER TABLE public.schools
  ADD COLUMN IF NOT EXISTS lesson_duration_minutes integer NOT NULL DEFAULT 45;

-- Границы 15..180 — разбор в шапке. Держать в синхроне с
-- packages/core/src/utils/lessonDuration.ts: там те же два числа, и они
-- нужны форме, чтобы отказ приходил до запроса, по-человечески.
ALTER TABLE public.schools
  DROP CONSTRAINT IF EXISTS schools_lesson_duration_minutes_check;
ALTER TABLE public.schools
  ADD CONSTRAINT schools_lesson_duration_minutes_check
  CHECK (lesson_duration_minutes BETWEEN 15 AND 180);

COMMENT ON COLUMN public.schools.lesson_duration_minutes IS
  'Длительность урока в минутах — одно число на школу, задаёт суперадмин в '
  'карточке школы. Влияет только на СОЗДАВАЕМЫЕ уроки: у существующих своё '
  'время начала и конца уже записано. Переопределений на отдельный урок нет '
  'намеренно. Границы 15..180, те же в packages/core/src/utils/lessonDuration.ts. '
  'Миграция 246.';

COMMIT;

-- ПРОВЕРКА ПОСЛЕ ПРИМЕНЕНИЯ:
--
--   -- колонка есть, умолчание 45, пустой быть не может (ждём 1 строку):
--   SELECT column_name, data_type, is_nullable, column_default
--     FROM information_schema.columns
--    WHERE table_schema = 'public' AND table_name = 'schools'
--      AND column_name = 'lesson_duration_minutes';
--
--   -- обеим школам проставилось 45:
--   SELECT name, lesson_duration_minutes FROM public.schools ORDER BY name;
--
--   -- проверка на месте:
--   SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint
--    WHERE conrelid = 'public.schools'::regclass
--      AND conname = 'schools_lesson_duration_minutes_check';
--
--   -- уроки не тронуты: 128 штук, все по 45, ends_at сходится:
--   SELECT count(*) AS уроков,
--          count(*) FILTER (WHERE duration_minutes = 45) AS по_45,
--          count(*) FILTER (WHERE ends_at <> starts_at
--                              + make_interval(mins => duration_minutes)) AS конец_не_сходится
--     FROM public.lessons;
--
-- ЧТО ПРОВЕРЕНО ПРОГОНОМ С ОТКАТОМ (01.09.2026; числа — в журнале решений):
--   * колонка появилась, тип integer, NOT NULL, умолчание 45
--   * обеим школам проставилось 45 без единого UPDATE с нашей стороны
--   * школа, созданная без этой колонки, получает 45
--   * NULL отбивается not-null, значения 0 / 5 / 14 / 181 / 300 — проверкой
--   * значения 15 / 45 / 90 / 180 принимаются
--   * 128 уроков целы: все по 45, ends_at сходится у всех
--   * после отката колонки нет, проверки нет, уроков 128
