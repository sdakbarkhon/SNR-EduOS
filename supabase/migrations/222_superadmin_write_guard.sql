-- Миграция 222: суперадмин больше не пишет в школьные таблицы.
--
-- ЗАЧЕМ. У суперадмина было право записи в 56 таблиц, где экрана нет вовсе:
-- 132 правила пропускали его молча. Три шага мы шли к этому: журнал действий
-- (220), просмотр школы на чтение (221), и теперь — закрытие. Корзины
-- разрешённого решено не открывать ни одной: сценарий «админ школы уволился»
-- закрыт кнопкой «завести администратора» на его собственном экране, и она
-- пишется в журнал. Право лезть в полсотни таблиц ради этого — лишнее, а
-- лишнее право дороже недостающего.
--
-- КАК УСТРОЕНЫ СУЩЕСТВУЮЩИЕ ПРАВИЛА, И ПОЧЕМУ МЫ ИХ НЕ ТРОГАЕМ.
-- Все 132 выглядят одинаково:
--
--     CHECK: (<настоящее условие роли>) OR is_super_admin()
--
-- Признак суперадмина стоит отдельным «или», добавочным. Чтобы его убрать,
-- пришлось бы переписать 132 живых правила — и каждое, задетое лишний раз,
-- ломает работу настоящим учителям, админам, ученикам и родителям. Поэтому мы
-- НЕ ТРОГАЕМ НИ ОДНОГО. Вместо этого рядом встают СУЖАЮЩИЕ правила.
--
-- ПОЧЕМУ СУЖАЮЩЕЕ ПРАВИЛО БЕЗОПАСНО, И ЭТО НЕ РАССУЖДЕНИЕ, А АРИФМЕТИКА.
-- Разрешительные правила складываются по «или», сужающие приклеиваются по
-- «и». Условие ниже читается так: «либо перед нами не суперадмин, либо запись
-- разрешена списком». У учителя, админа, ученика, родителя и анонима
-- is_super_admin() ложно, значит первая половина истинна, значит всё условие
-- истинно ВСЕГДА и ни на что не влияет. Сузиться может только суперадмин.
--
-- КОГО НЕ КАСАЕТСЯ ВООБЩЕ. Служебный ключ приложения (service_role) обходит
-- правила доступа целиком, поэтому весь путь записи админских экранов и
-- экранов самого суперадмина — создание школ, заведение администраторов,
-- сброс паролей — работает как работал. Проверено: ни один экран суперадмина
-- не пишет под его собственным токеном.
--
-- ЧИТАТЬ ОН ПРОДОЛЖАЕТ ВСЁ. Сужение ставится только на INSERT, UPDATE и
-- DELETE. Ни одно правило чтения не задето, все 62 таблицы и экраны просмотра
-- школы работают ровно как вчера.
--
-- НАКРЫВАЕМ ВСЕ ТАБЛИЦЫ С ПРАВИЛАМИ ЗАПИСИ, а не только те 56, где он сегодня
-- проходит. Разница на два стола, зато завтрашняя таблица не проскочит через
-- дыру в списке: правило появляется у неё вместе с первым же правилом записи,
-- если кто-то прогонит этот же цикл заново.

-- ── 1. Список разрешённого ──────────────────────────────────────────────────
-- Сейчас он ПУСТ, и это решение заказчика: не открываем ни одной корзины.
-- Функция оставлена намеренно — чтобы завтра открыть что-то было делом одной
-- строки, а не переписывания полутора сотен правил.
--
-- КАК ОТКРЫТЬ ОДНУ ТАБЛИЦУ, если понадобится: вписать её имя в массив ниже и
-- применить новую миграцию с CREATE OR REPLACE этой функции. Больше ничего
-- менять не надо: правила уже спрашивают её.
CREATE OR REPLACE FUNCTION public.sa_write_allowed(p_table text)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT p_table = ANY (ARRAY[]::text[])
$$;

COMMENT ON FUNCTION public.sa_write_allowed(text) IS
  'Таблицы, куда суперадмину РАЗРЕШЕНО писать. Сейчас список пуст — решение '
  'заказчика от 20.08.2026. Открыть таблицу = дописать её имя сюда. '
  'Миграция 222.';

-- ── 2. Сужающие правила ─────────────────────────────────────────────────────
-- По одному на каждую пару «таблица × вид записи». Условие у всех одно и то же
-- и в текст правила подставляется имя таблицы — своего имени правило изнутри
-- не знает.
--
-- TO public — чтобы правило применялось к любой роли, под которой может
-- прийти суперадмин. Служебный ключ обходит правила доступа и под сужение не
-- попадает; анониму оно безразлично (is_super_admin() у него ложно).
DO $do$
DECLARE
  r      record;
  v_cond text;
BEGIN
  FOR r IN
    -- Все пары «таблица × команда записи» среди действующих правил.
    -- Правило вида ALL разворачивается в три команды.
    SELECT DISTINCT p.tablename,
           unnest(CASE WHEN p.cmd = 'ALL'
                       THEN ARRAY['INSERT', 'UPDATE', 'DELETE']
                       ELSE ARRAY[p.cmd] END) AS cmd
      FROM pg_policies p
     WHERE p.schemaname = 'public'
       AND p.cmd <> 'SELECT'
       AND p.permissive = 'PERMISSIVE'
     ORDER BY 1, 2
  LOOP
    v_cond := format('NOT public.is_super_admin() OR public.sa_write_allowed(%L)', r.tablename);

    EXECUTE format('DROP POLICY IF EXISTS %I ON public.%I',
                   'superadmin write guard ' || lower(r.cmd), r.tablename);

    IF r.cmd = 'INSERT' THEN
      -- У вставки проверяется только новая строка.
      EXECUTE format(
        'CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR INSERT TO public WITH CHECK (%s)',
        'superadmin write guard insert', r.tablename, v_cond);
    ELSIF r.cmd = 'UPDATE' THEN
      -- У правки — и старая строка (можно ли её взять), и новая (можно ли
      -- такой её оставить). Без второй половины правку удалось бы протащить,
      -- переписав строку так, чтобы она перестала подходить под условие.
      EXECUTE format(
        'CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR UPDATE TO public USING (%s) WITH CHECK (%s)',
        'superadmin write guard update', r.tablename, v_cond, v_cond);
    ELSE
      EXECUTE format(
        'CREATE POLICY %I ON public.%I AS RESTRICTIVE FOR DELETE TO public USING (%s)',
        'superadmin write guard delete', r.tablename, v_cond);
    END IF;
  END LOOP;
END
$do$;

NOTIFY pgrst, 'reload schema';
