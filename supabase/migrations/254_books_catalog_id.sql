-- ============================================================================
-- Миграция 254: книги ссылаются на справочник предметов школы
-- ============================================================================
--
-- ЧТО БЫЛО. `books.subject` — слаг из списка в коде: "programming", "robotics",
-- "math", "english", "russian". Пять слов, зашитых в форму добавления книги.
-- Школа, заведя свой предмет («Схемотехника», «Science»), на книжной полке его
-- не увидит — полка про него не знает.
--
-- ЧТО СТАНОВИТСЯ. Рядом появляется `catalog_id` — ссылка на строку справочника
-- школы (`school_subjects`). Имя колонки, правило удаления и индекс взяты у
-- `subjects.catalog_id` из миграции 171 намеренно: второго способа сослаться на
-- справочник в схеме быть не должно.
--
-- СЛАГ ОСТАЁТСЯ НА МЕСТЕ. Он уходит в конце цепочки заходов, вместе с
-- остальными слаговыми колонками. Пока обе колонки живут рядом, и показ
-- по-прежнему опирается на слаг.
--
-- ПЕРЕЕЗД. Мост между слагом и справочником один — подпись: колонки слага у
-- справочника нет. Соответствия ниже повторяют словарь
-- packages/core/src/config/subjects.ts для тех пяти слагов, которые вообще
-- может выдать форма (BOOK_SUBJECT_KEYS в TeacherBooksView).
--
-- НЕОДНОЗНАЧНЫХ БЫТЬ НЕ МОЖЕТ. У справочника есть ограничение
-- school_subjects_name_unique (school_id, name): пара «школа + название» даёт
-- не больше одной строки. Поэтому UPDATE ниже не может выбрать наугад.
--
-- СКРЫТЫЙ ПРЕДМЕТ СВЯЗЫВАЕМ ТОЖЕ. «Английский язык» у демо-школы помечен
-- is_active = false — он не предлагается в списках, но существует. Книга,
-- изданная по нему, должна ссылаться на него, а не оставаться без пары:
-- скрытие предмета — это про выпадающие списки, а не про уже созданное.
--
-- КНИГА БЕЗ ПАРЫ В СПРАВОЧНИКЕ. `catalog_id` остаётся пустым. Книга никуда не
-- девается и показывается как раньше — по слагу. Пустая ссылка здесь
-- нормальное состояние, а не поломка: школа могла ещё не завести такой предмет.
-- ============================================================================

-- ── 1. Колонка ──────────────────────────────────────────────────────────────
ALTER TABLE public.books
  ADD COLUMN IF NOT EXISTS catalog_id uuid NULL
  REFERENCES public.school_subjects(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_books_catalog_id ON public.books (catalog_id);

COMMENT ON COLUMN public.books.catalog_id IS
  'Предмет книги строкой справочника школы (school_subjects). NULL = пары в справочнике нет, показ падает на устаревший слаг books.subject.';

-- ── 2. Переезд существующих строк ───────────────────────────────────────────
-- Только там, где ссылки ещё нет: повторный запуск миграции ничего не
-- переписывает и не отменяет ручных правок.
UPDATE public.books AS b
   SET catalog_id = ss.id
  FROM (VALUES
          ('programming', 'Программирование'),
          ('robotics',    'Робототехника'),
          ('math',        'Математика'),
          ('english',     'Английский язык'),
          ('russian',     'Русский язык')
       ) AS m(slug, name),
       public.school_subjects AS ss
 WHERE b.catalog_id IS NULL
   AND b.subject    = m.slug
   AND ss.school_id = b.school_id
   AND ss.name      = m.name;
