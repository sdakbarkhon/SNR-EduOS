-- ЧТО ИМЕННО МЕНЯЕТСЯ И ЧТО НАМЕРЕННО НЕ МЕНЯЕТСЯ:
--
--   INSERT  — добавлено is_subject_owner(subject_id).
--   UPDATE  — добавлено ТОЛЬКО в WITH CHECK (каким станет ряд), не в USING
--             (какие ряды вообще мои). Так автор не сможет перевести задание
--             на чужой предмет или снять предмет вовсе, но «моё задание»
--             по-прежнему определяется авторством.
--   DELETE  — НЕ ТРОНУТ. Своё задание автор должен уметь удалить всегда, даже
--             если предмет под ним успели переназначить. Иначе строка
--             становится вечной.
--
-- Условие приклеивается к существующим, ничего не убирая: ветка
-- `OR is_super_admin()` и проверка школы остаются на месте.

BEGIN;

-- ── Создание ────────────────────────────────────────────────────────────────
DROP POLICY IF EXISTS "teacher creates homework" ON public.homework;
CREATE POLICY "teacher creates homework" ON public.homework
  FOR INSERT WITH CHECK (
    (
      is_my_teacher_group(group_id)
      AND teacher_id = current_teacher_id()
      AND is_subject_owner(subject_id)
      AND school_id = current_school_id()
    )
    OR is_super_admin()
  );

-- ── Правка ──────────────────────────────────────────────────────────────────
DROP POLICY IF EXISTS "teacher updates own homework" ON public.homework;
CREATE POLICY "teacher updates own homework" ON public.homework
  FOR UPDATE
  USING (
    ((teacher_id = current_teacher_id()) AND (school_id = current_school_id()))
    OR is_super_admin()
  )
  WITH CHECK (
    (
      teacher_id = current_teacher_id()
      AND is_subject_owner(subject_id)
      AND school_id = current_school_id()
    )
    OR is_super_admin()
  );

COMMIT;

