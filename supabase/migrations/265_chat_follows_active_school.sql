-- ============================================================================
-- Миграция 265: чат следует за выбранной школой. Одна функция.
-- ============================================================================
--
-- ═══ ЧТО БЫЛО ══════════════════════════════════════════════════════════════
--
-- `is_my_thread` мерила УЧАСТИЕ и только его: «я записан в эту ветку». Школа в
-- вопросе не участвовала вовсе. Пока у учителя одна школа, разницы нет — все
-- его ветки и так её. Учитель двух школ получал один список с перепиской обеих,
-- без всякой пометки, какая откуда.
--
-- Замер на живых данных (срез 264, 06.09.2026): Диане заведена вторая школа и
-- выбрана активной. Всё школьное честно погасло — объявления 11 → 0,
-- уведомления 5 → 0, сообщения помощника 4 → 0. Чат не шелохнулся: 30 веток,
-- 60 участий, 85 сообщений остались на экране, и ВСЕ 175 строк принадлежат
-- школе, которая в этот момент не выбрана. То есть переключатель работал везде,
-- кроме чата, — и выглядел бы наполовину сломанным.
--
-- ═══ ПОЧЕМУ ФУНКЦИЯ, А НЕ ЧЕТЫРЕ ПРАВИЛА ═══════════════════════════════════
--
-- `is_my_thread` зовут ровно четыре правила и ничего больше: ни функция, ни
-- триггер (проверено живым запросом по pg_policies и pg_proc). Три читают
-- ветки, участников и сообщения; четвёртое разрешает отправку. Меняем один
-- источник — все четверо следуют за ним сами, и разъехаться им негде. Тот же
-- ход, что в 260: там одна функция заменила восемьдесят восемь правок.
--
-- ═══ ЦЕНА ══════════════════════════════════════════════════════════════════
--
-- Ноль. Из 346 участий в чатах НИ ОДНО не пересекает границу школы: у каждого
-- участника школа человека совпадает со школой ветки. Значит сегодня новая
-- проверка не отнимает доступ ни у кого — ни у ученика, ни у родителя, ни у
-- админа, ни у учителя. Она лишь готова к тому дню, когда у учителя школ станет
-- две.
--
-- ═══ ЧЕГО ЭТО НАМЕРЕННО НЕ КАСАЕТСЯ ════════════════════════════════════════
--
-- ОТМЕТКИ ПРОЧТЕНИЯ (`chat_read_state`) функцию не зовут — они про свои же
-- строки, `user_id = auth.uid()`. Остаются сквозными: непрочитанное из другой
-- школы не потеряется, пока туда не переключишься. Это косметика, и трогать её
-- заказчик не велел.
--
-- СУПЕРАДМИН. Ветки его собственной проверки (`is_super_admin()`) стоят В
-- ПРАВИЛАХ, рядом с вызовом функции, и мы их не касаемся — читать он будет
-- как читал. Внутрь функции суперадмина не заводим: это расширило бы ему
-- отправку сообщений в любую ветку, чего никто не просил. Проверено: среди
-- участников чатов суперадминов нет ни одного.
-- ============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.is_my_thread(p_thread_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  SELECT EXISTS (
    SELECT 1
      FROM public.chat_participants p
      JOIN public.chat_threads t ON t.id = p.thread_id
     WHERE p.thread_id = p_thread_id
       AND p.user_id = auth.uid()
       -- Единственная добавка: ветка обязана принадлежать той школе, что
       -- выбрана сейчас. Для ученика, родителя и админа это их единственная
       -- школа — для них ничего не меняется.
       AND t.school_id = public.current_school_id()
  );
$function$;

COMMENT ON FUNCTION public.is_my_thread(uuid) IS
  'Моя ли это ветка чата: я в участниках И ветка принадлежит выбранной сейчас школе. Школьная половина добавлена миграцией 265 — без неё учитель двух школ видел переписку обеих одним списком. Зовут четыре правила: чтение веток, участников и сообщений плюс отправка сообщения.';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_тело  text;
  v_зовут integer;
BEGIN
  SELECT prosrc INTO v_тело FROM pg_proc
   WHERE proname = 'is_my_thread' AND pronamespace = 'public'::regnamespace;
  IF v_тело NOT LIKE '%current_school_id%' THEN
    RAISE EXCEPTION '265: школа в is_my_thread не появилась';
  END IF;

  -- Правил, зовущих функцию, должно остаться ровно четыре: мы их не трогали,
  -- и появление пятого означало бы, что кто-то подцепился к ней мимо нас.
  SELECT count(*) INTO v_зовут FROM pg_policies
   WHERE schemaname = 'public'
     AND (coalesce(qual, '') || coalesce(with_check, '')) LIKE '%is_my_thread%';
  IF v_зовут <> 4 THEN
    RAISE EXCEPTION '265: функцию зовут % правил вместо четырёх', v_зовут;
  END IF;

  -- Отметки прочтения обязаны остаться сквозными: функции там быть не должно.
  IF EXISTS (
    SELECT 1 FROM pg_policies
     WHERE schemaname = 'public' AND tablename = 'chat_read_state'
       AND (coalesce(qual, '') || coalesce(with_check, '')) LIKE '%is_my_thread%'
  ) THEN
    RAISE EXCEPTION '265: отметки прочтения зацепило — их велено оставить сквозными';
  END IF;

  RAISE NOTICE '265: чат следует за выбранной школой, правил на функции четыре';
END $$;

COMMIT;
