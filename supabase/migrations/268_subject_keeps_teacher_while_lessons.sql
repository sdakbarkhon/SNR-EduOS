-- ============================================================================
-- Миграция 268: предмет с уроками не остаётся без учителя.
-- ============================================================================
--
-- ═══ ЧТО СЛОМАНО ═══════════════════════════════════════════════════════════
--
-- `subjects.teacher_id` допускает пусто, и опустошить его можно тремя путями:
-- кнопкой «снять» на экране назначений, удалением учителя (внешний ключ стоит
-- ON DELETE SET NULL) и любым скриптом.
--
-- Последствие не косметическое. Правила доступа учителя ищут его уроки через
-- `subjects.teacher_id`: обнули колонку — и уроки останутся на месте, ученик и
-- администратор будут их видеть, а ВЕДУЩИЙ не увидит ни одного. Ровно это и
-- случилось с математикой десятого класса демо-школы: семь уроков и двадцать
-- оценок есть, учителя у предмета нет.
--
-- ═══ ПОЧЕМУ И В БАЗЕ ТОЖЕ ══════════════════════════════════════════════════
--
-- Запрет уже стоит в коде (setAssignmentTeacher). Одного кода мало: экран —
-- не единственный путь к колонке, и починка данных скриптом снимет учителя
-- молча, как снимала до сих пор. Здесь тот же запрет с другой стороны, и
-- обойти его нельзя ничем, кроме отключения самого триггера.
--
-- ═══ ЧТО ИМЕННО ЗАПРЕЩЕНО ══════════════════════════════════════════════════
--
-- ТОЛЬКО ОПУСТОШЕНИЕ. Замена одного учителя другим разрешена всегда: передать
-- предмет — обычная жизнь школы, и мешать ей незачем. Запрещён единственный
-- переход: был учитель → стало пусто, и при этом у предмета есть уроки.
--
-- ПРЕДМЕТ БЕЗ УРОКОВ СНИМАЕТСЯ СВОБОДНО. Терять там нечего: скрывать нечего,
-- и «Химия 10-А» без учителя и без уроков — законное промежуточное состояние.
--
-- ЗАГЛУШКИ НЕ ЗАДЕТЫ. Двенадцать предметов-пустышек учителя не имеют по
-- замыслу, уроков у них нет ни одного (проверено), и триггер до них не
-- доходит вовсе.
--
-- ═══ ЧТО БУДЕТ С УДАЛЕНИЕМ УЧИТЕЛЯ ═════════════════════════════════════════
--
-- Ничего нового. `deleteTeacher` и сегодня отказывает, если у учителя есть
-- уроки, и отказывает ДО удаления, показав их число. Триггер сработал бы
-- только в обход этой проверки — прямым удалением строки учителя, когда
-- внешний ключ обнуляет колонку сам. Тогда удаление упрётся в тот же запрет,
-- и это правильно: молча осиротить семь уроков нельзя и скриптом.
--
-- ═══ КОГО ЭТО ЗАДЕВАЕТ СЕГОДНЯ ═════════════════════════════════════════════
--
-- Никого: запрет проверяет ПЕРЕХОД, а не состояние. Два предмета, уже
-- оставшихся без учителя, лежат как лежали — их чинят данными, а не миграцией.
-- ============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.fn_subject_keeps_teacher()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $function$
DECLARE
  v_уроков integer;
BEGIN
  -- Интересен ровно один переход: был учитель, стало пусто.
  IF NEW.teacher_id IS NOT NULL OR OLD.teacher_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT count(*) INTO v_уроков FROM public.lessons l WHERE l.subject_id = OLD.id;
  IF v_уроков = 0 THEN
    RETURN NEW;
  END IF;

  -- Текст человеческий и с числом: «нельзя» без числа читается как поломка.
  -- Код в начале — тот же, что бросает setAssignmentTeacher, чтобы экран
  -- показал одну и ту же фразу, откуда бы отказ ни пришёл.
  -- Формат ровно как у соседей (BLOCKED_TEACHER_LESSONS): код, двоеточие,
  -- ЧИСЛО, двоеточие, слова. Разборщик на экране берёт число первым куском —
  -- впиши слова сразу после первого двоеточия, и он покажет ноль.
  RAISE EXCEPTION 'BLOCKED_SUBJECT_LAST_TEACHER:%:у предмета есть уроки', v_уроков;
END;
$function$;

DROP TRIGGER IF EXISTS trg_subject_keeps_teacher ON public.subjects;
CREATE TRIGGER trg_subject_keeps_teacher
  BEFORE UPDATE OF teacher_id ON public.subjects
  FOR EACH ROW
  EXECUTE FUNCTION public.fn_subject_keeps_teacher();

COMMENT ON FUNCTION public.fn_subject_keeps_teacher() IS
  'Не даёт опустошить subjects.teacher_id у предмета, по которому есть уроки: без учителя его же уроки перестают быть ему видны, а ученик и админ продолжают их видеть. Замена учителя разрешена всегда, запрещён только переход «был → пусто».';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_предмет uuid;
  v_учитель uuid;
  v_поймали boolean := false;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
     WHERE c.relname = 'subjects' AND t.tgname = 'trg_subject_keeps_teacher'
  ) THEN
    RAISE EXCEPTION '268: триггер не завёлся';
  END IF;

  -- Живая проба на настоящем предмете с уроками — и сразу откат до точки.
  SELECT s.id, s.teacher_id INTO v_предмет, v_учитель
    FROM public.subjects s
   WHERE s.teacher_id IS NOT NULL
     AND EXISTS (SELECT 1 FROM public.lessons l WHERE l.subject_id = s.id)
   LIMIT 1;

  IF v_предмет IS NULL THEN
    RAISE NOTICE '268: предметов с учителем и уроками нет — пробу пропускаю';
  ELSE
    BEGIN
      UPDATE public.subjects SET teacher_id = NULL WHERE id = v_предмет;
    EXCEPTION WHEN OTHERS THEN
      v_поймали := true;
    END;
    IF NOT v_поймали THEN
      RAISE EXCEPTION '268: снятие учителя с предмета, у которого есть уроки, ПРОШЛО — запрет не работает';
    END IF;
  END IF;

  RAISE NOTICE '268: предмет с уроками без учителя не остаётся';
END $$;

COMMIT;
