-- Миграция 224: создание урока больше не рассылает уведомления.
--
-- ЗАЧЕМ. Вставка одного урока порождала строку КАЖДОМУ ученику группы и
-- КАЖДОМУ его родителю. Массовое заведение расписания превращалось в лавину:
-- четверть на четыре группы по 10-15 учеников — это тысячи строк за одно
-- нажатие. Это не догадка, это уже случалось: в шапке скрипта
-- apps/web/scripts/trim-demo-notifications.mjs записано, что в демо-школе
-- накопилось 8778 уведомлений на 37 человек, до 445 на одного, и разгребали
-- их разовым скриптом руками. Чистки по расписанию у уведомлений нет.
--
-- ПОЧЕМУ УБИРАЕМ ЦЕЛИКОМ, А НЕ ПРОРЕЖИВАЕМ. Уведомление о создании урока не
-- сообщает ничего нового: расписание ученик и так видит на своём экране, и
-- оно там полное. То есть строка дублирует то, что на виду, и при этом топит
-- в шуме оценки, домашки и объявления — а вот их больше нигде нет.
-- Остальные семь видов остаются нетронутыми: материал урока, оценка,
-- объявление, домашка, сдача, объявление-новое, освобождение.
--
-- ЧТО ИМЕННО СНИМАЕТСЯ. Триггер trg_lesson_created_notify на public.lessons
-- (AFTER INSERT) и функция fn_lesson_created_notify, которая под ним ходила.
-- Проверено перед снятием:
--   • функция не делает НИЧЕГО, кроме рассылки: внутри один цикл по ученикам
--     группы и вызов notify_user_and_parents, других записей в ней нет;
--   • на этой функции висит ровно один триггер — тот, что снимается;
--   • ни одна другая функция схемы её не упоминает.
-- Сама notify_user_and_parents НЕ ТРОГАЕТСЯ: через неё идут остальные семь
-- видов. Прямо её зовут восемь триггерных функций (объявление, домашка,
-- решение по заявлению, создание урока, оценка за урок, материал урока,
-- оценка ученику, оценка за этап) — после этой миграции останется семь;
-- ещё четыре ходят через посредника fn_notify_student_grade.
--
-- СТАРЫЕ СТРОКИ ОСТАЮТСЯ ЧИТАЕМЫМИ, и ограничение на список видов мы НЕ
-- трогаем намеренно. В notifications стоит проверка
--   kind = ANY (ARRAY['announcement', …, 'lesson_created', …])
-- и значение 'lesson_created' из неё НЕ убирается: в базе 121 такая строка
-- (114 в демо, 7 в настоящей школе), и сужение списка сделало бы их
-- недопустимыми. Новых строк этого вида просто перестанет появляться —
-- порождать их больше некому.
--
-- ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ. Существующие уведомления не удаляет ни одного
-- (решение заказчика отдельным заходом). Чистку по расписанию не заводит —
-- кроны под запретом, и они лечили бы следствие. Прочие девять триггеров на
-- уроках не задеты: сроки, этапы по умолчанию, автостарт, база знаний.

BEGIN;

DROP TRIGGER IF EXISTS trg_lesson_created_notify ON public.lessons;
DROP FUNCTION IF EXISTS public.fn_lesson_created_notify();

COMMIT;

