-- Миграция 245: пока урок ИДЁТ, замок на отметках не ложится.
-- Плюс починка живой поломки, найденной при прогоне (см. раздел «ВТОРОЕ» ниже).
--
-- ═══ ПЕРВОЕ: ЗАМОК ВНУТРИ УРОКА ═══════════════════════════════════════════
--
-- ЗАЧЕМ. Замок из миграции 203 даёт учителю 15 минут на исправление своей
-- отметки и считает их от выставления. Для домашних заданий и тестов это
-- разумно: работа сдана, учитель проверяет её когда угодно, и окно на правку
-- отсчитывается от его собственного действия.
--
-- Но урок длится 45 минут. Учитель отмечает присутствующих на первой минуте,
-- ставит оценку за работу на пятнадцатой — и к тридцатой уже ничего из этого
-- не может поправить, хотя урок ещё идёт и ученик стоит перед ним. Замок,
-- задуманный как «нельзя переписать вчерашний журнал», запирал учителя внутри
-- его же урока.
--
-- РЕШЕНИЕ ЗАКАЗЧИКА (31.08.2026):
--   * пока урок идёт — строго status = 'in_progress' — перекличка и оценки
--     правятся свободно, замок не применяется;
--   * оценки за этапы урока освобождаются вместе с ними: они внутри урока,
--     это тот же случай;
--   * вне урока — задания и тесты — 15 минут, как сейчас, не трогаем;
--   * у проектов замка нет и никогда не было; заводить не надо.
--
-- ПОЧЕМУ СТРОГО ПО СТАТУСУ, А НЕ «УРОК ПЛЮС СКОЛЬКО-ТО МИНУТ». Урок
-- завершился — замок обязан лечь сразу, а не через 15 минут после завершения.
-- Статус для этого и годится: он один, у него есть ограничение
-- (lessons_status_check: scheduled | in_progress | completed), меняет его
-- автозавершение (fn_auto_end_lessons) или учитель, и никакой второй шкалы
-- времени не заводится.
--
-- ГДЕ ИМЕННО СТОИТ УСЛОВИЕ — И ПОЧЕМУ НЕ В НАЧАЛЕ ФУНКЦИИ. Проверка добавлена
-- последней, ПОСЛЕ отсчёта пятнадцати минут и прямо перед отказом. Это не
-- вкусовщина, а требование заказчика «замок должен лечь сразу»:
--
--   * выше по функции стоит сохранение отметки времени
--     (NEW.graded_at := OLD.graded_at). Ранний выход в начале проскочил бы
--     мимо него, и каждая правка внутри урока переписывала бы graded_at на
--     now(). Тогда после звонка у отметки оставалось бы ещё 15 минут жизни —
--     ровно то, что заказчик запретил;
--   * на этом месте условие ничего не стоит: до него доходят только те
--     правки, которые функция И ТАК СОБИРАЛАСЬ ОТКЛОНИТЬ. Обычная правка
--     внутри пятнадцати минут выходит раньше и урока не читает вовсе.
--
-- ЧТО НЕ МЕНЯЕТСЯ (проверено пробами, числа в журнале решений):
--   * машинный прогул из миграции 225 — ранний выход по marked_by IS NULL
--     стоит в начале функции, наша правка до него не доходит;
--   * часы от учителя из миграции 218 (set_grading_meta) — не тронуты;
--   * администратор школы правит без ограничения по времени — его ранний
--     выход тоже выше нашего условия;
--   * homework_submissions и test_submissions — к уроку не привязаны,
--     статус искать негде, у них остаются те же 15 минут;
--   * mark_edit_window() остаётся 15 минут;
--   * правила доступа (RLS) не трогаются ни одно.
--
-- ОСОЗНАННОЕ СЛЕДСТВИЕ, О КОТОРОМ НАДО ЗНАТЬ. Ту же функцию зовёт триггер
-- trg_lock_teacher_marks_del на удаление оценки за урок. Значит, пока урок
-- идёт, учитель может не только исправить свою оценку, но и удалить её.
-- Это сознательно: удаление ошибочной оценки — такая же правка внутри урока,
-- как замена четвёрки на пятёрку, и запрещать одно, разрешая другое, было бы
-- необъяснимо. Удалять он может только СВОИ оценки (правило «teacher deletes
-- lesson grades»: graded_by = current_teacher_id()) и только пока урок идёт;
-- после завершения удаление запирается как раньше.
--
-- ═══ ВТОРОЕ: ЖИВАЯ ПОЛОМКА ИЗ МИГРАЦИИ 225 ════════════════════════════════
--
-- НАЙДЕНО ПРОГОНОМ 31.08.2026, не искали — споткнулись. Правка ЛЮБОЙ оценки
-- учителем падала не отказом замка, а сырой ошибкой базы:
--
--     ОТКАЗ: record "old" has no field "marked_by"
--
-- Воспроизводится на свежем соединении, первым же запросом, с параметрами и
-- без них, на PostgreSQL 17.6. Затронуты четыре таблицы из пяти:
-- lesson_grades, homework_submissions, test_submissions,
-- lesson_stage_progress. Не затронута только attendance — у неё колонка
-- marked_by есть.
--
-- ОТКУДА. Миграция 225 добавила в начало функции строку:
--
--     IF TG_OP = 'UPDATE' AND TG_TABLE_NAME = 'attendance'
--        AND OLD.marked_by IS NULL THEN
--
-- Предполагалось, что при TG_TABLE_NAME <> 'attendance' второе условие ложно
-- и до третьего дело не дойдёт. Postgres такого обещания не даёт: порядок
-- вычисления операндов AND за ним не закреплён, а обращение к полю record'а
-- разбирается по фактическому описанию строки. На таблице без marked_by
-- функция падает, не дойдя ни до одной своей проверки.
--
-- Сама миграция 225 этот капкан описывает — в ветке DELETE у неё стоит
-- комментарий «Через CASE здесь нельзя: plpgsql разбирает ОБЕ ветки и падает
-- на OLD.marked_at там, где такой колонки нет. Ветвим оператором IF». В новой
-- строке тот же приём применить забыли.
--
-- ЧТО ЭТО ЗНАЧИЛО ДЛЯ ЛЮДЕЙ, с 23.08.2026:
--   * учитель НЕ мог исправить уже выставленную оценку за урок
--     (gradeStudentForLesson делает upsert; повторное выставление идёт по
--     ветке UPDATE);
--   * учитель НЕ мог оценить домашнее задание вовсе (gradeSubmission —
--     update по существующей сдаче ученика);
--   * учитель НЕ мог оценить задание этапа (gradeStageTask — тоже update);
--   * тесты — так же.
-- Работали только первое выставление оценки за урок (это INSERT, триггер на
-- него не стоит) и перекличка.
--
-- ЧИНИМ ТЕМ ЖЕ ПРИЁМОМ, что описан в самой 225: вкладываем IF в IF, чтобы
-- обращение к OLD.marked_by стояло внутри уже выбранной ветки и на других
-- таблицах не вычислялось.
--
-- Почему в этой же миграции, а не отдельной: строка стоит внутри тела,
-- которое эта миграция и переписывает, а без починки первая же половина
-- захода недостижима — «оценка, выставленная час назад, правится» не может
-- пройти, пока функция падает раньше всех своих проверок.
--
-- ═══ ОБЩЕЕ ════════════════════════════════════════════════════════════════
--
-- ТЕЛО ФУНКЦИИ СНЯТО С ПРОДА через pg_get_functiondef 31.08.2026 (3525 знаков)
-- и совпало слово в слово с файлом миграции 225. CREATE OR REPLACE, а не DROP
-- и CREATE: пересоздание сбросило бы права на функцию.

BEGIN;

CREATE OR REPLACE FUNCTION public.fn_lock_teacher_marks()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_stamp   timestamptz;
  v_changed boolean := false;
  v_row     record;
  -- 31.08.2026 (миграция 245). Статус урока, к которому относится отметка.
  -- Остаётся NULL для таблиц, у которых урока нет вовсе.
  v_lesson_status text;
BEGIN
  v_row := CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;

  -- Без пользовательской сессии: крон автозавершения, миграции, служебный
  -- ключ. Их правило не касается — иначе прогул некому было бы проставить.
  IF auth.uid() IS NULL THEN
    RETURN v_row;
  END IF;

  -- 23.08.2026 (миграция 225). Машинный прогул: строку вставило
  -- автозавершение, автора у неё нет. Правка такой строки живым человеком —
  -- это ПЕРВОЕ выставление отметки, а не изменение чужой проверки. Замок на
  -- неё не ложится, и marked_at от машины не сохраняется: часы пойдут от
  -- исправления учителя, после чего действует обычное правило 15 минут.
  --
  -- 31.08.2026 (миграция 245). IF ВЛОЖЕН В IF, И ЭТО ОБЯЗАТЕЛЬНО. В 225 всё
  -- стояло одним условием через AND, и на таблицах без колонки marked_by
  -- функция падала с «record "old" has no field "marked_by"», не дойдя ни до
  -- одной своей проверки: порядок вычисления операндов AND в Postgres не
  -- закреплён, а поле record'а разбирается по фактическому описанию строки.
  -- Тот же приём и по той же причине применён ниже, в ветке DELETE.
  IF TG_OP = 'UPDATE' AND TG_TABLE_NAME = 'attendance' THEN
    IF OLD.marked_by IS NULL THEN
      RETURN NEW;
    END IF;
  END IF;

  -- Отметка времени — это часы замка, и заводить их заново нельзя никому,
  -- кроме первого выставления. Иначе окно открывается снова:
  --   * учитель правит ОДИН комментарий (значение не изменилось, запрет не
  --     сработал), а upsert попутно пишет graded_at := now() — и оценка,
  --     запертая полчаса назад, снова редактируется;
  --   * или учитель правит оценку каждые 14 минут и держит окно вечно.
  -- Поэтому на любом UPDATE возвращаем старое значение отметки. NULL не
  -- трогаем: пустая отметка означает «ещё не выставляли», и первое
  -- выставление обязано её проставить (домашние задания и тесты приходят
  -- от ученика с graded_at IS NULL).
  IF TG_OP = 'UPDATE' THEN
    IF TG_TABLE_NAME = 'attendance' THEN
      IF OLD.marked_at IS NOT NULL THEN NEW.marked_at := OLD.marked_at; END IF;
    ELSE
      IF OLD.graded_at IS NOT NULL THEN NEW.graded_at := OLD.graded_at; END IF;
    END IF;
    v_row := NEW;
  END IF;

  -- Администратор своей школы правит без ограничения по времени.
  IF public.is_school_admin_of(v_row.school_id) THEN
    RETURN v_row;
  END IF;

  IF TG_OP = 'DELETE' THEN
    -- Удаление всегда «меняет значение» — сверяем только срок.
    v_changed := true;
    -- Через CASE здесь нельзя: plpgsql разбирает ОБЕ ветки и падает на
    -- OLD.marked_at там, где такой колонки нет. Ветвим оператором IF —
    -- невыбранная ветка не вычисляется вовсе.
    IF TG_TABLE_NAME = 'attendance' THEN
      v_stamp := OLD.marked_at;
    ELSE
      v_stamp := OLD.graded_at;
    END IF;
  ELSIF TG_TABLE_NAME = 'lesson_grades' THEN
    v_changed := NEW.grade IS DISTINCT FROM OLD.grade;
    v_stamp := OLD.graded_at;
  ELSIF TG_TABLE_NAME = 'attendance' THEN
    v_changed := NEW.status IS DISTINCT FROM OLD.status;
    v_stamp := OLD.marked_at;
  ELSIF TG_TABLE_NAME = 'homework_submissions' THEN
    v_changed := NEW.grade IS DISTINCT FROM OLD.grade
              OR NEW.status IS DISTINCT FROM OLD.status;
    v_stamp := OLD.graded_at;
  ELSIF TG_TABLE_NAME = 'test_submissions' THEN
    v_changed := NEW.score IS DISTINCT FROM OLD.score
              OR NEW.grade IS DISTINCT FROM OLD.grade;
    v_stamp := OLD.graded_at;
  ELSIF TG_TABLE_NAME = 'lesson_stage_progress' THEN
    v_changed := NEW.grade IS DISTINCT FROM OLD.grade;
    v_stamp := OLD.graded_at;
  END IF;

  IF NOT v_changed OR v_stamp IS NULL THEN
    RETURN v_row;
  END IF;

  IF v_stamp > now() - public.mark_edit_window() THEN
    RETURN v_row;
  END IF;

  -- ── 31.08.2026 (миграция 245). ПОКА УРОК ИДЁТ — ЗАМКА НЕТ ────────────────
  --
  -- Сюда доходят только отметки, которые функция уже собралась отклонить.
  -- Спрашиваем последнее: а урок-то ещё идёт? Если идёт — учитель правит
  -- внутри своего урока, и запирать его не за что.
  --
  -- Ветвим оператором IF, а не CASE и не одним условием через AND: v_row —
  -- это record, обращение к полю разбирается по фактическому описанию строки,
  -- и невыбранная ветка IF не вычисляется вовсе. lesson_stage_progress не
  -- знает про lesson_id, до урока она добирается через свой этап.
  IF TG_TABLE_NAME IN ('attendance', 'lesson_grades') THEN
    SELECT l.status INTO v_lesson_status
      FROM public.lessons l
     WHERE l.id = v_row.lesson_id;
  ELSIF TG_TABLE_NAME = 'lesson_stage_progress' THEN
    SELECT l.status INTO v_lesson_status
      FROM public.lesson_stages st
      JOIN public.lessons l ON l.id = st.lesson_id
     WHERE st.id = v_row.stage_id;
  END IF;

  -- Урока нет или он не найден — v_lesson_status остаётся NULL, и сравнение
  -- даёт NULL, а не истину. Значит, при любой неясности отказ остаётся в
  -- силе. Это намеренно: замок ошибается в сторону запрета.
  IF v_lesson_status = 'in_progress' THEN
    RETURN v_row;
  END IF;

  RAISE EXCEPTION 'mark_locked'
    USING HINT = 'Прошло больше 15 минут с выставления. Изменить может администратор школы.';
END;
$function$;

COMMENT ON FUNCTION public.fn_lock_teacher_marks() IS
  'Замок на выставленное учителем: 15 минут на исправление, дальше только '
  'администратор школы. Пока урок ИДЁТ (status = in_progress) замок не '
  'применяется к перекличке, оценкам за урок и оценкам за этапы — учитель '
  'правит внутри своего урока свободно. Задания и тесты к уроку не привязаны '
  'и живут по общему правилу 15 минут. Миграции 203, 218, 225, 245.';

COMMIT;

