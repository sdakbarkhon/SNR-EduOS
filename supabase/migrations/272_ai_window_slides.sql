-- ============================================================================
-- Миграция 272: запас помощника отпускает постепенно.
-- ============================================================================
--
-- ═══ ЧТО СЛОМАНО ═══════════════════════════════════════════════════════════
--
-- Окно было ФИКСИРОВАННЫМ и отсчитывалось ОТ МОМЕНТА ИСЧЕРПАНИЯ (миграция
-- 253): потратил двадцатый вопрос — ждёшь два часа, потом снова полные
-- двадцать. Пока двадцатого не было, «край» окна оставался в минус
-- бесконечности, и счёт шёл ПО ВСЕЙ ИСТОРИИ ученика.
--
-- Отсюда жалоба заказчика: 19 из 20 со вчерашнего дня и не восстанавливается.
-- Так и есть — девятнадцать вопросов за всё время, двадцатого нет, край
-- бесконечно давно, и в счёт попадают все девятнадцать. Навсегда.
--
-- ═══ ЧТО СТАНОВИТСЯ ═══════════════════════════════════════════════════════
--
-- Окно СКОЛЬЗЯЩЕЕ: считаются вопросы за последние два часа, и каждый вопрос
-- возвращается через два часа после САМОГО СЕБЯ. Задал час назад — через час
-- он вернётся сам, без всякого «исчерпания».
--
-- Двадцать на окно и два часа — не меняются. Ученик — по-прежнему единственный,
-- кого это касается: функцию зовут только с student_id.
--
-- ═══ КОГДА ОТПУСТИТ ═══════════════════════════════════════════════════════
--
-- `blocked_until` теперь означает не «когда вернутся все», а «когда вернётся
-- СЛЕДУЮЩИЙ»: это момент, в который из окна выпадает двадцатый с конца вопрос.
-- Экран говорит об этом ровно так же — «следующий освободится в …», потому что
-- обещать «снова будут доступны все» скользящее окно не может.
--
-- ═══ ТАБЛИЦЫ ПО-ПРЕЖНЕМУ НЕ НУЖНО ═════════════════════════════════════════
--
-- Окно выводится из самих сообщений (`ai_chat_messages`, роль user). Приём тот
-- же, что в 253, и он годится: для скользящего окна нужен только список времён
-- последних вопросов, а он там и лежит. Отдельная таблица счётчиков означала бы
-- вторую правду о том же и рассинхрон при любой чистке сообщений.
--
-- Заморозка времени школы сюда по-прежнему не подмешивается: лимит считается
-- настоящими часами.
-- ============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.fn_ai_window_state(p_student_id uuid)
RETURNS TABLE(used integer, limit_n integer, blocked_until timestamptz)
LANGUAGE sql
STABLE
SET search_path TO 'public'
AS $function$
  WITH правило AS (
    SELECT 20 AS предел, interval '2 hours' AS окно
  ),
  свежие AS (
    -- Только вопросы, которые ЕЩЁ в окне. Всё, что старше двух часов, уже
    -- вернулось само и в счёт не идёт.
    SELECT m.created_at
      FROM public.ai_chat_messages m, правило п
     WHERE m.student_id = p_student_id
       AND m.role = 'user'
       AND m.created_at > now() - п.окно
     ORDER BY m.created_at DESC
  )
  SELECT
    (SELECT count(*)::int FROM свежие) AS used,
    (SELECT предел FROM правило) AS limit_n,
    CASE
      WHEN (SELECT count(*) FROM свежие) >= (SELECT предел FROM правило)
        -- Момент, когда из окна выпадет двадцатый с конца — то есть когда
        -- освободится ОДИН вопрос, а не все двадцать.
        THEN (SELECT created_at FROM свежие OFFSET (SELECT предел FROM правило) - 1 LIMIT 1)
             + (SELECT окно FROM правило)
      ELSE NULL
    END AS blocked_until;
$function$;

COMMENT ON FUNCTION public.fn_ai_window_state(uuid) IS
  'Скользящее окно помощника: сколько вопросов ученик задал за последние два часа и когда освободится СЛЕДУЮЩИЙ. Каждый вопрос возвращается через два часа после себя. Выводится из ai_chat_messages, отдельной таблицы счётчиков нет намеренно.';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_тело text;
  v_ученик uuid;
  r RECORD;
BEGIN
  SELECT prosrc INTO v_тело FROM pg_proc
   WHERE proname = 'fn_ai_window_state' AND pronamespace = 'public'::regnamespace;

  IF v_тело LIKE '%-infinity%' THEN
    RAISE EXCEPTION '272: край окна по-прежнему уходит в минус бесконечность — счёт пойдёт по всей истории';
  END IF;
  IF v_тело NOT LIKE '%now() - п.окно%' THEN
    RAISE EXCEPTION '272: окно не стало скользящим';
  END IF;

  -- Живая проба: у кого есть старые вопросы, тот обязан видеть ноль
  -- потраченных, если за два часа не спрашивал ничего.
  SELECT m.student_id INTO v_ученик
    FROM public.ai_chat_messages m
   WHERE m.role = 'user' AND m.created_at < now() - interval '2 hours'
   LIMIT 1;

  IF v_ученик IS NOT NULL THEN
    SELECT * INTO r FROM public.fn_ai_window_state(v_ученик);
    IF r.used <> 0 THEN
      RAISE EXCEPTION '272: у ученика со старыми вопросами потрачено % вместо нуля', r.used;
    END IF;
    IF r.blocked_until IS NOT NULL THEN
      RAISE EXCEPTION '272: ученик со старыми вопросами всё ещё заперт';
    END IF;
  END IF;

  RAISE NOTICE '272: окно скользит, старые вопросы возвращаются сами';
END $$;

COMMIT;
