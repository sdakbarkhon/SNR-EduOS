--
-- РЕШЕНИЕ ЗАКАЗЧИКА, письменно. Куратор убирается из продукта целиком; Карим
-- Ботиров удаляется как учитель вместе с ролью; Сарвар Эшмуродов — пустая
-- карточка без единого следа — удаляется заодно.
--
-- ЭТА МИГРАЦИЯ — ТОЛЬКО ДАННЫЕ. Правило доступа на уроках, функция
-- is_curator_teacher(), триггеры групповых чатов, поле куратора в форме
-- группы и строка «Классный руководитель» на экранах — отдельные заходы.
-- Здесь ничего из этого не трогается: снять код при живых данных нельзя,
-- сначала данные.
--
-- ═══ ДАМП СНЯТ ПЕРЕД ПРИМЕНЕНИЕМ ═══
-- backup_curator_removal_2026-08-30.sql в корне проекта, 1237 строк,
-- 279 КБ, в репозиторий не коммитится (.gitignore, шаблон backup_*.sql).
--
-- ═══ ЧТО НЕОБРАТИМО ═══
-- Шаг 4 (30 личных веток и 79 сообщений, из них 35 написаны учениками) и
-- шаг 7 (строки учителей, с ними каскадом 6 объявлений и 3 привязки).
-- Всё остальное возвращается из дампа. Учётные записи в auth не трогаем —
-- это ручной шаг заказчика после применения.
--
-- ═══ ПОРЯДОК ШАГОВ. ОН ВАЖЕН ═══
-- Обнуление groups.teacher_id запускает trg_group_curator_changed, который
-- снимает участия с ролью curator. Поэтому:
--   * личные ветки удаляем ДО обнуления (шаг 4 перед шагом 5) — иначе
--     разбираться в чатах пришлось бы после того, как часть уже снята;
--   * админа в классные ветки вписываем ПОСЛЕ обнуления (шаг 6 после
--     шага 5) — иначе триггер прошёл бы по веткам, где админ уже стоит.
-- Триггер trg_group_curator_direct_chats при обнулении НЕ срабатывает:
-- первой строкой у него `IF NEW.teacher_id IS NULL THEN RETURN NEW`.
-- Проверено прогоном с откатом.

BEGIN;

-- ── Предохранитель: применяем к тем, кого проверяли ─────────────────────────
DO $$
DECLARE v_karim integer; v_sarvar integer;
BEGIN
  SELECT count(*) INTO v_karim FROM public.teachers
   WHERE id = '67c9ac94-a651-4619-a087-33190c2a2cec';
  IF v_karim <> 1 THEN
    RAISE EXCEPTION 'Карима нет в teachers — миграция уже применялась или база другая.';
  END IF;
  SELECT count(*) INTO v_sarvar FROM public.teachers
   WHERE id = '75209908-fb38-4c1f-a8ee-76faf426d4aa';
  IF v_sarvar <> 1 THEN
    RAISE EXCEPTION 'Сарвара нет в teachers — миграция уже применялась или база другая.';
  END IF;
END $$;

-- ── ШАГ 1. Колонка куратора у учеников ──────────────────────────────────────
--
-- 30 строк, все указывали на Карима. Колонку НЕ УДАЛЯЕМ: её читает
-- замороженное ученическое приложение (apps/mobile, profile.tsx) — там она
-- показывает имя классного руководителя. После обнуления покажет «—».
-- Триггеров на students под это нет: прогон подтвердил, что меняются ровно
-- 30 строк и ни одна цифра больше.
UPDATE public.students
   SET curator_id = NULL
 WHERE curator_id = '67c9ac94-a651-4619-a087-33190c2a2cec';

-- ── ШАГ 2. Подписи под оценками ─────────────────────────────────────────────
--
-- lesson_grades.graded_by — NOT NULL и ON DELETE NO ACTION: обнулить нельзя,
-- а с живой ссылкой база не даст удалить учителя (проверено: отказ 23503 на
-- lesson_grades_graded_by_fkey). Решение заказчика — вариант Б: подпись
-- переписывается на предметника, чей это предмет. Ни одна оценка не теряется.
--
-- Карим ставил оценки по ЧУЖИМ предметам, поэтому владелец у каждой известен:
--   Робототехника  10-А 6 + 3-А 3 = 9 → Kamila Yusupova
--   Английский     7-А  2          = 2 → Diana Bekmuradova
--   Русский язык   7-А  4          = 4 → Igor Pavlov
--                                  ─────
--                                   15
--
-- Пишем не по списку id оценок, а по владельцу предмета того урока: так
-- подпись сходится с предметом по построению, а не по нашей выписке.
UPDATE public.lesson_grades lg
   SET graded_by = sb.teacher_id
  FROM public.lessons l
  JOIN public.subjects sb ON sb.id = l.subject_id
 WHERE lg.lesson_id = l.id
   AND lg.graded_by = '67c9ac94-a651-4619-a087-33190c2a2cec'
   AND sb.teacher_id IS NOT NULL;

-- Если у какой-то оценки предмет остался без владельца — останавливаемся.
-- Молча оставить её на Кариме нельзя: удаление учителя тогда откажет.
DO $$
DECLARE v integer;
BEGIN
  SELECT count(*) INTO v FROM public.lesson_grades
   WHERE graded_by = '67c9ac94-a651-4619-a087-33190c2a2cec';
  IF v > 0 THEN
    RAISE EXCEPTION 'Осталось % оценок без нового владельца — удаление учителя откажет.', v;
  END IF;
END $$;

-- ── ШАГ 3. Объявления ───────────────────────────────────────────────────────
--
-- announcements.created_by → ON DELETE CASCADE: шесть классных объявлений
-- ушли бы вместе с Каримом. Перевешиваем ДО удаления.
--
-- НА КОГО: Igor Pavlov (русский язык). Он единственный, кто ведёт во всех
-- трёх классах Карима и у кого больше всего уроков в каждом: 10 в 10-А,
-- 10 в 3-А, 9 в 7-А (в 7-А поровну с робототехникой). Объявление классу —
-- сообщение от того, кто чаще других перед этим классом стоит.
--
-- Пять общешкольных объявлений (created_by пуст, охват all_my_groups) НЕ
-- ТРОГАЕМ: они не привязаны к Кариму и удаление их не заденет.
UPDATE public.announcements
   SET created_by = '83b179d5-7f4b-4372-92ff-4d560596d06b'
 WHERE created_by = '67c9ac94-a651-4619-a087-33190c2a2cec';

-- ── ШАГ 4. Личные чаты куратора ─────────────────────────────────────────────
--
-- НЕОБРАТИМО. 30 веток, 79 сообщений — 44 от Карима и 35 от учеников.
-- Каскадом по thread_id уходят chat_messages (79), chat_participants (60) и
-- chat_read_state (2 из 13 — остальные 11 в чужих ветках) — все три ключа
-- CASCADE. Отметка о прочтении ветки, которой больше нет, смысла не имеет.
--
-- Делаем ДО обнуления групп: после обнуления триггер уже снимет участия, и
-- разбираться в чатах будет труднее.
--
-- Чаты предметников не задеты: отбор строго по teacher_id Карима.
DELETE FROM public.chat_threads
 WHERE teacher_id = '67c9ac94-a651-4619-a087-33190c2a2cec'
   AND kind = 'direct';

-- ── ШАГ 5. Кураторство над группами ─────────────────────────────────────────
--
-- 3 строки. Здесь срабатывает trg_group_curator_changed и снимает 6 участий
-- с ролью curator — 3 классные ветки и 3 родительские. Это ожидаемо и
-- посчитано. Больше ничего он не трогает: прогон показал ровно две
-- изменившиеся цифры.
UPDATE public.groups
   SET teacher_id = NULL
 WHERE teacher_id = '67c9ac94-a651-4619-a087-33190c2a2cec';

-- ── ШАГ 6. Админ школы в классные чаты ──────────────────────────────────────
--
-- После шага 5 в трёх классных ветках остались только ученики: 84 сообщения
-- без единого взрослого. Решение заказчика — вписать админа школы.
--
-- Роль ставим 'admin', а не 'curator': значение 'curator' в CHECK ещё есть,
-- но роль из продукта уходит, и заводить новые строки с ней бессмысленно.
-- 'admin' в CHECK присутствует.
--
-- Правило доступа это позволяет: «admin/teacher add participants» разрешает
-- вставку, когда fn_is_admin() и ветка kind='group' в своей школе. Классные
-- ветки ровно такие. Проверено прогоном под ролью authenticated от лица
-- админа демо-школы.
--
-- Родительские ветки «— Родители» НЕ трогаем: решение заказчика — оставить
-- как есть.
INSERT INTO public.chat_participants (thread_id, user_id, role_in_thread)
SELECT ct.id, '5e8667dd-2a09-4ae2-9fa5-373e92e7e3cc', 'admin'
  FROM public.chat_threads ct
  JOIN public.schools s ON s.id = ct.school_id
 WHERE s.is_demo
   AND ct.kind = 'group'
   AND ct.title NOT LIKE '%— Родители'
   AND EXISTS (SELECT 1 FROM public.chat_messages m WHERE m.thread_id = ct.id)
ON CONFLICT (thread_id, user_id) DO NOTHING;

-- ── ШАГ 7. Сами учителя ─────────────────────────────────────────────────────
--
-- НЕОБРАТИМО. Каскадом уйдут 3 строки group_teachers. Объявления уже
-- перевешены (шаг 3), личные ветки уже удалены (шаг 4), подписи под оценками
-- уже переписаны (шаг 2) — каскаду забирать нечего.
--
-- SET NULL сработает по: subjects.teacher_id (13 строк — предметы останутся
-- без учителя, уроков и заданий по ним 0), books.uploaded_by (4 книги),
-- groups.teacher_id и students.curator_id (уже пусты после шагов 1 и 5).
--
-- Сарвар Эшмуродов: 0 групп, 0 предметов, 0 привязок, 0 объявлений, 0 оценок,
-- 0 веток, 0 учеников, 0 книг. Уходит без единого следа.
--
-- УЧЁТНЫЕ ЗАПИСИ В auth.users ЗДЕСЬ НЕ ТРОГАЕМ. Это ручной шаг заказчика
-- через Dashboard. Пока запись жива, 19 сообщений Карима в классных чатах
-- сохраняют автора; после её удаления sender_id обнулится (SET NULL), и
-- сообщения останутся без подписи — ядро это переживает.
DELETE FROM public.teachers
 WHERE id IN ('67c9ac94-a651-4619-a087-33190c2a2cec',
              '75209908-fb38-4c1f-a8ee-76faf426d4aa');

COMMIT;

