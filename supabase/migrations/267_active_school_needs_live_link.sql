-- ============================================================================
-- Миграция 267: уволенный из последней школы больше в неё не попадает.
-- ============================================================================
--
-- ═══ ЧТО СЛОМАНО ═══════════════════════════════════════════════════════════
--
-- `fn_my_active_school()` (миграция 259) кончается запасным ходом: нет
-- сохранённого выбора — берём `teachers.school_id`, домашнюю школу из строки
-- человека. Запасной ход не спрашивал, работает ли человек там ВООБЩЕ.
--
-- Замер 06.09.2026: Диане сняли все связи `teacher_schools`, и она по-прежнему
-- видела 25 своих уроков — функция вернула домашнюю школу, будто ничего не
-- произошло. То есть «уволить из школы» не увольняло: связь снята, а доступ
-- остался.
--
-- Пока увольнения из ОДНОЙ школы не существовало, это никого не задевало:
-- человека либо удаляли целиком вместе с учётной записью, либо не трогали.
-- С девятым заходом появилось увольнение из одной школы — и дыра стала
-- рабочей.
--
-- ═══ ЧТО МЕНЯЕТСЯ ══════════════════════════════════════════════════════════
--
-- Порядок ответа: выбранная школа → домашняя → любая действующая связь → пусто.
--
--   1. ВЫБРАННАЯ. Как была: сохранённый выбор, если по нему есть действующая
--      связь. Не изменилось ни строчки.
--   2. ДОМАШНЯЯ — ТЕПЕРЬ С ОГОВОРКОЙ. Отдаётся, только если по ней есть
--      действующая связь ИЛИ связей у человека нет вовсе. Второе — про
--      наследие: у кого связей не заведено, тот работает как до цепочки.
--   3. ЛЮБАЯ ДЕЙСТВУЮЩАЯ. Уволили из домашней, а в другой школе он остался —
--      человек не должен оказаться нигде. Код увольнения переставляет
--      домашнюю школу сам, но полагаться на одну лишь аккуратность кода в
--      таком месте нельзя.
--   4. ПУСТО. Действующих связей не осталось ни одной — школы у человека нет.
--      Правила доступа сравнивают со `school_id`, а сравнение с NULL ложно,
--      значит он не увидит ничего. Это и есть увольнение.
--
-- ═══ КОГО ЭТО ЗАДЕВАЕТ СЕГОДНЯ ═════════════════════════════════════════════
--
-- Никого. У всех двенадцати учителей ровно по одной ДЕЙСТВУЮЩЕЙ связи, и она
-- же домашняя школа: и до, и после правки функция отдаёт одно и то же.
-- Проверено прогоном по всем двенадцати.
--
-- Ветки ученика, родителя и админа в `current_school_id()` не тронуты: связей
-- у них не бывает, и эта функция их не касается.
-- ============================================================================

BEGIN;

CREATE OR REPLACE FUNCTION public.fn_my_active_school()
RETURNS uuid
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT COALESCE(
    -- 1. Выбранная школа, если она всё ещё его.
    (
      SELECT a.school_id
        FROM public.staff_active_school a
       WHERE a.user_id = auth.uid()
         AND EXISTS (
           SELECT 1 FROM public.teacher_schools ts
             JOIN public.teachers t ON t.id = ts.teacher_id
            WHERE t.user_id = auth.uid()
              AND ts.school_id = a.school_id
              AND ts.is_active
         )
    ),
    -- 2. Домашняя школа — но только пока он там числится. Либо наследие: у
    --    человека нет ни одной связи, и тогда домашняя школа единственный
    --    ответ, какой у нас есть.
    (
      SELECT t.school_id
        FROM public.teachers t
       WHERE t.user_id = auth.uid()
         AND (
           NOT EXISTS (SELECT 1 FROM public.teacher_schools ts WHERE ts.teacher_id = t.id)
           OR EXISTS (
             SELECT 1 FROM public.teacher_schools ts
              WHERE ts.teacher_id = t.id AND ts.school_id = t.school_id AND ts.is_active
           )
         )
       LIMIT 1
    ),
    -- 3. Уволен из домашней, но где-то ещё работает.
    (
      SELECT ts.school_id
        FROM public.teacher_schools ts
        JOIN public.teachers t ON t.id = ts.teacher_id
       WHERE t.user_id = auth.uid() AND ts.is_active
       ORDER BY ts.school_id
       LIMIT 1
    )
    -- 4. Ничего из перечисленного — NULL. Школы у человека нет.
  )
$function$;

COMMENT ON FUNCTION public.fn_my_active_school() IS
  'Школа сотрудника СЕЙЧАС: выбранная (если по ней есть действующая связь), иначе домашняя (пока он там числится либо пока связей нет вовсе — наследие), иначе любая действующая связь, иначе NULL. NULL означает «не работает ни в одной школе»: правила доступа сравнивают со school_id, и сравнение с NULL ложно.';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_тело text;
BEGIN
  SELECT prosrc INTO v_тело FROM pg_proc
   WHERE proname = 'fn_my_active_school' AND pronamespace = 'public'::regnamespace;

  IF v_тело NOT LIKE '%NOT EXISTS%' THEN
    RAISE EXCEPTION '267: запасной ход по-прежнему отдаёт домашнюю школу без оглядки на связи';
  END IF;

  -- Функция обязана остаться SECURITY DEFINER: без этого она не увидит
  -- teacher_schools из-под правил доступа и начнёт врать всем.
  IF NOT EXISTS (
    SELECT 1 FROM pg_proc
     WHERE proname = 'fn_my_active_school' AND pronamespace = 'public'::regnamespace
       AND prosecdef
  ) THEN
    RAISE EXCEPTION '267: функция перестала быть SECURITY DEFINER';
  END IF;

  RAISE NOTICE '267: без действующей связи школы у человека нет';
END $$;

COMMIT;
