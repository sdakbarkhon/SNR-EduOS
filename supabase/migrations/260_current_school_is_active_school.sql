-- ============================================================================
-- Миграция 260, срез 0: «моя школа» для учителя — та, которую он выбрал.
-- ============================================================================
--
-- ═══ ЧТО МЕНЯЕТСЯ И ПОЧЕМУ ЗДЕСЬ, А НЕ В ВОСЬМИДЕСЯТИ ВОСЬМИ ПРАВИЛАХ ══════
--
-- Восемьдесят восемь правил проверяют школу учителю, и ВСЕ ВОСЕМЬДЕСЯТ ВОСЕМЬ
-- делают это одной и той же фразой: `school_id = current_school_id()`.
-- Восемьдесят шесть узнают учителя по привязке (is_my_teacher_group,
-- current_teacher_id), ещё два — по самому факту «он учитель»
-- (h5p_content insert by teacher, teacher reads library material groups).
-- Форма проверки у всех одна.
--
-- Значит переписывать нужно не восемьдесят восемь предикатов, а один ответ на
-- вопрос «а какая школа моя». Восемьдесят восемь переписанных длинных правил —
-- это восемьдесят восемь возможностей ошибиться, и ни одной выгоды.
--
-- ═══ ПОЧЕМУ ЭТО НЕ ЛОМАЕТ ЗАПИСЬ ═══════════════════════════════════════════
--
-- Пятьдесят девять колонок пишут школу умолчанием `current_school_id()`.
-- Правя функцию, мы двигаем чтение и запись ОДНОВРЕМЕННО: правило ждёт
-- выбранную школу — умолчание её же и пишет.
--
-- Переписав вместо этого правила, мы получили бы разрыв: правило ждёт школу Б,
-- умолчание пишет школу А, вставка не проходит собственную проверку. Учитель
-- во второй школе не смог бы создать ничего, пока не доедет третий заход.
--
-- ═══ ПОЧЕМУ СЕГОДНЯ НЕ МЕНЯЕТСЯ НИЧЕГО ═════════════════════════════════════
--
-- Переключателя нет, `staff_active_school` пуста, у каждого из двенадцати
-- учителей ровно одна школа. Функция вернёт домашнюю — ту же, что вчера.
-- Числа «до» и «после» обязаны совпасть до единицы, и это проверяется
-- прогоном, а не обещанием.
--
-- ═══ ЧЕГО ЭТА МИГРАЦИЯ НЕ ДЕЛАЕТ ═══════════════════════════════════════════
--
-- ВЕТКИ УЧЕНИКА, РОДИТЕЛЯ И АДМИНА НЕ ТРОНУТЫ — они слово в слово те же, что
-- в миграции 82. Меняется одна ветка из четырёх.
--
-- Ни одно правило доступа не переписано. Ни одно умолчание не тронуто.
-- teachers.school_id остаётся домашней школой и запасным ответом.
--
-- ═══ ЧТО БУДЕТ, ЕСЛИ ВЫБОРА НЕТ ИЛИ СВЯЗЬ ПРОПАЛА ══════════════════════════
--
-- Ответ один: домашняя школа. Пусто не возвращается никогда — пустая школа
-- означала бы «школы нет» и погасила бы учителю всё разом. Поэтому:
--
--   строки в staff_active_school нет           -> домашняя;
--   выбрана школа, где связь снята или удалена  -> домашняя;
--   связей нет вовсе                            -> домашняя.
--
-- Последнее важно: связь заводится администрацией, и учитель, которому её
-- ещё не завели, обязан работать как раньше, а не потерять доступ.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.current_school_id()
RETURNS uuid
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  -- Ученик — как было (миграция 82), слово в слово.
  SELECT school_id FROM public.students WHERE user_id = auth.uid()
  UNION ALL
  -- Учитель — единственная изменённая ветка. Ответ считает
  -- fn_my_active_school() (миграция 259): выбранная школа, если связь с ней
  -- жива, иначе домашняя. Второй копии этого правила здесь нет намеренно —
  -- «где я сейчас» должно считаться в одном месте.
  SELECT public.fn_my_active_school()
    FROM public.teachers WHERE user_id = auth.uid()
  UNION ALL
  -- Админ — как было.
  SELECT school_id FROM public.admins WHERE user_id = auth.uid()
  UNION ALL
  -- Родитель — как было.
  SELECT school_id FROM public.parents WHERE user_id = auth.uid()
  LIMIT 1
$function$;

COMMENT ON FUNCTION public.current_school_id() IS
  'Школа текущего пользователя. У ученика, админа и родителя — из его записи. У учителя — та, которую он выбрал (staff_active_school), если связь с ней жива, иначе домашняя teachers.school_id. Пусто не возвращает никогда, пока запись человека существует.';

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_teachers integer;
  v_no_link  integer;
BEGIN
  SELECT count(*) INTO v_teachers FROM public.teachers;
  SELECT count(*) INTO v_no_link
    FROM public.teachers t
   WHERE NOT EXISTS (SELECT 1 FROM public.teacher_schools ts WHERE ts.teacher_id = t.id);
  RAISE NOTICE '260: учителей %, из них без связи со школой % (им отвечает домашняя школа)',
    v_teachers, v_no_link;

  -- Функция обязана существовать и остаться SECURITY DEFINER: без этого она
  -- перестала бы видеть строки, по которым считает, и вернула бы пусто.
  IF NOT EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public' AND p.proname = 'current_school_id' AND p.prosecdef
  ) THEN
    RAISE EXCEPTION '260: current_school_id перестала быть SECURITY DEFINER';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
     WHERE n.nspname = 'public' AND p.proname = 'fn_my_active_school'
  ) THEN
    RAISE EXCEPTION '260: нет fn_my_active_school — сначала применяется 259';
  END IF;
END $$;
