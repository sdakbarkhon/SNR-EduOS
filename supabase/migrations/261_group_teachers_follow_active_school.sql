-- ============================================================================
-- Миграция 261, срез 1 (люди и группы): привязки следуют за выбранной школой.
-- ============================================================================
--
-- ═══ ЕДИНСТВЕННОЕ ПРАВИЛО СРЕЗА, КОТОРОЕ ПРИШЛОСЬ ТРОНУТЬ ═════════════════
--
-- Остальные восемь таблиц среза (students, student_groups, groups, projects и
-- вложенные) сверяют школу через current_school_id() и уже поехали за
-- выбором вместе с ней — миграцией 260. Проверено прогоном: 12 учителей из
-- 12 видят только свою школу, чужих строк ноль.
--
-- group_teachers отвечала иначе. Её учительская ветка читалась так:
--
--     teacher_id = current_teacher_id()
--
-- Школы в ней нет вовсе — школа стоит только в ветке админа. Поэтому учитель
-- двух школ видел свои привязки ОБЕИХ сразу, тогда как группы — только
-- выбранной школы: список привязок к группам, которых он в этот момент
-- прочитать не может.
--
-- ЭТО НЕ БЫЛО ДЫРОЙ. Чужого правило не показывало никогда: `teacher_id =
-- current_teacher_id()` — это собственные строки человека и ничьи больше.
-- Правится не опасность, а разнобой: восемь таблиц среза отвечают «выбранная
-- школа», девятая отвечала «все мои сразу».
--
-- ═══ ЧТО ИМЕННО МЕНЯЕТСЯ ══════════════════════════════════════════════════
--
-- В первую ветку добавляется одно условие — школа строки должна совпасть с
-- выбранной. Ветки админа и суперадмина переносятся СЛОВО В СЛОВО.
--
-- ЗАПИСЬ НЕ ТРОГАЕТСЯ. Привязки пишет админ при назначении, и делает это
-- служебным ключом (lib/admin-api.ts, linkTeacherToGroup), который правила
-- обходит. Кроме чтения у таблицы ещё ЧЕТЫРЕ правила: `admin manages
-- group_teachers` (FOR ALL, им админ и пишет, и читает) и три сторожа
-- суперадмина (sa_write_allowed). Ни одно из четырёх здесь не упоминается.
--
-- ═══ ЧТО МЕНЯЕТСЯ СЕГОДНЯ ═════════════════════════════════════════════════
--
-- Ничего. У всех двенадцати учителей ровно одна школа, все их привязки в ней:
-- 3/3/3/3/2 в демо-школе и по 1 у остальных. Числа обязаны остаться теми же —
-- это проверяется прогоном, а не обещанием.
-- ============================================================================

DROP POLICY IF EXISTS "read own group_teachers rows" ON public.group_teachers;
CREATE POLICY "read own group_teachers rows"
  ON public.group_teachers FOR SELECT
  USING (
    -- Свои привязки — но только в школе, в которой я сейчас.
    (teacher_id = public.current_teacher_id() AND school_id = public.current_school_id())
    -- Ветка админа — как была.
    OR (public.fn_is_admin() AND school_id = public.current_school_id())
    -- Ветка суперадмина — как была.
    OR public.is_super_admin()
  );

-- ── Самопроверка ────────────────────────────────────────────────────────────
DO $$
DECLARE
  v_read  integer;
  v_write integer;
BEGIN
  -- Правило чтения одно, и оно знает про школу.
  SELECT count(*) INTO v_read FROM pg_policies
   WHERE schemaname='public' AND tablename='group_teachers' AND cmd='SELECT'
     AND qual LIKE '%current_teacher_id()%' AND qual LIKE '%current_school_id()%';
  IF v_read <> 1 THEN
    RAISE EXCEPTION '261: правило чтения group_teachers не переведено на выбранную школу (найдено %)', v_read;
  END IF;

  -- Остальные правила на месте и по именам: правка не должна была задеть ни
  -- ветку админа (admin manages group_teachers, FOR ALL), ни трёх сторожей
  -- суперадмина. Считаем по именам, а не числом: число ничего не докажет.
  SELECT count(*) INTO v_write FROM pg_policies
   WHERE schemaname='public' AND tablename='group_teachers'
     AND policyname IN ('admin manages group_teachers',
                        'superadmin write guard insert',
                        'superadmin write guard update',
                        'superadmin write guard delete');
  IF v_write <> 4 THEN
    RAISE EXCEPTION '261: из четырёх правил записи на месте только %', v_write;
  END IF;

  RAISE NOTICE '261: чтение переведено на выбранную школу, четыре правила записи не тронуты';
END $$;
