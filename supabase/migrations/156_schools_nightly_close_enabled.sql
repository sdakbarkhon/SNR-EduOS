BEGIN;

ALTER TABLE public.schools
  ADD COLUMN IF NOT EXISTS nightly_close_enabled boolean NOT NULL DEFAULT true;

-- Демо-школа — единственное исключение; реальная школа (и любая будущая)
-- остаётся на DEFAULT true, поведение не меняется ни на бит.
UPDATE public.schools
  SET nightly_close_enabled = false
  WHERE id = 'a0a0a0a0-0000-0000-0000-000000000001';

COMMIT;
