import { subjects, defaultSubjectStyle } from "./subjects";

/**
 * ОДНО МЕСТО, КОТОРОЕ ОТВЕЧАЕТ «КАК ВЫГЛЯДИТ ЭТОТ ПРЕДМЕТ». 04.09.2026.
 *
 * ═══ ЗАЧЕМ ════════════════════════════════════════════════════════════════
 *
 * Подпись, значок и цвет предмета сегодня берутся из ДВУХ разных мест, и какое
 * из них сработает — решает случайность того, что оказалось на руках у экрана:
 *
 *   есть строка справочника школы -> берём name/icon/color оттуда;
 *   на руках только слаг          -> берём из словаря packages/core/config.
 *
 * Второй путь — временный. Словарь названий уходит в конце этой цепочки
 * заходов: школа заводит свои предметы, и списка в коде быть не должно. Но
 * пока он жив, ключуемые слагом экраны (оценки, посещаемость, книги,
 * библиотека кафедры, шапка учителя, аналитика) без него подписались бы словом
 * «Предмет».
 *
 * Поэтому резолвер один, а источников у него два, и он ГОВОРИТ, откуда взял:
 * поле `source`. Когда словарь уйдёт, «dictionary» просто перестанет
 * появляться — и это будет видно, а не случится молча.
 *
 * ═══ ЧТО ВОЗВРАЩАЕТ ═══════════════════════════════════════════════════════
 *
 * `icon` — ИМЯ значка строкой, а не компонент: ядро общее для веба и
 * мобильного, и тянуть сюда react-иконки нельзя. Имя разворачивает в картинку
 * единый реестр веба (`apps/web/lib/subject-icons`), сведённый прошлым
 * заходом. Второго реестра здесь нет и не будет.
 *
 * ═══ ТРИ ЯЗЫКА — ЧЕСТНЫЙ ОТВЕТ ════════════════════════════════════════════
 *
 * Подпись НЕ ПЕРЕВОДИТСЯ, и переводить её сегодня нечем. Справочник школы
 * хранит одно название одной строкой (`school_subjects.name`) — то, что набрал
 * админ. Места под перевод в схеме нет, а словарь в коде держит только русские
 * подписи: взять английскую «Robotics» неоткуда.
 *
 * Это осознанный выбор, а не упущение: название предмета — слово школы.
 * «Схемотехника» и «Science» набраны так, как их называют в этой школе, и
 * подменять их переводом значило бы решать за неё.
 *
 * РАЗВИЛКА НА БУДУЩЕЕ (решение заказчика, не моё): если переводы понадобятся —
 * это колонка `name_i18n jsonb` у справочника плюс поля в форме админа,
 * отдельный заход с миграцией. До тех пор во всех трёх языках показывается то,
 * что написала школа.
 */

/** Откуда взялись подпись, значок и цвет. */
export type SubjectStyleSource =
  /** Строка справочника школы — то, что завёл админ. Правильный путь. */
  | "catalog"
  /** Словарь названий в коде. Временный путь, уходит в конце цепочки. */
  | "dictionary"
  /** Не нашли ничего: прочерк, книжка и общий цвет продукта. */
  | "fallback";

export type ResolvedSubject = {
  /** Подпись как её показывать человеку. Прочерк, если предмета нет. */
  label: string;
  /** ИМЯ значка (PascalCase, как в базе). Разворачивает реестр веба. */
  icon: string;
  color: string;
  source: SubjectStyleSource;
};

/** Строка справочника школы — ровно те поля, что нужны для показа. */
export type SubjectCatalogRow = {
  name?: string | null;
  icon?: string | null;
  color?: string | null;
};

/**
 * Что известно о предмете на месте вызова. Экраны знают разное: у одних есть
 * готовая строка справочника, у других — только слаг из своей колонки.
 */
export type SubjectHint = {
  /** Строка справочника или назначения (subjects / school_subjects). */
  catalog?: SubjectCatalogRow | null;
  /** Слаг из колонки: teachers.subject_slug, books.subject и подобных. */
  slug?: string | null;
  /**
   * Справочник школы целиком — если экран его загрузил. Позволяет найти
   * строку ПО СЛАГУ: у справочника колонки слага нет, поэтому мост один —
   * подпись словаря. Уйдёт словарь — уйдёт и мост, вместе с ним.
   */
  schoolCatalog?: ReadonlyArray<SubjectCatalogRow> | null;
};

const ПРОЧЕРК = "—";

/**
 * Запасной значок ИМЕНЕМ КАК В БАЗЕ. `defaultSubjectStyle.icon` держит
 * написание словаря (kebab), а договор этого резолвера — PascalCase. Реестр
 * веба понимает оба, но отдавать наружу два написания из одного места значит
 * заново заводить ту самую путаницу, которую вчера свели.
 */
const ЗАПАСНОЙ_ЗНАЧОК = "BookOpen";

/** Готова ли строка справочника к показу: имя есть, значит и остальное берём. */
function изСправочника(row: SubjectCatalogRow | null | undefined): ResolvedSubject | null {
  const label = (row?.name ?? "").trim();
  if (!label) return null;
  return {
    label,
    icon: (row?.icon ?? "").trim() || ЗАПАСНОЙ_ЗНАЧОК,
    color: (row?.color ?? "").trim() || defaultSubjectStyle.color,
    source: "catalog",
  };
}

/**
 * Подпись, значок и цвет предмета — из справочника школы, а при его нехватке
 * из словаря кода.
 *
 * ПОРЯДОК ИСТОЧНИКОВ, ОТ ЛУЧШЕГО К ХУДШЕМУ:
 *   1. переданная строка справочника;
 *   2. строка справочника школы, найденная по слагу через подпись словаря;
 *   3. сам словарь по слагу;
 *   4. прочерк, книжка и общий цвет продукта.
 */
export function resolveSubject(hint: SubjectHint): ResolvedSubject {
  const прямо = изСправочника(hint.catalog);
  if (прямо) return прямо;

  const slug = (hint.slug ?? "").trim();
  const словарное = slug ? subjects[slug] : undefined;

  if (slug && hint.schoolCatalog && hint.schoolCatalog.length > 0) {
    // Мост «слаг → строка справочника»: у справочника слага нет, поэтому
    // сверяем по подписи. Совпало — показываем школьное, а не словарное:
    // школа могла сменить и цвет, и значок, и это её право.
    const поПодписи = словарное?.label
      ? hint.schoolCatalog.find((r) => (r.name ?? "").trim() === словарное.label)
      : undefined;
    const поИмени = hint.schoolCatalog.find((r) => (r.name ?? "").trim() === slug);
    const найдено = изСправочника(поПодписи ?? поИмени);
    if (найдено) return найдено;
  }

  if (словарное) {
    return { label: словарное.label, icon: словарное.icon, color: словарное.color, source: "dictionary" };
  }

  // Слаг, которого нет ни в справочнике, ни в словаре, — это чаще всего
  // название предмета, попавшее в slug-колонку (так лежат «Схемотехника» и
  // «Science» в groups.subject). Показываем его как есть: собственное имя
  // лучше слова «Предмет».
  if (slug) {
    return { label: slug, icon: ЗАПАСНОЙ_ЗНАЧОК, color: defaultSubjectStyle.color, source: "fallback" };
  }

  return { label: ПРОЧЕРК, icon: ЗАПАСНОЙ_ЗНАЧОК, color: defaultSubjectStyle.color, source: "fallback" };
}
