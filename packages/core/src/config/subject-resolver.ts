/** Откуда взялись подпись, значок и цвет. */
export type SubjectStyleSource =
  /** Строка справочника школы — то, что завёл админ. Правильный путь. */
  | "catalog"
  /** Словарь названий в коде. Снесён 06.09.2026 — не возвращается никогда. */
  | "dictionary"
  /** Не нашли ничего: прочерк, книжка и общий цвет продукта. */
  | "fallback";

export type ResolvedSubject = {
  /** Подпись как её показывать человеку. Прочерк, если предмета нет. */
  label: string;
  /** ИМЯ значка (PascalCase, как в базе). Разворачивает реестр веба. */
  icon: string;
  color: string;
  source: SubjectStyleSource;
};

/** Строка справочника школы — ровно те поля, что нужны для показа. */
export type SubjectCatalogRow = {
  name?: string | null;
  icon?: string | null;
  color?: string | null;
};

/**
 * Что известно о предмете на месте вызова. Экраны знают разное: у одних есть
 * готовая строка справочника, у других — только слаг из своей колонки.
 */
export type SubjectHint = {
  /** Строка справочника или назначения (subjects / school_subjects). */
  catalog?: SubjectCatalogRow | null;
  /**
   * Значение старой колонки: `books.subject`, `course_materials.subject`,
   * `teachers.subject_slug`. Где-то там имя предмета, где-то ещё слаг —
   * резолвер и то и другое показывает как есть, если пары не нашлось.
   */
  slug?: string | null;
  /**
   * Справочник школы целиком — если экран его загрузил. Строка ищется ПО
   * НАЗВАНИЮ: в старых колонках (`books.subject`, `course_materials.subject`)
   * лежит имя предмета, и сверять есть с чем.
   */
  schoolCatalog?: ReadonlyArray<SubjectCatalogRow> | null;
};

const ПРОЧЕРК = "—";

/**
 * Общий цвет продукта — на случай, когда красить нечем. Раньше он приходил из
 * `defaultSubjectStyle` вместе со словарём названий; словарь снесён
 * 06.09.2026, а цвет остался тем же.
 */
const ЗАПАСНОЙ_ЦВЕТ = "#7C63F0";

/** Запасной значок ИМЕНЕМ КАК В БАЗЕ (PascalCase) — договор этого резолвера. */
const ЗАПАСНОЙ_ЗНАЧОК = "BookOpen";

/** Готова ли строка справочника к показу: имя есть, значит и остальное берём. */
function изСправочника(row: SubjectCatalogRow | null | undefined): ResolvedSubject | null {
  const label = (row?.name ?? "").trim();
  if (!label) return null;
  return {
    label,
    icon: (row?.icon ?? "").trim() || ЗАПАСНОЙ_ЗНАЧОК,
    color: (row?.color ?? "").trim() || ЗАПАСНОЙ_ЦВЕТ,
    source: "catalog",
  };
}

/**
 * Подпись, значок и цвет предмета — из справочника школы.
 *
 * ПОРЯДОК ИСТОЧНИКОВ, ОТ ЛУЧШЕГО К ХУДШЕМУ:
 *   1. переданная строка справочника;
 *   2. строка справочника школы, найденная по названию;
 *   3. значение старой колонки как есть;
 *   4. прочерк, книжка и общий цвет продукта.
 */
export function resolveSubject(hint: SubjectHint): ResolvedSubject {
  const прямо = изСправочника(hint.catalog);
  if (прямо) return прямо;

  const slug = (hint.slug ?? "").trim();

  if (slug && hint.schoolCatalog && hint.schoolCatalog.length > 0) {
    // Строку справочника ищем ПО НАЗВАНИЮ: в этих колонках давно лежит имя
    // предмета, а не слаг. Мост через словарь кода снесён вместе со словарём.
    const найдено = изСправочника(
      hint.schoolCatalog.find((r) => (r.name ?? "").trim() === slug),
    );
    if (найдено) return найдено;
  }

  // Пары в справочнике нет. Показываем то, что лежит в колонке, как есть:
  // собственное имя лучше слова «Предмет», а выдумывать за школу нечего.
  if (slug) {
    return { label: slug, icon: ЗАПАСНОЙ_ЗНАЧОК, color: ЗАПАСНОЙ_ЦВЕТ, source: "fallback" };
  }

  return { label: ПРОЧЕРК, icon: ЗАПАСНОЙ_ЗНАЧОК, color: ЗАПАСНОЙ_ЦВЕТ, source: "fallback" };
}
