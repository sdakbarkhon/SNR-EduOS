/**
 * Замок на выставленное учителем. Миграции 203, 218, 225, 245.
 *
 * ПРАВИЛО ЦЕЛИКОМ, в одном месте:
 *
 *   1. Отметки времени нет — это первое выставление, замок ни при чём.
 *   2. С выставления прошло меньше 15 минут — правится.
 *   3. Урок ещё ИДЁТ (status = in_progress) — правится, сколько бы времени
 *      ни прошло. Учитель внутри своего урока, запирать его не за что.
 *   4. Иначе заперто: менять может только администратор школы.
 *
 * Пункт 3 добавлен 31.08.2026 миграцией 245. Он касается только отметок
 * ВНУТРИ урока: переклички, оценки за урок, оценки за этап. Домашние задания
 * и тесты к уроку не привязаны — у них урока нет, и правило до них не
 * доходит. Поэтому `lesson` в запросе обязателен: для отметки вне урока в
 * него передают `null`, но забыть его нельзя — не даст компилятор. Копий
 * этого правила по экранам быть не должно: на среднем балле копии в этом
 * проекте расходились семь раз.
 *
 * ЗДЕСЬ ТОЛЬКО СЧЁТ ДЛЯ ИНТЕРФЕЙСА. Настоящий запрет стоит триггером в базе
 * (fn_lock_teacher_marks), обойти его через API нельзя. Задача этого файла —
 * не разрешить того, что база отобьёт, и не запретить того, что база
 * разрешает.
 *
 * ОТ КАКОГО ВРЕМЕНИ СЧИТАЕМ. От настоящих часов, а не от «школьного»
 * замороженного времени: метки graded_at/marked_at пишет now() базы. Сравнивать
 * их с замороженной датой школы значило бы сравнивать разные шкалы — в
 * демо-школе всё запиралось бы в ту же секунду.
 */

/** Столько времени у учителя на исправление. Держать в синхроне с
 *  public.mark_edit_window() — там та же величина, и она главная. */
export const MARK_EDIT_WINDOW_MINUTES = 15;

/** Статус урока: те же три значения, что и в lessons_status_check. */
export type LessonLockStatus = "scheduled" | "in_progress" | "completed";

export type MarkLockQuery = {
  /** graded_at или marked_at записи; null — ещё не выставляли. */
  stamp: string | null | undefined;
  /**
   * Статус урока, к которому относится отметка, — или `null`, если отметка к
   * уроку не привязана (домашнее задание, тест). Поле обязательное намеренно:
   * пропустить его нельзя, иначе правило начнёт расходиться по экранам.
   */
  lesson: LessonLockStatus | null;
  /**
   * Текущее время в миллисекундах; передаётся, чтобы экран мог пересчитывать
   * состояние по таймеру, не дёргая часы внутри рендера.
   */
  nowMs?: number;
};

export type MarkLockState = {
  /** true — менять значение может только администратор школы. */
  locked: boolean;
  /** Сколько целых минут ещё можно править (0, если окно уже вышло). */
  minutesLeft: number;
  /** Значения ещё нет — это выставление, а не изменение: замок не при чём. */
  notSetYet: boolean;
  /**
   * Урок идёт, и поэтому отсчёт пятнадцати минут ничего не решает. Для
   * интерфейса: показывать не обратный отсчёт, а «урок идёт — правится
   * свободно». Обратный отсчёт во время урока был бы прямой ложью — он
   * обещает срок, которого нет.
   */
  freeWhileLesson: boolean;
};

/**
 * Состояние замка по отметке времени выставления и статусу урока.
 *
 * Порядок проверок здесь тот же, что в теле fn_lock_teacher_marks: сначала
 * «отметки нет», потом пятнадцать минут, и только потом идущий урок. Ответ
 * `locked` от порядка не зависит (разрешено = уложился в окно ИЛИ урок идёт),
 * но одинаковый порядок нужен, чтобы файл и миграцию можно было читать рядом.
 */
export function markLockState({ stamp, lesson, nowMs = Date.now() }: MarkLockQuery): MarkLockState {
  // Урок идёт — обратного отсчёта нет, что бы ни показывали часы. Считаем
  // отдельно от ответа `locked`, чтобы не менять порядок проверок ниже.
  const свободноПокаУрокИдёт = lesson === "in_progress";

  if (!stamp) {
    return {
      locked: false,
      minutesLeft: MARK_EDIT_WINDOW_MINUTES,
      notSetYet: true,
      freeWhileLesson: свободноПокаУрокИдёт,
    };
  }

  const setAt = Date.parse(stamp);
  if (Number.isNaN(setAt)) {
    // Непонятная метка — не запираем: лучше пустить, чем молча запретить.
    return {
      locked: false,
      minutesLeft: MARK_EDIT_WINDOW_MINUTES,
      notSetYet: false,
      freeWhileLesson: свободноПокаУрокИдёт,
    };
  }

  const leftMs = setAt + MARK_EDIT_WINDOW_MINUTES * 60_000 - nowMs;
  if (leftMs > 0) {
    return {
      locked: false,
      minutesLeft: Math.max(1, Math.ceil(leftMs / 60_000)),
      notSetYet: false,
      freeWhileLesson: свободноПокаУрокИдёт,
    };
  }

  // Пятнадцать минут вышли. Последний вопрос — ровно тот, что задаёт база.
  if (свободноПокаУрокИдёт) {
    return { locked: false, minutesLeft: 0, notSetYet: false, freeWhileLesson: true };
  }

  return { locked: true, minutesLeft: 0, notSetYet: false, freeWhileLesson: false };
}

/** Узнаёт отказ базы «запись заперта» среди прочих ошибок. */
export function isMarkLockedError(err: unknown): boolean {
  const raw =
    typeof err === "string"
      ? err
      : err && typeof err === "object" && "message" in err
        ? String((err as { message?: unknown }).message ?? "")
        : "";
  return /mark_locked/i.test(raw);
}
