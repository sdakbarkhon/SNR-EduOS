//
// 03.09.2026 разборщик очереди записал в базу «[object Object]» вместо
// причины отказа. Там стояло `String(e)`, а supabase-js бросает не Error, а
// обычный объект с полями message, code, details, hint — и `String` от него
// даёт ровно эту бесполезную строку. Разбор занял отдельную пробу с откатом,
// которой не понадобилось бы, скажи запись правду сразу.
//
// Тогда же чинилось одно место — разборщик. Но экран очереди (заход Q4) зовёт
// функции базы напрямую из браузера и ловит ТОТ ЖЕ вид ошибки. Написать здесь
// вторую копию значило бы завести ту же беду заново с другой стороны: в этом
// проекте копии правил расходились семь раз на одном только среднем балле.
//
// Поэтому правило одно и живёт здесь, а разборщик и экран его зовут.

/**
 * Разворачивает ошибку в текст, который можно показать человеку и положить
 * в базу.
 *
 * Понимает три вида:
 *   - настоящий `Error` — берёт `message`;
 *   - объект в стиле postgrest/supabase-js — склеивает message, details, hint
 *     и приписывает код в квадратных скобках (код нужен: по нему ищут, а
 *     «23502» человеку скажет мало, зато нам — всё);
 *   - что угодно ещё — пытается сериализовать, и только в крайнем случае
 *     отдаёт `String(e)`.
 */
export function describeError(e: unknown): string {
  if (e instanceof Error) return e.message;
  if (e && typeof e === "object") {
    const o = e as { message?: unknown; code?: unknown; details?: unknown; hint?: unknown };
    const куски = [o.message, o.details, o.hint].filter((x): x is string => typeof x === "string" && x !== "");
    const код = typeof o.code === "string" && o.code ? ` [${o.code}]` : "";
    if (куски.length) return куски.join(" — ") + код;
    try {
      const json = JSON.stringify(e);
      // «{}» — это не текст ошибки, это её отсутствие. Лучше честно сказать,
      // что причины нет, чем показать пустые скобки.
      if (json && json !== "{}") return json.slice(0, 300);
    } catch {
      /* не сериализуется — падаём в String ниже */
    }
  }
  return String(e);
}
