/**
 * Подпись кабинета. 24.08.2026.
 *
 * БЕДА. В базе `lessons.room` у части уроков хранит уже готовую фразу со
 * словом: в демо-школе у всех 126 уроков там записано «Кабинет 101». Экраны
 * же дописывают перед значением свою подпись — и выходит «каб. Кабинет 101».
 * Для новых уроков это уже поправили в форме создания, но 126 старых записей
 * остались, и переписывать их задним числом — правка данных ради вида.
 *
 * ЛЕЧИМ НА ЭКРАНЕ. Если значение само начинается со слова «кабинет» — второй
 * раз его не пишем.
 *
 * ПОЧЕМУ СЛОВА ПЕРЕЧИСЛЕНЫ НА ТРЁХ ЯЗЫКАХ, А НЕ ВЗЯТЫ ИЗ СЛОВАРЯ. Язык
 * значения в базе не следует за языком интерфейса: «Кабинет 101» останется
 * русским и у родителя с узбекским телефоном. Сверяться только с активным
 * словарём значило бы починить двойное слово по-русски и оставить его на двух
 * других языках.
 *
 * «pixel room» (такое значение есть в боевой школе) под правило не попадает:
 * слово стоит не в начале, и подпись ему нужна.
 */

/** Слова, с которых может начинаться уже готовое название кабинета. */
const ROOM_WORDS = ["кабинет", "каб", "xona", "xonasi", "room"];

/** Значение уже несёт слово «кабинет» — подпись дописывать не надо. */
function startsWithRoomWord(value: string): boolean {
  const lower = value.toLowerCase();
  return ROOM_WORDS.some((w) => {
    if (!lower.startsWith(w)) return false;
    // Дальше должен идти разделитель, цифра или конец строки. Иначе «roomy»
    // и «кабинетчик» сошли бы за подпись. \b здесь не годится: он считает
    // границу по латинице и на кириллице ведёт себя не так, как ожидается.
    const rest = lower.slice(w.length);
    return rest === "" || /^[\s.,:№-]/.test(rest) || /^\d/.test(rest);
  });
}

/**
 * Готовая подпись кабинета или null, если кабинета нет.
 *
 * @param room  значение из lessons.room
 * @param label подпись из словаря активного языка («Кабинет» / «Xona» / «Room»)
 */
export function formatRoom(room: string | null | undefined, label: string): string | null {
  const value = (room ?? "").trim();
  if (!value) return null;
  return startsWithRoomWord(value) ? value : `${label} ${value}`;
}
