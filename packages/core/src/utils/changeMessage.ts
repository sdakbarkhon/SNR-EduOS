/**
 * ЧТО ИМЕННО ИЗМЕНИЛОСЬ — ОДНО ПРАВИЛО НА ВСЕ ФОРМЫ АДМИНА. 06.09.2026.
 *
 * ═══ ЧТО БЫЛО ══════════════════════════════════════════════════════════════
 *
 * Одна форма меняет разные по весу вещи, а сообщение было одно на всё:
 *
 *   «Данные ученика обновлены»   — а ученика перевели в другую группу:
 *                                  он вышел из чата класса, вышел из личных
 *                                  чатов с прежними учителями и завёл новые;
 *   «Данные родителя сохранены»  — а у него сменился список детей;
 *   ничего вообще                — назначения предмета создавались, менялись
 *                                  и удалялись молча, экран просто
 *                                  перерисовывался.
 *
 * Человек не знал, что сделал. Хуже неточной фразы: непонятно даже, сработало
 * ли вообще.
 *
 * ═══ ПРАВИЛО ═══════════════════════════════════════════════════════════════
 *
 * Сообщение называет ТО, ЧТО ИЗМЕНИЛОСЬ, а не перечисляет все поля. Поправили
 * одно имя — так и говорим.
 *
 * Перемены делятся на две корзины, и это единственное деление, которое здесь
 * есть:
 *
 *   ВЕСОМЫЕ — те, у которых есть последствия за пределами карточки: перевод
 *   между группами, снятие с группы, смена учителя у предмета, смена списка
 *   детей. За ними заводятся и снимаются чаты, появляется и пропадает доступ.
 *   Каждая называется отдельной готовой фразой.
 *
 *   СВЕДЕНИЯ — имя, логин, телефон, почта. Последствий за карточкой нет,
 *   называть каждое отдельной фразой незачем: хватает перечисления в одной
 *   строке.
 *
 * Есть весомые — говорим о них, а сведения дописываем следом, если их тоже
 * правили. Весомых нет — только строка про сведения. Нет ни того ни другого —
 * прямо говорим, что изменений не было: «сохранено» на несохранённом это тоже
 * неправда.
 *
 * ═══ ПОЧЕМУ ЗДЕСЬ, А НЕ НА КАЖДОМ ЭКРАНЕ ═══════════════════════════════════
 *
 * Экранов три, и правило у них одно. Разложенное по трём файлам, оно разошлось
 * бы на третьей правке — ровно так уже разошлись сами сообщения. Тексты
 * остаются в словарях, здесь только порядок сборки.
 *
 * ЧТО СЧИТАТЬ ПЕРЕМЕНОЙ — РЕШАЕТ ЭКРАН. Сравнивать умеет только он: у формы
 * ученика прежняя группа лежит в снимке карточки, у формы родителя — прежний
 * список детей. Сюда приходят уже готовые фразы.
 */

export interface ПеременыФормы {
  /** Перемены с последствиями. Каждая — законченная фраза с точкой. */
  весомые: string[];
  /** Правленые сведения. Только названия полей, без значений. */
  сведения: string[];
}

export interface ТекстыПеремен {
  /** Шаблон строки про сведения, с {fields}. Например «Поправлено: {fields}.»
   *  Не нужен формам, где править нечего, кроме весомого, — таков экран
   *  назначений: там предмет, группа и учитель, и мелочей нет вовсе. */
  сведения?: string;
  /** Что сказать, когда не изменилось ничего. */
  ничего: string;
}

/**
 * Собирает сообщение по правилу выше.
 *
 * Разделитель между фразами — пробел: каждая весомая перемена приходит
 * законченным предложением, склеивать их запятыми значило бы решать за
 * словарь, как они читаются вместе.
 */
export function сообщениеОПеременах(
  перемены: ПеременыФормы,
  тексты: ТекстыПеремен,
): string {
  const весомые = перемены.весомые.filter((ф) => ф.trim());
  const сведения = перемены.сведения.filter((ф) => ф.trim());

  const строкаСведений = сведения.length > 0 && тексты.сведения
    ? тексты.сведения.replace("{fields}", сведения.join(", "))
    : "";

  if (весомые.length === 0) return строкаСведений || тексты.ничего;
  return [...весомые, строкаСведений].filter(Boolean).join(" ");
}
