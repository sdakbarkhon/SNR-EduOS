/**
 * Длительность урока. Миграция 246.
 *
 * ПРАВИЛО. Одно число на школу — `schools.lesson_duration_minutes`. Его задаёт
 * суперадмин в карточке школы. Учитель длительность не спрашивается и задать
 * её не может: переопределений на отдельный урок нет намеренно, иначе
 * вернулись бы ровно те три источника одного числа, которые мы убрали.
 *
 * ЧИСЛА ЗДЕСЬ — КОПИЯ ГЛАВНОГО, А ГЛАВНОЕ В СХЕМЕ. Границы продублированы
 * ограничением `schools_lesson_duration_minutes_check` (BETWEEN 15 AND 180).
 * Здесь они нужны затем, чтобы форма отказывала ДО запроса и по-человечески, а
 * не показывала сырой текст про constraint. Меняются только вместе.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Число дёргают и сервер (роуты создания уроков), и
 * клиент (форма суперадмина), и общий слой (createLesson). Положить его в
 * queries значило бы тащить за собой supabase-клиент туда, где нужна одна
 * константа.
 */

/** Столько длится урок, если у школы почему-то ничего не прочиталось.
 *  Совпадает с умолчанием колонки (миграция 246) и с тем, что стоит у всех
 *  128 существующих уроков. */
export const DEFAULT_LESSON_DURATION_MINUTES = 45;

/** Короче четверти часа урок не бывает: окно правки отметок
 *  (public.mark_edit_window) — те же 15 минут, и урок короче него сделал бы
 *  правило «пока урок идёт» бессмысленным. Разбор — в шапке миграции 246. */
export const LESSON_DURATION_MIN_MINUTES = 15;

/** Три часа — сдвоенная пара или длинная мастерская. Пять часов это уже не
 *  урок, а день, и почти наверняка опечатка (450 вместо 45). */
export const LESSON_DURATION_MAX_MINUTES = 180;

/** Годится ли число в длительность урока. Целое и в границах. */
export function isValidLessonDuration(value: number): boolean {
  return Number.isInteger(value)
    && value >= LESSON_DURATION_MIN_MINUTES
    && value <= LESSON_DURATION_MAX_MINUTES;
}

/**
 * Разбор того, что человек напечатал в поле.
 *
 * Возвращает `null`, если поле пустое — это законный случай «не менял», и
 * вызывающий обязан отличать его от «напечатал чепуху». Для чепухи
 * возвращается `NaN`: она должна дойти до человека отказом, а не молча
 * превратиться в 45.
 */
export function parseLessonDuration(raw: string | null | undefined): number | null {
  const text = (raw ?? "").trim();
  if (!text) return null;
  if (!/^\d+$/.test(text)) return NaN;
  return Number(text);
}
