/** Таблица, из которой пришла оценка. Единственный признак разделения. */
export type GradeSource =
  | "homework_submissions"
  | "test_submissions"
  | "project_submissions"
  | "lesson_stage_progress"
  | "lesson_grades";

/**
 * Источники, которые в средний балл НЕ идут.
 *
 * Список исключений, а не разрешений, — намеренно: новая таблица с оценками
 * попадёт в средний балл сама, и это правильное поведение по умолчанию.
 * Забыть добавить источник в средний балл хуже, чем забыть исключить: в
 * первом случае оценка молча пропадает, во втором — видна и её замечают.
 */
const EXCLUDED_FROM_AVERAGE: ReadonlySet<GradeSource> = new Set<GradeSource>([
  "lesson_stage_progress",
]);

/** Идёт ли оценка из этого источника в средний балл. */
export function countsTowardAverage(source: GradeSource): boolean {
  return !EXCLUDED_FROM_AVERAGE.has(source);
}

/**
 * Единая нормировка сдачи теста к пятибалльной.
 *
 * ПОЧЕМУ СНАЧАЛА grade, А НЕ score/max_score. `grade` — это оценка на
 * пятибалльной шкале, которую видит ученик и которую проставляет проверка
 * теста (миграция 31). `score/max_score` — сырая доля правильных ответов;
 * такого числа никто на экране не видит, и оценкой оно не является.
 *
 * Разница не умозрительная: на живых данных 71 сдача из 120 даёт разные
 * значения (10 из 12 — это доля 4.17, а выставленная оценка 5), и средний по
 * школе расходится на 4.74 против 4.57. Пока в одном месте брали оценку, а в
 * другом долю, два экрана про одни и те же работы честно показывали разное.
 *
 * Доля остаётся запасным путём: у старых сдач `grade` пуст, и терять их
 * молча нельзя.
 */
export function testGrade5(sub: {
  grade?: number | null;
  score?: number | null;
  max_score?: number | null;
}): number | null {
  if (sub.grade != null) return sub.grade;
  const max = sub.max_score ?? 0;
  if (max > 0 && sub.score != null) return (sub.score / max) * 5;
  return null;
}

/**
 * Среднее по пятибалльным значениям.
 *
 * Пустые значения отбрасываются, а не считаются нулём: неоценённая работа —
 * это «ещё не проверили», а не «ноль». Пустой список даёт null, а не 0 —
 * иначе экран покажет «0.0» там, где оценок просто нет.
 */
export function averageOf(values: ReadonlyArray<number | null | undefined>): number | null {
  let sum = 0;
  let n = 0;
  for (const v of values) {
    if (v == null || Number.isNaN(v)) continue;
    sum += v;
    n += 1;
  }
  return n > 0 ? sum / n : null;
}

/** Оценка в том виде, в каком её знает средний балл. */
export type CountableGrade = {
  sourceTable: GradeSource;
  grade5: number | null;
};

/**
 * Среднее по списку оценок: сам отбрасывает источники, не идущие в средний
 * балл. Ровно та форма, в которой оценки лежат в StudentGradeItem.
 */
export function averageOfGrades(items: ReadonlyArray<CountableGrade>): number | null {
  return averageOf(items.filter((g) => countsTowardAverage(g.sourceTable)).map((g) => g.grade5));
}

/** Сколько оценок из списка реально участвует в среднем балле. */
export function countedGrades<T extends CountableGrade>(items: ReadonlyArray<T>): T[] {
  return items.filter((g) => countsTowardAverage(g.sourceTable) && g.grade5 != null);
}
