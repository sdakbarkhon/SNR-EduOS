/** Слово «класс» на трёх языках интерфейса — в названии группы оно лишнее. */
const CLASS_WORD = /[\s,]*(класс|klass|sinf|class)\s*$/i;

/** Сколько символов помещается в плашку 56×56 без уменьшения шрифта. */
const MAX_BADGE_LENGTH = 5;

/**
 * Короткое обозначение класса из названия группы.
 * «3-А класс» → «3-А», «10-А класс» → «10-А», «G-7» → «G-7».
 * «SNR Схемотехника» → null: класса в названии нет.
 */
export function groupClassLabel(name: string | null | undefined): string | null {
  const raw = (name ?? "").trim();
  if (!raw) return null;

  const withoutWord = raw.replace(CLASS_WORD, "").trim();
  if (!withoutWord) return null;

  // Пробел внутри — это уже не обозначение класса, а название («SNR Схемотехника»).
  if (/\s/.test(withoutWord)) return null;
  if (withoutWord.length > MAX_BADGE_LENGTH) return null;

  return withoutWord.toUpperCase();
}
