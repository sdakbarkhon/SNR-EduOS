/**
 * Сроки автозавершения урока. Миграция 225.
 *
 * ПРАВИЛО. Урок закрывается НЕ по звонку, а через несколько минут после него.
 * Всё это время учитель ещё может дописать перекличку; когда запас выходит,
 * pg_cron закрывает урок и ставит «Пропуск без причины» каждому неотмеченному.
 *
 * ПОЧЕМУ ПЯТЬ, А НЕ ПЯТНАДЦАТЬ. Перемена между уроками — десять минут. Запас
 * обязан быть СТРОГО меньше перемены: иначе к звонку на следующий урок
 * предыдущий всё ещё идёт, и его закроет триггер «один активный урок на
 * группу» (миграция 152) — а тот закрывает урок БЕЗ раздачи прогулов.
 * Посещаемость не проставится вовсе: одна беда сменится другой, потише и
 * потому опаснее.
 *
 * Здесь только СЧЁТ времени для интерфейса. Настоящий срок задан в
 * public.fn_auto_end_lessons() — там та же величина, и она главная.
 */
export const AUTO_END_GRACE_MINUTES = 5;

/**
 * КАК УРОК ВЫГЛЯДИТ В РАСПИСАНИИ УЧЕНИКА. 06.09.2026.
 *
 * ═══ ЗАЧЕМ ОДНО ПРАВИЛО ═══════════════════════════════════════════════════
 *
 * Экранов с расписанием у ученика три: главная, день и неделя. Каждый решал
 * сам, и они разошлись: главная приглушала законченный урок, а день и неделя
 * показывали его точно таким же, как ещё не начавшийся. Ребёнок смотрит на
 * список и не понимает, что уже прошло.
 *
 * Здесь решение ОДНО. Как рисовать — дело экрана: у карточки день свои цвета,
 * у чипа недели свои. Но ЧТО рисовать, они спрашивают в одном месте.
 *
 * Порядок важен: идущий урок сильнее «прошедшего» (последний урок дня
 * замирает на «Сейчас»), а «следующий» сильнее обычного.
 */
export type ВидУрокаНаЭкране = "идёт" | "следующий" | "прошёл" | "обычный";

export function видУрокаНаЭкране(
  lesson: { id: string; status?: string | null },
  currentId: string | null | undefined,
  nextId: string | null | undefined,
): ВидУрокаНаЭкране {
  if (currentId && lesson.id === currentId) return "идёт";
  if (nextId && lesson.id === nextId) return "следующий";
  if (lesson.status === "completed") return "прошёл";
  return "обычный";
}

/** Насколько гасить прошедший урок. Одно число на все три экрана. */
export const ПРИГЛУШЕНИЕ_ПРОШЕДШЕГО = 0.6;
